            INC_CNT,
            DEC_CNT,
            RE_CNT,
            CANCL_CNT,
            INC_SPNSR_AMT,
            DEC_SPNSR_AMT,
            CANCL_SPNSR_AMT,
            PAY_RATE,
            SETLE_CD,
            CHURN_12M
        FROM GN_DW.ML.ML_TRAIN_DATA_SPNSR_CHURN_12M;

