	GA_CONV_CNT,
	DAY_OF_WEEK,
	WEEK_OF_YEAR,
	AD_SOURCE_TYPE,
	PAGE_TYPE,
	AD_GROUP_NM,
	GROUP_DIV,
	CREATIVE_TYPE,
	AD_TYPE_NM,
	READ_CNT,
	MEDIA_POTENTIAL_CUST_CNT,
