	DVLP_MEMBER_CNT,
	DVLP_CNT,
	BRDC_AD_VIEW_RT_SRC,
	BRDC_CPC_SRC
) COMMENT='GOLD 광고 팩트 3종(FAP 코어 + FAD 디지털·FAB 방송 위성)을 AD_PERF_DK 로 1:1 pre-join — SV_AD 의 단일 base. PK=AD_PERF_DK(전건 유일, fan-out 0). 위성은 원천유형별 완전분할이라 LEFT JOIN 이 행수를 늘리지 않는다(디지털행=방송컬럼 NULL, 방송행=디지털컬럼 NULL — 결측이 아니라 원천 부재). 존재 이유: semantic view metric 식은 자기 logical table 컬럼만 참조 가능해 개발단가(AD_COST÷CRM_DEV_CNT) 등 cross-satellite 비율을 SV 에서 직접 계산할 수 없다.'
