-- 실행 롤 = ACCOUNTADMIN(ACCOUNT_USAGE · SHOW) · 작성 2026-10-20 O247
-- 설명 = 20_정식산출물/D10_운영매뉴얼.md · 일배치·장애 상세 쿼리는 A6_일배치_장애대응_런북.sql(Q01~Q10)·N04 를 재사용한다.
-- ⚠️ 개인정보 값(이메일)은 출력하지 않는다 — 건수만.

-- Q01 Agent · 기본 버전 (롤백 기준)
SHOW AGENTS IN SCHEMA GN_DW.SERVING;

-- Q02 알림 경로 — 알림 통합(이메일)
SHOW NOTIFICATION INTEGRATIONS;

-- Q03 알림 수신자 건수 (유형별 · 값 미출력)
SELECT COUNT(*) AS N_ALL,
       COUNT_IF(IS_ACTIVE_YN = 'Y') AS N_ACTIVE,
       COUNT_IF(IS_PIPELINE_ADMIN_YN = 'Y') AS N_PIPELINE_ADMIN,
       COUNT_IF(IS_DBT_ALERT_YN = 'Y') AS N_DBT_ALERT
FROM GN_DW.OPS.ALERT_RECIPIENT_CONFIG;

-- Q04 네트워크 정책 (RUNBOOK §8.1 전제)
SHOW NETWORK POLICIES;

-- Q05 보안 감시 — 최근 7일 로그인 실패 · 권한 변경 건수 (RUNBOOK §8.2·§8.3)
SELECT 'LOGIN_FAIL_7D' AS K, COUNT(*) AS N
FROM SNOWFLAKE.ACCOUNT_USAGE.LOGIN_HISTORY
WHERE EVENT_TIMESTAMP >= DATEADD(day, -7, CURRENT_TIMESTAMP())
  AND IS_SUCCESS = 'NO'
UNION ALL
SELECT 'GRANT_REVOKE_7D', COUNT(*)
FROM SNOWFLAKE.ACCOUNT_USAGE.QUERY_HISTORY
WHERE START_TIME >= DATEADD(day, -7, CURRENT_TIMESTAMP())
  AND QUERY_TYPE IN ('GRANT', 'REVOKE');

-- Q06 마스킹 정책 부착 현황 (A8-28 적용 여부 · 실행 전 = 0)
SELECT POLICY_NAME, COUNT(*) AS N_COLUMNS
FROM SNOWFLAKE.ACCOUNT_USAGE.POLICY_REFERENCES
WHERE POLICY_DB = 'GN_DW'
  AND POLICY_KIND = 'MASKING_POLICY'
GROUP BY 1
ORDER BY 1;

-- Q07 Streamlit (RUNBOOK §7 · 기대 = 0)
SHOW STREAMLITS IN DATABASE GN_DW;
