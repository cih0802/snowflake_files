-- N06 비용 산정 · 용량 계획 근거 (D11 모니터링·비용관리 정의서와 공용)
-- 읽기 전용 · env_capture --id N06 로 _ENV/<계정>/N06_*.csv 캡처 · 작성 2026-10-20 O247
-- 실행 롤 = ACCOUNTADMIN(ACCOUNT_USAGE · SHOW) · 쿼리 원형 = cost-intelligence 스킬 references/queries/overview·storage
-- ⚠️ ACCOUNT_USAGE 는 최대 수 시간 지연된다. 당일은 제외한다(< CURRENT_DATE()).
-- ⚠️ 개발계 계정 IW20760 은 2026-10-17 에 재구축됐다 ⇒ 90일 창이라도 실제 이력은 그 이후만 있을 수 있다(Q01 FIRST_DAY 로 확인).

-- Q01 서비스별 크레딧 — 최근 90일 (metering 기준 · 청구 대조용)
SELECT SERVICE_TYPE,
       ROUND(SUM(CREDITS_USED), 2) AS CREDITS,
       ROUND(SUM(CREDITS_USED) / NULLIF(SUM(SUM(CREDITS_USED)) OVER (), 0) * 100, 1) AS PCT,
       MIN(START_TIME)::DATE AS FIRST_DAY,
       MAX(START_TIME)::DATE AS LAST_DAY
FROM SNOWFLAKE.ACCOUNT_USAGE.METERING_HISTORY
WHERE START_TIME >= DATEADD(DAY, -90, CURRENT_DATE())
  AND START_TIME < CURRENT_DATE()
GROUP BY 1
ORDER BY CREDITS DESC;

-- Q02 월별 · 서비스별 크레딧 추세
SELECT DATE_TRUNC('MONTH', START_TIME)::DATE AS MONTH,
       SERVICE_TYPE,
       ROUND(SUM(CREDITS_USED), 2) AS CREDITS
FROM SNOWFLAKE.ACCOUNT_USAGE.METERING_HISTORY
WHERE START_TIME >= DATEADD(DAY, -90, CURRENT_DATE())
  AND START_TIME < CURRENT_DATE()
GROUP BY 1, 2
ORDER BY 1, 3 DESC;

-- Q03 웨어하우스별 크레딧 — 최근 90일 (compute · cloud services 분리)
SELECT WAREHOUSE_NAME,
       ROUND(SUM(CREDITS_USED), 2) AS CREDITS,
       ROUND(SUM(CREDITS_USED_COMPUTE), 2) AS CREDITS_COMPUTE,
       ROUND(SUM(CREDITS_USED_CLOUD_SERVICES), 2) AS CREDITS_CLOUD,
       COUNT(DISTINCT START_TIME::DATE) AS ACTIVE_DAYS
FROM SNOWFLAKE.ACCOUNT_USAGE.WAREHOUSE_METERING_HISTORY
WHERE START_TIME >= DATEADD(DAY, -90, CURRENT_DATE())
  AND START_TIME < CURRENT_DATE()
GROUP BY 1
ORDER BY CREDITS DESC;

-- Q04 일별 총 크레딧 (월 추정의 기준 — 최근 14일 평균을 쓴다)
SELECT START_TIME::DATE AS DAY,
       ROUND(SUM(CREDITS_USED), 2) AS CREDITS
FROM SNOWFLAKE.ACCOUNT_USAGE.METERING_HISTORY
WHERE START_TIME >= DATEADD(DAY, -30, CURRENT_DATE())
  AND START_TIME < CURRENT_DATE()
GROUP BY 1
ORDER BY 1;

-- Q05 AI 도메인별 크레딧 — 최근 90일 (각 도메인의 정본 뷰만 · 합산 안전 · 08_mornitoring/02 §3)
SELECT 'CORTEX CODE' AS DOMAIN, ROUND(SUM(TOKEN_CREDITS), 4) AS CREDITS, COUNT(*) AS EVENTS
FROM SNOWFLAKE.ACCOUNT_USAGE.SNOWFLAKE_COCO_USAGE_HISTORY
WHERE USAGE_TIME >= DATEADD(DAY, -90, CURRENT_DATE())
UNION ALL
SELECT 'SNOWFLAKE INTELLIGENCE', ROUND(SUM(TOKEN_CREDITS), 4), COUNT(*)
FROM SNOWFLAKE.ACCOUNT_USAGE.SNOWFLAKE_INTELLIGENCE_USAGE_HISTORY
WHERE START_TIME >= DATEADD(DAY, -90, CURRENT_DATE())
UNION ALL
SELECT 'CORTEX AGENT', ROUND(SUM(TOKEN_CREDITS), 4), COUNT(*)
FROM SNOWFLAKE.ACCOUNT_USAGE.CORTEX_AGENT_USAGE_HISTORY
WHERE START_TIME >= DATEADD(DAY, -90, CURRENT_DATE())
UNION ALL
SELECT 'AI FUNCTION', ROUND(SUM(TOKEN_CREDITS), 4), COUNT(*)
FROM SNOWFLAKE.ACCOUNT_USAGE.CORTEX_AISQL_USAGE_HISTORY
WHERE USAGE_TIME >= DATEADD(DAY, -90, CURRENT_DATE())
UNION ALL
SELECT 'CORTEX ANALYST', ROUND(SUM(CREDITS), 4), COUNT(*)
FROM SNOWFLAKE.ACCOUNT_USAGE.CORTEX_ANALYST_USAGE_HISTORY
WHERE START_TIME >= DATEADD(DAY, -90, CURRENT_DATE())
ORDER BY CREDITS DESC NULLS LAST;

-- Q06 스토리지 — GN_DW 최근 7일 평균 (GB)
SELECT DATABASE_NAME,
       ROUND(AVG(AVERAGE_DATABASE_BYTES) / POW(1024, 3), 2) AS DB_GB,
       ROUND(AVG(AVERAGE_FAILSAFE_BYTES) / POW(1024, 3), 2) AS FAILSAFE_GB,
       ROUND(AVG(AVERAGE_DATABASE_BYTES + AVERAGE_FAILSAFE_BYTES
                 + COALESCE(AVERAGE_HYBRID_TABLE_STORAGE_BYTES, 0)) / POW(1024, 3), 2) AS TOTAL_GB
FROM SNOWFLAKE.ACCOUNT_USAGE.DATABASE_STORAGE_USAGE_HISTORY
WHERE USAGE_DATE >= DATEADD(DAY, -7, CURRENT_DATE())
  AND USAGE_DATE < CURRENT_DATE()
GROUP BY 1
ORDER BY TOTAL_GB DESC;

