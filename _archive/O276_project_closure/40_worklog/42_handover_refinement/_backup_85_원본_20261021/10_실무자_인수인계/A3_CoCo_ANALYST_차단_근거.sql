-- Q01 CoCo 접근 결정 DB 롤 부여처 (BCR-2445 적용 후 = CORTEX_USER 또는 CORTEX_AGENT_USER · 적용 전 = + COPILOT_USER)
SHOW GRANTS OF DATABASE ROLE SNOWFLAKE.CORTEX_USER;
SHOW GRANTS OF DATABASE ROLE SNOWFLAKE.CORTEX_AGENT_USER;
SHOW GRANTS OF DATABASE ROLE SNOWFLAKE.COPILOT_USER;

-- Q02 차단 대상 후보 — GN_DW_ANALYST 를 받은 사용자·롤 (실시간)
SHOW GRANTS OF ROLE GN_DW_ANALYST;
SHOW GRANTS OF ROLE GN_DW_VIEWER;

-- Q03 CoCo 한도 파라미터 — 계정 기본값
SHOW PARAMETERS LIKE 'CORTEX_CODE%' IN ACCOUNT;

-- Q04 CoCo 사용 실적 — 최근 30일 사용자별 (통합 뷰 · 인터페이스별 뷰와 합산 금지)
SELECT u.NAME AS USER_NAME,
       COUNT(*) AS N_REQUEST,
       ROUND(SUM(h.TOKEN_CREDITS), 4) AS CREDITS,
       MIN(h.USAGE_TIME) AS FIRST_T,
       MAX(h.USAGE_TIME) AS LAST_T
FROM SNOWFLAKE.ACCOUNT_USAGE.SNOWFLAKE_COCO_USAGE_HISTORY h
LEFT JOIN SNOWFLAKE.ACCOUNT_USAGE.USERS u
  ON u.USER_ID = h.USER_ID
WHERE h.USAGE_TIME > DATEADD(day, -30, CURRENT_TIMESTAMP())
GROUP BY 1
ORDER BY 3 DESC;

-- Q05 Per-user quota (CORTEX CODE 도메인 차단 대안) 존재 여부
SHOW SNOWFLAKE.CORE.QUOTA INSTANCES;
