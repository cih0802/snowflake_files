-- [D2] 대사 — 원천 고유값·채움 = GOLD 고유값·채움 (백필 없음 · 같은 원천이면 같아야 한다)
SELECT 'DIM_CAMPAIGN.CAMPAIGN_TARGET_NAME' AS col, COUNT(DISTINCT CAMPAIGN_TARGET_NAME) AS n_distinct, COUNT(CAMPAIGN_TARGET_NAME) AS n_filled FROM GN_DW.GOLD.DIM_CAMPAIGN
UNION ALL SELECT 'FAP.CMPGN_TYPE1_BSN_NM', COUNT(DISTINCT CMPGN_TYPE1_BSN_NM), COUNT(CMPGN_TYPE1_BSN_NM) FROM GN_DW.GOLD.FACT_AD_PERFORMANCE
UNION ALL SELECT 'FAP.CMPGN_TYPE2_BSN_NM', COUNT(DISTINCT CMPGN_TYPE2_BSN_NM), COUNT(CMPGN_TYPE2_BSN_NM) FROM GN_DW.GOLD.FACT_AD_PERFORMANCE
UNION ALL SELECT 'FAP.CMPGN_TY_NM', COUNT(DISTINCT CMPGN_TY_NM), COUNT(CMPGN_TY_NM) FROM GN_DW.GOLD.FACT_AD_PERFORMANCE
UNION ALL SELECT 'DIM_SPONSORSHIP.DNTN_TY_CD', COUNT(DISTINCT DNTN_TY_CD), COUNT(DNTN_TY_CD) FROM GN_DW.GOLD.DIM_SPONSORSHIP
UNION ALL SELECT 'FER.BDGT_ITEM_NM', COUNT(DISTINCT BDGT_ITEM_NM), COUNT(BDGT_ITEM_NM) FROM GN_DW.GOLD.FACT_EXPENSE_RESOLUTION
UNION ALL SELECT 'DIM_MEMBER.REGIST_DEPT_CD', COUNT(DISTINCT REGIST_DEPT_CD), COUNT(REGIST_DEPT_CD) FROM GN_DW.GOLD.DIM_MEMBER
UNION ALL SELECT 'FME.REGIST_DEPT_CD(STOP)', COUNT(DISTINCT REGIST_DEPT_CD), COUNT(REGIST_DEPT_CD) FROM GN_DW.GOLD.FACT_MEMBER_EVENT WHERE EVENT_TYPE = 'STOP'
UNION ALL SELECT 'FMD.SND_FRST_SPNSR', COUNT(DISTINCT SND_FRST_SPNSR), COUNT(SND_FRST_SPNSR) FROM GN_DW.GOLD.FACT_MESSAGE_DISPATCH
UNION ALL SELECT 'FMD.SND_CHILD_DTL_NM', COUNT(DISTINCT SND_CHILD_DTL_NM), COUNT(SND_CHILD_DTL_NM) FROM GN_DW.GOLD.FACT_MESSAGE_DISPATCH
UNION ALL SELECT 'FMD.SND_NATION_NM', COUNT(DISTINCT SND_NATION_NM), COUNT(SND_NATION_NM) FROM GN_DW.GOLD.FACT_MESSAGE_DISPATCH
UNION ALL SELECT 'FMD.SND_BPLC_KOR_NM', COUNT(DISTINCT SND_BPLC_KOR_NM), COUNT(SND_BPLC_KOR_NM) FROM GN_DW.GOLD.FACT_MESSAGE_DISPATCH
ORDER BY 1;
