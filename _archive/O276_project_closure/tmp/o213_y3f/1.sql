CREATE TABLE IF NOT EXISTS GN_DW.SILVER.BIGQUERY_SESSION AS
select
    TO_DATE(EVENT_DATE, 'YYYYMMDD') as EVENT_DT,
    CAST(USER_PSEUDO_ID AS VARCHAR(200)) as USER_PSEUDO_ID,
    try_cast(EP_GA_SESSION_ID as number) as BIGQUERY_SESSION_ID,
    USER_PSEUDO_ID || '-' || EP_GA_SESSION_ID as BIGQUERY_SESSION_KEY,
    max(try_cast(EP_GA_SESSION_NUMBER as number)) as BIGQUERY_SESSION_NUMBER,
    min(TO_TIMESTAMP_NTZ(EVENT_TIMESTAMP / 1000000)) as SESSION_START_TS,
    CAST(NULL AS VARCHAR) as PLATFORM, CAST(NULL AS VARCHAR) as DEVICE_CATEGORY, CAST(NULL AS VARCHAR) as DEVICE_OPERATING_SYSTEM,
    CAST(NULL AS VARCHAR) as DEVICE_WEB_INFO_BROWSER, CAST(NULL AS VARCHAR) as DEVICE_LANGUAGE, CAST(NULL AS VARCHAR) as DEVICE_MOBILE_BRAND_NAME,
    CAST(NULL AS VARCHAR) as DEVICE_WEB_INFO_HOSTNAME, CAST(NULL AS VARCHAR) as GEO_CONTINENT, CAST(NULL AS VARCHAR) as GEO_SUB_CONTINENT,
    CAST(NULL AS VARCHAR) as GEO_COUNTRY, CAST(NULL AS VARCHAR) as GEO_METRO, CAST(NULL AS VARCHAR) as TS_SOURCE, CAST(NULL AS VARCHAR) as TS_MEDIUM,
    CAST(NULL AS VARCHAR) as CTS_MANUAL_MEDIUM, CAST(NULL AS VARCHAR) as EP_MEDIUM, CAST(NULL AS VARCHAR) as STSLC_CRC_DEFAULT_CHANNEL_GROUP,
    CAST(NULL AS VARCHAR) as STSLC_CRC_PRIMARY_CHANNEL_GROUP, CAST(NULL AS VARCHAR) as STSLC_CRC_SOURCE_PLATFORM,
    CAST(NULL AS VARCHAR) as STSLC_GAC_CAMPAIGN_NAME, CAST(NULL AS VARCHAR) as STSLC_GAC_AD_GROUP_NAME,
    CAST(NULL AS VARCHAR) as UP_MEMBER_TYPE, CAST(NULL AS VARCHAR) as UP_DONOR_TYPE, CAST(NULL AS VARCHAR) as UP_DONATION_TYPE,
    CAST(NULL AS VARCHAR) as UP_BIZ_TYPE, CAST(NULL AS VARCHAR) as UP_LOGIN_STATUS, CAST(NULL AS VARCHAR) as EP_PAYMENT_TYPE,
    count(*) as EVENT_CNT,
    count_if(EVENT_NAME = 'page_view') as PAGE_VIEW_CNT,
    iff(max(iff(EP_SESSION_ENGAGED = '1', 1, 0)) = 1, true, false) as IS_ENGAGED,
    sum(try_cast(EP_ENGAGEMENT_TIME_MSEC as number)) as ENGAGEMENT_TIME_MSEC,
    CAST('BIGQUERY' AS VARCHAR(16777216)) as DW_SOURCE_SYSTEM,
    CAST('SILVER.BIGQUERY_REFINED_DATA' AS VARCHAR(16777216)) as DW_SOURCE_TABLE,
    CAST(CURRENT_TIMESTAMP() AS TIMESTAMP_NTZ) as DW_LOAD_TS,
    CAST(CURRENT_TIMESTAMP() AS TIMESTAMP_NTZ) as DW_UPDATE_TS,
    CAST(NULL AS VARCHAR) as DW_BATCH_ID
from GN_DW.SILVER.BIGQUERY_REFINED_DATA
group by EVENT_DATE, USER_PSEUDO_ID, EP_GA_SESSION_ID
limit 0