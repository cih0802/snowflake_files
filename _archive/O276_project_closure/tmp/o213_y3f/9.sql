CREATE TABLE IF NOT EXISTS GN_DW.GOLD.FACT_EXPENSE_RESOLUTION
COMMENT = '지출결의 팩트. [Grain: RESOLUTION_NO × ROW_SEQ (원천 1행)]. [주의: FACT_BUDGET·FACT_BUDGET_YEARLY 와 합산 금지 · 부서별 지출의 유일 원천]. [원천: ERP → SILVER.ERP_EXPENSE_RESOLUTION]. 🆕 O213-F'
AS
select
    COALESCE(CASE WHEN WRITE_DATE BETWEEN '1945-01-01' AND '2145-12-31' THEN TRY_TO_NUMBER(TO_CHAR(WRITE_DATE, 'YYYYMMDD')) END, 0) as DATE_SK,
    RESOLUTION_NO, ROW_SEQ, RESOLUTION_YEAR, RESOLUTION_DEPT_NM, EXPS_RESOLUTION_NM, SOURCE_DIV_NM,
    BDGT_UNIT_NM, MOK_NM, DTL_ITEM_NM, SUBDTL_ITEM_NM, FUND_SOURCE_NM, DESCRIPTION, SUM_AMT,
    CAST('ERP' AS VARCHAR) AS DW_SOURCE_SYSTEM,
    CURRENT_TIMESTAMP()::TIMESTAMP_NTZ AS DW_LOAD_TS,
    CURRENT_TIMESTAMP()::TIMESTAMP_NTZ AS DW_UPDATE_TS,
    CAST(NULL AS VARCHAR) AS DW_BATCH_ID
from GN_DW.SILVER.ERP_EXPENSE_RESOLUTION
limit 0
