WITH __cc AS (
  SELECT
    active_spnsr_cnt,
    cmpgn_ctgr_nm,
    has_member_pred,
    mber_no,
    member_churn_grade,
    sponsor_churn_grade,
    stdr_mt,
    member_churn_prob
  FROM GN_DW.SERVING.ML_CHURN_BY_CMPGN_CTGR_V
), base AS (
  SELECT
    __cc.mber_no,
    __cc.member_churn_prob,
    __cc.member_churn_grade,
    __cc.sponsor_churn_grade,
    __cc.active_spnsr_cnt,
    __cc.has_member_pred
  FROM __cc
  WHERE
    __cc.stdr_mt = '202609' AND __cc.cmpgn_ctgr_nm = '고려인캠페인'
), denom AS (
  SELECT
    COUNT(DISTINCT mber_no) AS act,
    COUNT(DISTINCT CASE WHEN has_member_pred THEN mber_no END) AS pred,
    COUNT(DISTINCT CASE WHEN member_churn_grade = '고위험' THEN mber_no END) AS high
  FROM base
)
SELECT
  b.mber_no AS "회원번호",
  ROUND(b.member_churn_prob * 100, 2) AS "회원 중단확률(%)",
  b.member_churn_grade AS "회원 중단위험 등급",
  b.sponsor_churn_grade AS "후원건 이탈위험 등급",
  b.active_spnsr_cnt AS "활동 약정 수(건)",
  d.act AS "활동회원수(명)",
  d.pred AS "회원 단위 예측 대상 회원수(명)",
  d.high AS "중단 고위험 회원수(명)"
FROM base AS b
CROSS JOIN denom AS d
WHERE
  b.member_churn_grade = '고위험'
ORDER BY
  b.member_churn_prob DESC NULLS LAST
LIMIT 10
