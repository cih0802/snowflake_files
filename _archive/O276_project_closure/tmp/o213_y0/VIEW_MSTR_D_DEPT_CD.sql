create or replace view D_DEPT_CD(
	DEPT_ID,
	DEPT_NM,
	DEPT2_ID,
	DEPT3_ID,
	DEPT4_ID,
	DEPT5_ID,
	SORT_ORDR,
	USE_YN,
	ACMSLT_DEPT_YN,
	FST_DE,
	LST_DE,
	WORK_DE
) COMMENT='부서(1레벨 · 상위 2~5 매핑)'
 as
SELECT
  E.DEPT_ID, E.DEPT_NM, D.DEPT_ID AS DEPT2_ID, C.DEPT_ID AS DEPT3_ID,
  B.DEPT_ID AS DEPT4_ID, A.DEPT_ID AS DEPT5_ID,
  E.SORT_ORDR, E.USE_YN, E.ACMSLT_DEPT_YN,
  IFNULL(TO_CHAR(E.FRST_REGIST_DT, 'YYYYMMDD'), '19000101') AS FST_DE,
  IFNULL(TO_CHAR(E.LAST_UPDT_DT,   'YYYYMMDD'), '99991231') AS LST_DE,
  TO_CHAR(CURRENT_DATE(), 'YYYYMMDD') AS WORK_DE
FROM GN_DW.MSTR.D_CM_DEPT_INFO A
JOIN GN_DW.MSTR.D_CM_DEPT_INFO B ON B.ACMSLT_UPPER_DEPT_ID = A.DEPT_ID
JOIN GN_DW.MSTR.D_CM_DEPT_INFO C ON C.ACMSLT_UPPER_DEPT_ID = B.DEPT_ID
JOIN GN_DW.MSTR.D_CM_DEPT_INFO D ON D.ACMSLT_UPPER_DEPT_ID = C.DEPT_ID
JOIN GN_DW.MSTR.D_CM_DEPT_INFO E ON E.ACMSLT_UPPER_DEPT_ID = D.DEPT_ID
WHERE A.UPPER_DEPT_ID = 'ZV000000'
  AND A.USE_YN = 'Y'
  AND C.DEPT_ID != 'ZC000029'
UNION ALL
SELECT 'Z~', '없음', 'Z~', 'Z~', 'Z~', 'Z~', 999, 'Y', 'Y', '20191101', '99991231', TO_CHAR(CURRENT_DATE(), 'YYYYMMDD');