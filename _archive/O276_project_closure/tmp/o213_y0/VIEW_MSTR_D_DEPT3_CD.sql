create or replace view D_DEPT3_CD(
	DEPT3_ID,
	DEPT3_NM,
	DEPT4_ID,
	DEPT5_ID,
	SORT_ORDR,
	USE_YN,
	ACMSLT_DEPT_YN,
	WORK_DE
) COMMENT='실적부서3(3레벨)'
 as
SELECT
  C.DEPT_ID AS DEPT3_ID, C.DEPT_NM AS DEPT3_NM, B.DEPT_ID AS DEPT4_ID, A.DEPT_ID AS DEPT5_ID,
  C.SORT_ORDR, C.USE_YN, C.ACMSLT_DEPT_YN,
  TO_CHAR(CURRENT_DATE(), 'YYYYMMDD') AS WORK_DE
FROM GN_DW.MSTR.D_CM_DEPT_INFO A
JOIN GN_DW.MSTR.D_CM_DEPT_INFO B ON B.ACMSLT_UPPER_DEPT_ID = A.DEPT_ID
JOIN GN_DW.MSTR.D_CM_DEPT_INFO C ON C.ACMSLT_UPPER_DEPT_ID = B.DEPT_ID
WHERE A.UPPER_DEPT_ID = 'ZV000000'
  AND A.USE_YN = 'Y'
  AND C.DEPT_ID != 'ZC000029'
UNION ALL
SELECT 'Z~', '없음', 'Z~', 'Z~', 999, 'Y', 'Y', TO_CHAR(CURRENT_DATE(), 'YYYYMMDD');