create or replace view D_SPNSR_BSNS_V(
	STRD_MT,
	SPNSR_NO,
	SPNSR_BSNS_NO,
	SPNSR_BSNS_ID,
	MBER_NO,
	CMPGN_CD,
	ACMSLT_DEPT_CD,
	JOIN_PATH_CD,
	FRST_RGSTR_ID,
	FST_DE,
	SPNSR_AMT,
	DSC_DE,
	SPNSR_DSCNTC_YN,
	SPNSR_DSCNTC_RSN_CD
) COMMENT='후원·후원사업 결합. DSC_DE 미중단 = 99991231'
 as
SELECT
  TO_CHAR(A.FRST_REGIST_DT, 'YYYYMM')   AS STRD_MT,
  A.SPNSR_NO,
  B.SPNSR_BSNS_NO,
  B.SPNSR_BSNS_ID,
  A.MBER_NO,
  A.CMPGN_CD,
  A.ACMSLT_DEPT_CD,
  A.JOIN_PATH_CD,
  A.FRST_RGSTR_ID,
  TO_CHAR(A.FRST_REGIST_DT, 'YYYYMMDD') AS FST_DE,
  B.SPNSR_AMT,
  IFNULL(B.SPNSR_DSCNTC_DE, '99991231') AS DSC_DE,
  B.SPNSR_DSCNTC_YN,
  B.SPNSR_DSCNTC_RSN_CD
FROM GN_DW.BRONZE_CRM.TM_MM_FDRM_MBER_SPNSR A
JOIN GN_DW.BRONZE_CRM.TM_MM_FDRM_MBER_SPNSR_BSNS B
  ON A.SPNSR_NO = B.SPNSR_NO;