import io
P = "/workspace/scripts/handoff_ddl_gate.py"
s = io.open(P, encoding="utf-8").read()
a = s.index("STALE_TOKENS = [")
b = s.index("]\n# 과거 실측 기록", a)
body = s[a:b]
old_gen = '''    # 🆕 [2026-10-16] 기준값 한 세대 더 — BRONZE_ERP.SYNC_ERR_INFO 신규(원천 12번) ⇒ **총계 81 · 브론즈 65 · ERP 3**.
    ("80 테이블", ("81",), "이관 총계 (현행 81)"),
    ("80개 테이블", ("81",), "이관 총계 (현행 81)"),
    ("= 80", ("81",), "이관 총계 (현행 81)"),
    ("총계 80", ("81",), "이관 총계 (현행 81)"),
    ("브론즈 64", ("65",), "브론즈 소계 (현행 65)"),
    ("64 테이블", ("65",), "브론즈 소계 (현행 65)"),
    ("64테이블", ("65",), "브론즈 소계 (현행 65)"),
    ("64개 테이블", ("65",), "브론즈 소계 (현행 65)"),
'''
