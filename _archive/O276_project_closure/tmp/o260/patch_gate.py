    #   🔴 현행값(80 · 64)이 2026-10-02 세대와 **같은 수**다 ⇒ 그 세대 토큰(80/64)은 지웠다(현행을 stale 로 잡는다).
    #      대신 2026-10-16 세대(81 · 65 · GSC 3)를 옛 세대로 추가한다.
    ("81 테이블", ("80",), "이관 총계 (현행 80)"),
    ("81개 테이블", ("80",), "이관 총계 (현행 80)"),
    ("= 81", ("80",), "이관 총계 (현행 80)"),
    ("총계 81", ("80",), "이관 총계 (현행 80)"),
    ("브론즈 65", ("64",), "브론즈 소계 (현행 64)"),
