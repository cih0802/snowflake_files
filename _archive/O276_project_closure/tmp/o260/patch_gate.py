body2 = body2.replace('("81",), "이관 총계 (현행 81)"', '("80",), "이관 총계 (현행 80)"')
body2 = body2.replace('("65",), "브론즈 소계 (현행 65)"', '("64",), "브론즈 소계 (현행 64)"')
io.open(P, "w", encoding="utf-8").write(s[:a] + body2 + s[b:])
print("ok", body2.count("현행 80"), body2.count("현행 64"), body2.count("현행 81"), body2.count("현행 65"))
