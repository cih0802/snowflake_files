USE ROLE GN_DW_ADMIN;

-- [1] 정책
CREATE MASKING POLICY IF NOT EXISTS GN_DW.SECURITY.MP_PII_STRING
  AS (VAL STRING) RETURNS STRING ->
  CASE
    WHEN VAL IS NULL THEN NULL
    WHEN IS_ROLE_IN_SESSION('GN_DW_ADMIN') THEN VAL
    ELSE '***'
  END
  COMMENT = 'BRONZE PII 문자열(이름·휴대폰·연락처) · 원문 = GN_DW_ADMIN 이상 · 그 외 *** · A8-28';

-- [2] 부착 — 5 테이블 12 컬럼
ALTER TABLE GN_DW.BRONZE_CRM.TM_PM_SETLE_INFO MODIFY
  COLUMN MBTLNUM           SET MASKING POLICY GN_DW.SECURITY.MP_PII_STRING,
  COLUMN APPLCNT_MBTLNUM   SET MASKING POLICY GN_DW.SECURITY.MP_PII_STRING,
  COLUMN PAYER_NM          SET MASKING POLICY GN_DW.SECURITY.MP_PII_STRING,
  COLUMN APPLCNT_NM        SET MASKING POLICY GN_DW.SECURITY.MP_PII_STRING,
  COLUMN ETC_CTTPC         SET MASKING POLICY GN_DW.SECURITY.MP_PII_STRING,
  COLUMN APPLCNT_ETC_CTTPC SET MASKING POLICY GN_DW.SECURITY.MP_PII_STRING;

ALTER TABLE GN_DW.BRONZE_CRM.TH_PM_SETLE_INFO_HIST MODIFY
  COLUMN PAYER_NM          SET MASKING POLICY GN_DW.SECURITY.MP_PII_STRING,
  COLUMN APPLCNT_NM        SET MASKING POLICY GN_DW.SECURITY.MP_PII_STRING,
  COLUMN ETC_CTTPC         SET MASKING POLICY GN_DW.SECURITY.MP_PII_STRING,
  COLUMN APPLCNT_ETC_CTTPC SET MASKING POLICY GN_DW.SECURITY.MP_PII_STRING;

ALTER TABLE GN_DW.BRONZE_CRM.TM_PM_DNTN_DTLS
  MODIFY COLUMN PAYER_NM SET MASKING POLICY GN_DW.SECURITY.MP_PII_STRING;

ALTER TABLE GN_DW.BRONZE_CRM.TM_PM_MBRFEE_ACMSLT
  MODIFY COLUMN PAYER_NM SET MASKING POLICY GN_DW.SECURITY.MP_PII_STRING;

-- [3] 확인 (읽기)
--   ① 부착 현황 = 12행 기대
SELECT REF_ENTITY_NAME, REF_COLUMN_NAME, POLICY_NAME
FROM TABLE(GN_DW.INFORMATION_SCHEMA.POLICY_REFERENCES(
  POLICY_NAME => 'GN_DW.SECURITY.MP_PII_STRING'))
ORDER BY 1, 2;

--   ② ADMIN 은 원문 · 값은 출력하지 말고 건수만 본다
SELECT COUNT_IF(MBTLNUM = '***') AS MASKED_CNT, COUNT(MBTLNUM) AS NON_NULL_CNT
FROM GN_DW.BRONZE_CRM.TM_PM_SETLE_INFO;          -- 기대 MASKED_CNT = 0
