CREATE OR REPLACE PROCEDURE GN_DW.ML.SP_ONCE_TO_FDRM_CONVERSION_6M("P_STDR_MT" VARCHAR DEFAULT null)
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS CALLER
AS 'BEGIN
    -- 변수 선언
    LET V_STDR_MT VARCHAR := COALESCE(P_STDR_MT, TO_CHAR(DATEADD(MONTH, -1, CURRENT_DATE()), ''YYYYMM''));
    LET V_START_TIME TIMESTAMP_NTZ := CURRENT_TIMESTAMP();
    LET V_PROC_NAME VARCHAR := ''SP_ONCE_TO_FDRM_CONVERSION_6M'';
    
    BEGIN
        -- 웨어하우스 설정 (15분 타임아웃)
        ALTER WAREHOUSE GN_DW_ML_WH SET STATEMENT_TIMEOUT_IN_SECONDS = 900;
        USE WAREHOUSE GN_DW_ML_WH;

        -- =============================================================================
        -- STEP 1: 학습 데이터셋 구성 (회원 단위, 증액 타겟)
        -- =============================================================================
        
        CREATE OR REPLACE TABLE GN_DW.ML.ML_TRAIN_DATA_ONCE_TO_FDRM_CONVERSION_6M AS
        WITH TARGET AS (
            /* ============================================================
               1. 학습 대상 회원 및 전환 여부
               ============================================================ */
            SELECT
                a.ONCE_MBER_NO,
                a.FRST_REGIST_DT AS ONCE_JOIN_DT,
                b.FRST_REGIST_DT AS CONVERSION_DT,
                CASE
                    WHEN b.FRST_REGIST_DT > a.FRST_REGIST_DT
                     AND b.FRST_REGIST_DT <= DATEADD(DAY, 180, a.FRST_REGIST_DT)
                    THEN 1
                    ELSE 0
                END AS CONVERSION_YN, 
                CASE
                    WHEN a.FRST_REGIST_DT <= DATEADD(DAY, -180, CURRENT_DATE()) OR CONVERSION_YN = 1 THEN ''TRAIN''
                    ELSE ''SCORE''
                END 
                AS DATA_TYPE
            FROM GN_DW.BRONZE_CRM.TM_MM_ONCE_MBER_INFO a
            LEFT JOIN GN_DW.BRONZE_CRM.TM_MM_FDRM_MBER_DT_DTLS b
                ON a.ONCE_MBER_NO = b.ONCE_MBER_NO
            /* 가입 후 6개월이 지나 라벨이 확정된 회원만 학습 대상 */
            WHERE 
                a.FRST_REGIST_DT >= ''2024-01-01''
        ),
        /* ============================================================
           2. 월별 스냅샷 생성
              - 가입월 = 1개월차
              - 가입 후 6개월차까지
              - 전환 회원은 전환월까지만
           ============================================================ */
        MONTHLY_TARGET AS (
            SELECT
                T.ONCE_MBER_NO,
                T.ONCE_JOIN_DT,
                T.CONVERSION_DT,
                T.CONVERSION_YN,
                T.DATA_TYPE,
                DATEADD(
                    MONTH,
                    M.MONTH_SEQ,
                    DATE_TRUNC(''MONTH'', T.ONCE_JOIN_DT)
                ) AS STDR_MONTH
            FROM TARGET T
            CROSS JOIN (
                SELECT 0 AS MONTH_SEQ
                UNION ALL SELECT 1
                UNION ALL SELECT 2
                UNION ALL SELECT 3
                UNION ALL SELECT 4
                UNION ALL SELECT 5
            ) M
            WHERE
                /* 가입월 ~ 가입 후 5개월 = 총 6개 월 */
                DATEADD(
                    MONTH,
                    M.MONTH_SEQ,
                    DATE_TRUNC(''MONTH'', T.ONCE_JOIN_DT)
                ) <= TO_DATE(:V_STDR_MT || ''01'', ''YYYYMMDD'')
                
                /* 전환월까지만 생성 */
                AND (
                    T.CONVERSION_DT IS NULL
                    OR
                    DATEADD(
                        MONTH,
                        M.MONTH_SEQ,
                        DATE_TRUNC(''MONTH'', T.ONCE_JOIN_DT)
                    ) <= DATE_TRUNC(''MONTH'', T.CONVERSION_DT)
                )
        ),
        ONCE_BQ AS (
            SELECT DISTINCT
                b.ONCE_MBER_NO,
                a.USER_PSEUDO_ID,
                a.EP_GA_SESSION_ID
            FROM GN_DW.SILVER.BIGQUERY_REFINED_DATA a
            INNER JOIN TARGET b
                ON COALESCE(a.USER_ID, a.UP_MEMBER_ID, a.UP_USER_ID) = b.ONCE_MBER_NO
            ORDER BY
                a.USER_PSEUDO_ID,
                a.EP_GA_SESSION_ID
        ),
        BQ_MONTHLY AS (
            SELECT
                b.ONCE_MBER_NO,
                LEFT(a.EVENT_DATE, 6) AS STDR_MT,
                COUNT(
                    DISTINCT a.USER_PSEUDO_ID || ''_'' || a.EP_GA_SESSION_ID
                ) AS SESSION_CNT,
                COUNT(*) AS BQ_EVENT_CNT,
        
                COUNT(
                    DISTINCT a.EVENT_DATE
                ) AS ACTIVE_DAY_CNT,
                SUM(
                    CASE
                        WHEN a.EVENT_NAME = ''page_view''
                        THEN 1 ELSE 0
                    END
                ) AS PAGE_VIEW_CNT,
                SUM(
                    CASE
                        WHEN a.EVENT_NAME = ''purchase''
                        THEN 1 ELSE 0
                    END
                ) AS PURCHASE_CNT,
                SUM(
                    CASE
                        WHEN a.EVENT_NAME = ''begin_checkout''
                        THEN 1 ELSE 0
                    END
                ) AS BEGIN_CHECKOUT_CNT,
                SUM(
                    CASE
                        WHEN a.EVENT_NAME = ''form_submit''
                        THEN 1 ELSE 0
                    END
                ) AS FORM_SUBMIT_CNT,
                SUM(
                    CASE
                        WHEN a.EVENT_NAME = ''scroll''
                        THEN 1 ELSE 0
                    END
                ) AS SCROLL_CNT,
                SUM(
                    COALESCE(a.EP_ENGAGEMENT_TIME_MSEC, 0)
                ) / 1000.0 AS ENGAGEMENT_TIME_SEC,
                COUNT(
                    DISTINCT CASE
                        WHEN a.EP_SESSION_ENGAGED = ''1''
                        THEN a.USER_PSEUDO_ID || ''_'' || a.EP_GA_SESSION_ID
                    END
                ) AS ENGAGED_SESSION_CNT,
                COUNT(
                    DISTINCT CASE
                        WHEN a.DEVICE_CATEGORY = ''mobile''
                        THEN a.USER_PSEUDO_ID || ''_'' || a.EP_GA_SESSION_ID
                    END
                ) AS MOBILE_SESSION_CNT,
        
                COUNT(
                    DISTINCT CASE
                        WHEN a.DEVICE_CATEGORY = ''desktop''
                        THEN a.USER_PSEUDO_ID || ''_'' || a.EP_GA_SESSION_ID
                    END
                ) AS DESKTOP_SESSION_CNT
            FROM GN_DW.SILVER.BIGQUERY_REFINED_DATA a
            INNER JOIN ONCE_BQ b
                ON a.USER_PSEUDO_ID = b.USER_PSEUDO_ID
               AND a.EP_GA_SESSION_ID = b.EP_GA_SESSION_ID
            GROUP BY
                b.ONCE_MBER_NO,
                LEFT(a.EVENT_DATE, 6)
        )
        SELECT
            a.ONCE_MBER_NO,
            TO_VARCHAR(a.STDR_MONTH, ''YYYYMM'') AS STDR_MT,
            a.ONCE_JOIN_DT,
            a.CONVERSION_DT,
            a.CONVERSION_YN,
            a.DATA_TYPE,
            b.ONCE_DNTN_CNT,
            b.ONCE_DNTN_AMT,
            b.ONCE_DNTN_AVG_AMT, 
            b.ONCE_DNTN_MAX_AMT,
            c.SERVICE_CNT,
            c.CRMN_CNT,
            c.EMAIL_CNT,
            c.MESSAGE_CNT,
            c.PSTMTR_CNT,
            c.EVENT_CNT,
            d.SESSION_CNT,
            d.BQ_EVENT_CNT,
            d.ACTIVE_DAY_CNT,
            d.PAGE_VIEW_CNT,
            d.PURCHASE_CNT,
            d.BEGIN_CHECKOUT_CNT,
            d.FORM_SUBMIT_CNT,
            d.SCROLL_CNT,
            d.ENGAGEMENT_TIME_SEC,
            d.ENGAGED_SESSION_CNT,
            d.MOBILE_SESSION_CNT,
            d.DESKTOP_SESSION_CNT
        FROM MONTHLY_TARGET a
            LEFT OUTER JOIN (
                SELECT
                    ONCE_MBER_NO,
                    TO_VARCHAR(PAY_DE, ''YYYYMM'') AS STDR_MT,
                    -- 기부 횟수
                    COUNT(*) AS ONCE_DNTN_CNT,
                    -- 기부 금액
                    SUM(PAY_AMT) AS ONCE_DNTN_AMT,
                    -- 평균 기부 금액
                    AVG(PAY_AMT) AS ONCE_DNTN_AVG_AMT,
                    -- 최대 기부 금액
                    MAX(PAY_AMT) AS ONCE_DNTN_MAX_AMT
                FROM GN_DW.BRONZE_CRM.TM_PM_DNTN_DTLS
                WHERE USE_YN = ''Y''
                GROUP BY
                    ONCE_MBER_NO,
                    TO_VARCHAR(PAY_DE, ''YYYYMM'')
            ) b ON a.ONCE_MBER_NO = b.ONCE_MBER_NO AND TO_VARCHAR(a.STDR_MONTH, ''YYYYMM'') = b.STDR_MT
            LEFT OUTER JOIN (
                -- 일시후원별 서비스 정보. 정보 있으면 서비스 제공한 것이다. 이메일, 메시지의 경우 
                SELECT
                    MBER_NO,
                    LEFT(SVR_DT, 6) AS STDR_MT,
                    /* 전체 서비스 제공 건수 */
                    COUNT(*) AS SERVICE_CNT,
                    /* SVC_TYPE별 제공 건수 */
                    SUM(CASE WHEN SVC_TYPE = ''행사'' THEN 1 ELSE 0 END) AS CRMN_CNT,
                    SUM(CASE WHEN SVC_TYPE = ''이메일'' THEN 1 ELSE 0 END) AS EMAIL_CNT,
                    SUM(CASE WHEN SVC_TYPE = ''메세지'' THEN 1 ELSE 0 END) AS MESSAGE_CNT,
                    SUM(CASE WHEN SVC_TYPE = ''우편물'' THEN 1 ELSE 0 END) AS PSTMTR_CNT,
                    SUM(CASE WHEN SVC_TYPE = ''이벤트'' THEN 1 ELSE 0 END) AS EVENT_CNT
                FROM GN_DW.ML.MBER_SERVICE_INFO
                WHERE SVR_DT IS NOT NULL
                GROUP BY
                    MBER_NO,
                    LEFT(SVR_DT, 6)
            ) c ON a.ONCE_MBER_NO = c.MBER_NO AND TO_VARCHAR(a.STDR_MONTH, ''YYYYMM'') = c.STDR_MT
            LEFT OUTER JOIN BQ_MONTHLY d ON a.ONCE_MBER_NO = d.ONCE_MBER_NO AND TO_VARCHAR(a.STDR_MONTH, ''YYYYMM'') = d.STDR_MT
        ORDER BY
            a.ONCE_MBER_NO,
            TO_VARCHAR(a.STDR_MONTH, ''YYYYMM'');

        -- =============================================================================
        -- STEP 2: 학습용 뷰 + 모델 학습
        -- =============================================================================
        CREATE OR REPLACE VIEW GN_DW.ML.V_TRAIN_ONCE_CONVERSION AS
        SELECT
            -- 기부 피처
            COALESCE(ONCE_DNTN_CNT, 0)       AS ONCE_DNTN_CNT,
            COALESCE(ONCE_DNTN_AMT, 0)       AS ONCE_DNTN_AMT,
            COALESCE(ONCE_DNTN_AVG_AMT, 0)   AS ONCE_DNTN_AVG_AMT,
            COALESCE(ONCE_DNTN_MAX_AMT, 0)   AS ONCE_DNTN_MAX_AMT,
            -- 서비스 피처
            COALESCE(SERVICE_CNT, 0)          AS SERVICE_CNT,
            COALESCE(CRMN_CNT, 0)            AS CRMN_CNT,
            COALESCE(EMAIL_CNT, 0)           AS EMAIL_CNT,
            COALESCE(MESSAGE_CNT, 0)         AS MESSAGE_CNT,
            COALESCE(PSTMTR_CNT, 0)          AS PSTMTR_CNT,
            COALESCE(EVENT_CNT, 0)           AS EVENT_CNT,
            -- 웹 행동 피처
            COALESCE(SESSION_CNT, 0)          AS SESSION_CNT,
            COALESCE(BQ_EVENT_CNT, 0)        AS BQ_EVENT_CNT,
            COALESCE(ACTIVE_DAY_CNT, 0)      AS ACTIVE_DAY_CNT,
            COALESCE(PAGE_VIEW_CNT, 0)       AS PAGE_VIEW_CNT,
            COALESCE(PURCHASE_CNT, 0)        AS PURCHASE_CNT,
            COALESCE(BEGIN_CHECKOUT_CNT, 0)  AS BEGIN_CHECKOUT_CNT,
            COALESCE(FORM_SUBMIT_CNT, 0)     AS FORM_SUBMIT_CNT,
            COALESCE(SCROLL_CNT, 0)          AS SCROLL_CNT,
            COALESCE(ENGAGEMENT_TIME_SEC, 0) AS ENGAGEMENT_TIME_SEC,
            COALESCE(ENGAGED_SESSION_CNT, 0) AS ENGAGED_SESSION_CNT,
            COALESCE(MOBILE_SESSION_CNT, 0)  AS MOBILE_SESSION_CNT,
            COALESCE(DESKTOP_SESSION_CNT, 0) AS DESKTOP_SESSION_CNT,
            -- 타겟
            CONVERSION_YN
        FROM GN_DW.ML.ML_TRAIN_DATA_ONCE_TO_FDRM_CONVERSION_6M;
      
       -- =============================================================================
        -- STEP 4: 예측 실행 (테이블 없으면 생성+COMMENT, 있으면 DELETE 후 INSERT)
        -- =============================================================================
        CREATE OR REPLACE SNOWFLAKE.ML.CLASSIFICATION GN_DW.ML.ONCE_TO_FDRM_CLASSIFIER(
            INPUT_DATA => SYSTEM$REFERENCE(''VIEW'', ''GN_DW.ML.V_TRAIN_ONCE_CONVERSION''),
            TARGET_COLNAME => ''CONVERSION_YN'',
            CONFIG_OBJECT => {''evaluate'': TRUE}
        );
        
        CREATE TABLE IF NOT EXISTS GN_DW.ML.ML_RST_DATA_ONCE_CONVERSION (
            STDR_MT VARCHAR COMMENT ''기준월 (YYYYMM)'',
            ONCE_MBER_NO VARCHAR COMMENT ''회원번호'',
            -- CONVERSION_YN VARCHAR COMMENT ''회원 전환여부'',
            -- DATA_TYPE VARCHAR COMMENT ''데이터유형'',
            PREDICT VARIANT COMMENT ''예측결과''
        )
        COMMENT = ''일시회원 향후 6개월 내 전환 가능성 예측 결과'';
        
        -- 기존 동일 STDR_MT 데이터 삭제
        EXECUTE IMMEDIATE ''DELETE FROM GN_DW.ML.ML_RST_DATA_ONCE_CONVERSION WHERE STDR_MT = '''''' || :V_STDR_MT || '''''''';

        -- 예측 결과 INSERT
        INSERT INTO GN_DW.ML.ML_RST_DATA_ONCE_CONVERSION
        SELECT
            :V_STDR_MT,
            t.ONCE_MBER_NO,
            -- t.CONVERSION_YN,
            -- t.DATA_TYPE,
            pred.PREDICT
        FROM GN_DW.ML.ML_TRAIN_DATA_ONCE_TO_FDRM_CONVERSION_6M t,
        LATERAL (
            SELECT
                GN_DW.ML.ONCE_TO_FDRM_CLASSIFIER!PREDICT(
                    INPUT_DATA => OBJECT_CONSTRUCT(
                        ''ONCE_DNTN_CNT'',       COALESCE(t.ONCE_DNTN_CNT, 0),
                        ''ONCE_DNTN_AMT'',       COALESCE(t.ONCE_DNTN_AMT, 0),
                        ''ONCE_DNTN_AVG_AMT'',   COALESCE(t.ONCE_DNTN_AVG_AMT, 0),
                        ''ONCE_DNTN_MAX_AMT'',   COALESCE(t.ONCE_DNTN_MAX_AMT, 0),
                        ''SERVICE_CNT'',         COALESCE(t.SERVICE_CNT, 0),
                        ''CRMN_CNT'',            COALESCE(t.CRMN_CNT, 0),
                        ''EMAIL_CNT'',           COALESCE(t.EMAIL_CNT, 0),
                        ''MESSAGE_CNT'',         COALESCE(t.MESSAGE_CNT, 0),
                        ''PSTMTR_CNT'',          COALESCE(t.PSTMTR_CNT, 0),
                        ''EVENT_CNT'',           COALESCE(t.EVENT_CNT, 0),
                        ''SESSION_CNT'',         COALESCE(t.SESSION_CNT, 0),
                        ''BQ_EVENT_CNT'',        COALESCE(t.BQ_EVENT_CNT, 0),
                        ''ACTIVE_DAY_CNT'',      COALESCE(t.ACTIVE_DAY_CNT, 0),
                        ''PAGE_VIEW_CNT'',       COALESCE(t.PAGE_VIEW_CNT, 0),
                        ''PURCHASE_CNT'',        COALESCE(t.PURCHASE_CNT, 0),
                        ''BEGIN_CHECKOUT_CNT'',  COALESCE(t.BEGIN_CHECKOUT_CNT, 0),
                        ''FORM_SUBMIT_CNT'',     COALESCE(t.FORM_SUBMIT_CNT, 0),
                        ''SCROLL_CNT'',          COALESCE(t.SCROLL_CNT, 0),
                        ''ENGAGEMENT_TIME_SEC'', COALESCE(t.ENGAGEMENT_TIME_SEC, 0),
                        ''ENGAGED_SESSION_CNT'', COALESCE(t.ENGAGED_SESSION_CNT, 0),
                        ''MOBILE_SESSION_CNT'',  COALESCE(t.MOBILE_SESSION_CNT, 0),
                        ''DESKTOP_SESSION_CNT'', COALESCE(t.DESKTOP_SESSION_CNT, 0)
                    )
                ) AS PREDICT
        ) pred
        WHERE t.DATA_TYPE = ''SCORE'';

        -- 성공 로그 기록
        INSERT INTO GN_DW.ML.ML_PROCEDURE_LOG (PROC_NAME, STDR_MT, START_TIME, END_TIME, DURATION_SEC, STATUS, ERROR_MSG)
        SELECT 
            :V_PROC_NAME,
            :V_STDR_MT,
            :V_START_TIME,
            CURRENT_TIMESTAMP(),
            DATEDIFF(''SECOND'', :V_START_TIME, CURRENT_TIMESTAMP()),
            ''SUCCESS'',
            NULL;
        
        RETURN ''SUCCESS: STDR_MT='' || :V_STDR_MT;
    EXCEPTION
        WHEN OTHER THEN
            LET V_ERR_MSG VARCHAR := SQLERRM;
            -- 실패 로그 기록
            INSERT INTO GN_DW.ML.ML_PROCEDURE_LOG (PROC_NAME, STDR_MT, START_TIME, END_TIME, DURATION_SEC, STATUS, ERROR_MSG)
            SELECT 
                :V_PROC_NAME,
                :V_STDR_MT,
                :V_START_TIME,
                CURRENT_TIMESTAMP(),
                DATEDIFF(''SECOND'', :V_START_TIME, CURRENT_TIMESTAMP()),
                ''FAILED'',
                :V_ERR_MSG;

            RETURN ''FAILED: '' || :V_ERR_MSG;
    END;
END';
CREATE OR REPLACE PROCEDURE GN_DW.ML.SP_SPNSR_CHURN_12M_PREDICT("P_STDR_MT" VARCHAR DEFAULT null)
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS CALLER
AS 'BEGIN
    -- 변수 선언
    LET V_STDR_MT VARCHAR := COALESCE(P_STDR_MT, TO_CHAR(DATEADD(MONTH, -1, CURRENT_DATE()), ''YYYYMM''));
    LET V_TRAIN_END VARCHAR := TO_CHAR(DATEADD(MONTH, -12, TO_DATE(:V_STDR_MT || ''01'', ''YYYYMMDD'')), ''YYYYMM'');
    LET V_START_TIME TIMESTAMP_NTZ := CURRENT_TIMESTAMP();
    LET V_PROC_NAME VARCHAR := ''SP_SPNSR_CHURN_12M_PREDICT'';

    BEGIN
        -- 웨어하우스 설정 (15분 타임아웃)
        ALTER WAREHOUSE GN_DW_ML_WH SET STATEMENT_TIMEOUT_IN_SECONDS = 900;
        USE WAREHOUSE GN_DW_ML_WH;

        -- =============================================================================
        -- STEP 1: 학습 데이터셋 구성
        -- 건수 많아서 분기별.....
        -- =============================================================================
        EXECUTE IMMEDIATE ''
        CREATE OR REPLACE TABLE GN_DW.ML.ML_TRAIN_DATA_SPNSR_CHURN_12M AS
        WITH 
        CMPGN_CTGR AS (
            SELECT DISTINCT CMPGN_CTGR_CD
            FROM GN_DW.BRONZE_CRM.TM_CM_CMPGN_MNG
            WHERE CMPGN_CTGR_CD IS NOT NULL
        ),
        DVLP_FEATURES AS (
            SELECT 
                d.STDR_MT,
                d.MBER_NO,
                d.SPNSR_BSNS_ID,
                d.SPNSR_BSNS_NO,
                d.CMPGN_CTGR_CD,
                d.STDR_MT_DVLP_DIV_CD,
                d.STDR_MT_SPNSR_AMT,
                d.NEW_CNT,
                d.INC_CNT,
                d.DEC_CNT,
                d.RE_CNT,
                --d.CANCL_CNT,
                d.CHN_CNT,
                d.NEW_SPNSR_AMT,
                d.INC_SPNSR_AMT,
                d.DEC_SPNSR_AMT,
                d.CANCL_SPNSR_AMT,
                DATEDIFF(''''MONTH'''', TO_DATE(d.FIRST_OCCRRNC_DE, ''''YYYYMMDD''''), TO_DATE(d.STDR_MT || ''''01'''', ''''YYYYMMDD'''')) AS TENURE_MONTHS
            FROM GN_DW.ML.MONTHLY_SPNSR_DVLP_AMT d
            JOIN CMPGN_CTGR c ON d.CMPGN_CTGR_CD = c.CMPGN_CTGR_CD
            WHERE d.STDR_MT_DVLP_DIV_CD NOT IN (''''5'''')
              AND d.STDR_MT BETWEEN ''''202301'''' AND '''''' || :V_TRAIN_END || ''''''
              -- AND RIGHT(d.STDR_MT, 2) IN (''''01'''', ''''04'''', ''''07'''', ''''10'''')
        ),
        CHURN_EVENTS AS (
            SELECT 
                MBER_NO,
                SPNSR_BSNS_ID,
                SPNSR_BSNS_NO,
                STDR_MT AS CHURN_MT
            FROM GN_DW.ML.MONTHLY_SPNSR_DVLP_AMT
            WHERE STDR_MT_DVLP_DIV_CD = ''''5''''
        ),
        PAY_FEATURES AS (
            SELECT 
                MBER_NO,
                SPNSR_BSNS_ID,
                SPNSR_BSNS_NO,
                LEFT(MBRFEE_MT, 6) AS STDR_MT,
                COUNT(*) AS PAY_CNT,
                SUM(CASE WHEN PAY_SUC_STATUS = ''''Y'''' THEN 1 ELSE 0 END) AS PAY_SUC_CNT,
                DIV0NULL(SUM(CASE WHEN PAY_SUC_STATUS = ''''Y'''' THEN 1 ELSE 0 END), COUNT(*)) AS PAY_RATE
            FROM GN_DW.ML.MBRFEE_PAY_DTLS
            GROUP BY MBER_NO, SPNSR_BSNS_ID, SPNSR_BSNS_NO, LEFT(MBRFEE_MT, 6)
        ),
        SETLE_FEATURES AS (
            SELECT 
                MBER_NO,
                STDR_MT,
                STDR_MT_SETLE_CD
            FROM GN_DW.ML.MBER_MONTHLY_SETLE_INFO
        ),
        CHURN_FLAG AS (
            SELECT 
                f.MBER_NO,
                f.SPNSR_BSNS_ID,
                f.SPNSR_BSNS_NO,
                f.STDR_MT,
                MAX(CASE WHEN ce.CHURN_MT IS NOT NULL THEN 1 ELSE 0 END) AS CHURN_12M
            FROM DVLP_FEATURES f
            LEFT JOIN CHURN_EVENTS ce
                ON ce.MBER_NO = f.MBER_NO
               AND ce.SPNSR_BSNS_ID = f.SPNSR_BSNS_ID
               AND ce.SPNSR_BSNS_NO = f.SPNSR_BSNS_NO
               AND ce.CHURN_MT > f.STDR_MT
               AND ce.CHURN_MT <= TO_CHAR(DATEADD(MONTH, 12, TO_DATE(f.STDR_MT || ''''01'''', ''''YYYYMMDD'''')), ''''YYYYMM'''')
            GROUP BY f.MBER_NO, f.SPNSR_BSNS_ID, f.SPNSR_BSNS_NO, f.STDR_MT
        )
        SELECT 
            f.STDR_MT,
            f.MBER_NO,
            f.SPNSR_BSNS_ID,
            f.SPNSR_BSNS_NO,
            f.CMPGN_CTGR_CD,
            f.STDR_MT_SPNSR_AMT,
            f.TENURE_MONTHS,
            f.CHN_CNT,
            f.INC_CNT,
            f.DEC_CNT, 
            f.RE_CNT,
            -- f.CANCL_CNT,
            f.INC_SPNSR_AMT,
            f.DEC_SPNSR_AMT,
            -- f.CANCL_SPNSR_AMT,
            COALESCE(p.PAY_RATE, 1) AS PAY_RATE,
            COALESCE(s.STDR_MT_SETLE_CD, ''''UNKNOWN'''') AS SETLE_CD,
            COALESCE(cf.CHURN_12M, 0) AS CHURN_12M
        FROM DVLP_FEATURES f
        LEFT JOIN PAY_FEATURES p 
            ON f.MBER_NO = p.MBER_NO 
           AND f.SPNSR_BSNS_ID = p.SPNSR_BSNS_ID
           AND f.SPNSR_BSNS_NO = p.SPNSR_BSNS_NO
           AND f.STDR_MT = p.STDR_MT
        LEFT JOIN SETLE_FEATURES s
            ON f.MBER_NO = s.MBER_NO
           AND f.STDR_MT = s.STDR_MT
        LEFT JOIN CHURN_FLAG cf
            ON f.MBER_NO = cf.MBER_NO
           AND f.SPNSR_BSNS_ID = cf.SPNSR_BSNS_ID
           AND f.SPNSR_BSNS_NO = cf.SPNSR_BSNS_NO
           AND f.STDR_MT = cf.STDR_MT
        '';

        -- =============================================================================
        -- STEP 2: 학습용 뷰 생성 + 모델 학습
        -- =============================================================================
        CREATE OR REPLACE VIEW GN_DW.ML.ML_TRAIN_DATA_SPNSR_CHURN_12M_V AS
        SELECT 
            CMPGN_CTGR_CD,
            STDR_MT_SPNSR_AMT,
            TENURE_MONTHS,
            CHN_CNT,
            INC_CNT,
            DEC_CNT,
            RE_CNT,
            -- CANCL_CNT,
            INC_SPNSR_AMT,
            DEC_SPNSR_AMT,
            -- CANCL_SPNSR_AMT,
            PAY_RATE,
            SETLE_CD,
            CHURN_12M
        FROM GN_DW.ML.ML_TRAIN_DATA_SPNSR_CHURN_12M;

        CREATE OR REPLACE SNOWFLAKE.ML.CLASSIFICATION GN_DW.ML.SPNSR_CHURN_CLASSIFIER_MODEL(
            INPUT_DATA => SYSTEM$REFERENCE(''VIEW'', ''GN_DW.ML.ML_TRAIN_DATA_SPNSR_CHURN_12M_V''),
            TARGET_COLNAME => ''CHURN_12M'',
            CONFIG_OBJECT => {''ON_ERROR'': ''SKIP''}
        );

        -- =============================================================================
        -- STEP 3: 예측 데이터 구성 (현재 활성 후원건)
        -- =============================================================================
        EXECUTE IMMEDIATE ''
        CREATE OR REPLACE TABLE GN_DW.ML.ML_TRAIN_DATA_ACT_SPNSR_CHURN_12M AS
        WITH 
        CMPGN_CTGR AS (
            SELECT DISTINCT CMPGN_CTGR_CD
            FROM GN_DW.BRONZE_CRM.TM_CM_CMPGN_MNG
            WHERE CMPGN_CTGR_CD IS NOT NULL
        ),
        CURRENT_ACTIVE AS (
            SELECT
                d.STDR_MT,
                d.MBER_NO,
                d.SPNSR_BSNS_ID,
                d.SPNSR_BSNS_NO,
                d.CMPGN_CTGR_CD,
                d.STDR_MT_SPNSR_AMT,
                DATEDIFF(''''MONTH'''', TO_DATE(d.FIRST_OCCRRNC_DE, ''''YYYYMMDD''''), TO_DATE(d.STDR_MT || ''''01'''', ''''YYYYMMDD'''')) AS TENURE_MONTHS,
                d.CHN_CNT,
                d.INC_CNT,
                d.DEC_CNT,
                d.RE_CNT,
                -- d.CANCL_CNT,
                d.INC_SPNSR_AMT,
                d.DEC_SPNSR_AMT
                -- d.CANCL_SPNSR_AMT
            FROM GN_DW.ML.MONTHLY_SPNSR_DVLP_AMT d
            JOIN CMPGN_CTGR c ON d.CMPGN_CTGR_CD = c.CMPGN_CTGR_CD
            WHERE d.STDR_MT = '''''' || :V_STDR_MT || ''''''
              AND d.STDR_MT_DVLP_DIV_CD NOT IN (''''5'''')
        ),
        PAY_FEATURES AS (
            SELECT 
                MBER_NO,
                SPNSR_BSNS_ID,
                DIV0NULL(SUM(CASE WHEN PAY_SUC_STATUS = ''''Y'''' THEN 1 ELSE 0 END), COUNT(*)) AS PAY_RATE
            FROM GN_DW.ML.MBRFEE_PAY_DTLS
            WHERE LEFT(MBRFEE_MT, 6) = '''''' || :V_STDR_MT || ''''''
            GROUP BY MBER_NO, SPNSR_BSNS_ID
        ),
        SETLE_FEATURES AS (
            SELECT MBER_NO, STDR_MT_SETLE_CD
            FROM GN_DW.ML.MBER_MONTHLY_SETLE_INFO
            WHERE STDR_MT = '''''' || :V_STDR_MT || ''''''
        )
        SELECT 
            a.STDR_MT,
            a.MBER_NO,
            a.SPNSR_BSNS_ID,
            a.SPNSR_BSNS_NO,
            a.CMPGN_CTGR_CD,
            a.STDR_MT_SPNSR_AMT,
            a.TENURE_MONTHS,
            a.CHN_CNT,
            a.INC_CNT,
            a.DEC_CNT,
            a.RE_CNT,
            -- a.CANCL_CNT,
            a.INC_SPNSR_AMT,
            a.DEC_SPNSR_AMT,
            -- a.CANCL_SPNSR_AMT,
            COALESCE(p.PAY_RATE, 1) AS PAY_RATE,
            COALESCE(s.STDR_MT_SETLE_CD, ''''UNKNOWN'''') AS SETLE_CD
        FROM CURRENT_ACTIVE a
        LEFT JOIN PAY_FEATURES p 
            ON a.MBER_NO = p.MBER_NO AND a.SPNSR_BSNS_ID = p.SPNSR_BSNS_ID
        LEFT JOIN SETLE_FEATURES s
            ON a.MBER_NO = s.MBER_NO
        '';

        -- =============================================================================
        -- STEP 4: 예측 실행 (테이블 없으면 생성+COMMENT, 있으면 DELETE 후 INSERT)
        -- =============================================================================
        -- 테이블 존재 여부 확인 후 생성 또는 DELETE+INSERT
        CREATE TABLE IF NOT EXISTS GN_DW.ML.ML_RST_DATA_SPNSR_CHURN_12M (
            STDR_MT VARCHAR COMMENT ''기준월 (YYYYMM)'',
            MBER_NO VARCHAR COMMENT ''회원번호'',
            SPNSR_BSNS_ID VARCHAR COMMENT ''후원사업ID'',
            SPNSR_BSNS_NO VARCHAR COMMENT ''후원사업번호'',
            CMPGN_CTGR_CD VARCHAR COMMENT ''캠페인 카테고리 코드'',
            -- STDR_MT_SPNSR_AMT NUMBER COMMENT ''기준월 후원금액'',
            -- TENURE_MONTHS NUMBER COMMENT ''후원 유지기간 (월)'',
            -- CHN_CNT NUMBER COMMENT ''변경 건수'',
            -- INC_CNT NUMBER COMMENT ''증액 건수'',
            -- DEC_CNT NUMBER COMMENT ''감액 건수'',
            -- RE_CNT NUMBER COMMENT ''재후원 건수'',
            -- CANCL_CNT NUMBER COMMENT ''해지 건수'',
            -- INC_SPNSR_AMT NUMBER COMMENT ''증액 금액'',
            -- DEC_SPNSR_AMT NUMBER COMMENT ''감액 금액'',
            -- CANCL_SPNSR_AMT NUMBER COMMENT ''해지 금액'',
            -- PAY_RATE FLOAT COMMENT ''납입 성공률'',
            -- SETLE_CD VARCHAR COMMENT ''결제수단코드'',
            PREDICTION VARIANT COMMENT ''예측 결과 (VARIANT: probability, class 포함)''
        )
        COMMENT = ''후원건(SPNSR_BSNS_NO) 단위 향후 12개월 내 중단확률 예측 결과'';

        -- 기존 동일 STDR_MT 데이터 삭제
        EXECUTE IMMEDIATE ''DELETE FROM GN_DW.ML.ML_RST_DATA_SPNSR_CHURN_12M WHERE STDR_MT = '''''' || :V_STDR_MT || '''''''';

        -- 예측 결과 INSERT
        EXECUTE IMMEDIATE ''
        INSERT INTO GN_DW.ML.ML_RST_DATA_SPNSR_CHURN_12M
        SELECT 
            '''''' || :V_STDR_MT || '''''' AS STDR_MT, 
            MBER_NO,
            SPNSR_BSNS_ID,
            SPNSR_BSNS_NO,
            CMPGN_CTGR_CD,
            GN_DW.ML.SPNSR_CHURN_CLASSIFIER_MODEL!PREDICT(
                INPUT_DATA => OBJECT_CONSTRUCT(
                    ''''CMPGN_CTGR_CD'''', CMPGN_CTGR_CD,
                    ''''STDR_MT_SPNSR_AMT'''', STDR_MT_SPNSR_AMT,
                    ''''TENURE_MONTHS'''', TENURE_MONTHS,
                    ''''CHN_CNT'''', CHN_CNT,
                    ''''INC_CNT'''', INC_CNT,
                    ''''DEC_CNT'''', DEC_CNT,
                    ''''RE_CNT'''', RE_CNT,
                    -- ''''CANCL_CNT'''', CANCL_CNT,
                    ''''INC_SPNSR_AMT'''', INC_SPNSR_AMT,
                    ''''DEC_SPNSR_AMT'''', DEC_SPNSR_AMT,
                    -- ''''CANCL_SPNSR_AMT'''', CANCL_SPNSR_AMT,
                    ''''PAY_RATE'''', PAY_RATE,
                    ''''SETLE_CD'''', SETLE_CD
                )
            ) AS PREDICTION
        FROM GN_DW.ML.ML_TRAIN_DATA_ACT_SPNSR_CHURN_12M
        '';

        -- 성공 로그 기록
        INSERT INTO GN_DW.ML.ML_PROCEDURE_LOG (PROC_NAME, STDR_MT, START_TIME, END_TIME, DURATION_SEC, STATUS, ERROR_MSG)
        SELECT 
            :V_PROC_NAME,
            :V_STDR_MT,
            :V_START_TIME,
            CURRENT_TIMESTAMP(),
            DATEDIFF(''SECOND'', :V_START_TIME, CURRENT_TIMESTAMP()),
            ''SUCCESS'',
            NULL;

        RETURN ''SUCCESS: STDR_MT='' || :V_STDR_MT || '', TRAIN_END='' || :V_TRAIN_END;

    EXCEPTION
        WHEN OTHER THEN
            LET V_ERR_MSG VARCHAR := SQLERRM;
            -- 실패 로그 기록
            INSERT INTO GN_DW.ML.ML_PROCEDURE_LOG (PROC_NAME, STDR_MT, START_TIME, END_TIME, DURATION_SEC, STATUS, ERROR_MSG)
            SELECT 
                :V_PROC_NAME,
                :V_STDR_MT,
                :V_START_TIME,
                CURRENT_TIMESTAMP(),
                DATEDIFF(''SECOND'', :V_START_TIME, CURRENT_TIMESTAMP()),
                ''FAILED'',
                :V_ERR_MSG;

            RETURN ''FAILED: '' || :V_ERR_MSG;
    END;
END';