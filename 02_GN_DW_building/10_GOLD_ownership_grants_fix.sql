-- 설계(개발계 2026-10-28 실측과 일치)
--   TABLE 소유 = GN_DW_ADMIN (06/08 DDL 생성 · dbt 는 적재만)          개발계 68건
--   VIEW  소유 = GN_DW_DBT   (dbt 가 CREATE OR REPLACE VIEW 로 재생성)   개발계 19건
--   GN_DW_DBT · GN_DW_ENGINEER = TABLE SELECT·INSERT·UPDATE·DELETE·TRUNCATE / VIEW SELECT / SCHEMA USAGE·CREATE VIEW
--   GN_DW_ANALYST · GN_DW_VIEWER · GN_DW_SERVICE = SCHEMA USAGE / TABLE·VIEW SELECT
--   🔴 dbt role 에 TABLE OWNERSHIP 을 주지 마라(최소권한 O184). dbt 가 ALTER 를 시도해 실패하면
--      권한 문제가 아니라 DDL 선행 누락이다(on_schema_change=append_new_columns ⇒ ALTER ADD COLUMN).
--      ⇒ 해당 배포 파일의 ALTER(예: 45_DEPLOY_SEND_GBN_AT_OPEN.sql [D1-C])를 GN_DW_ADMIN 으로 먼저 실행한다.
--   WARN: COPY CURRENT GRANTS 필수 — 생략하면 기존 grant 가 전부 회수된다.
-- 실행 = 블록 순서대로 [S0] → [S1] → [S2] → [S3]. [S0]/[S3] 결과 0행이 정상.
-- =============================================================================

-- [S0] 진단 — 설계와 다른 소유자 (0행이 정상)
USE ROLE GN_DW_ADMIN;
SELECT TABLE_TYPE, TABLE_NAME, TABLE_OWNER,
       IFF(TABLE_TYPE = 'VIEW', 'GN_DW_DBT', 'GN_DW_ADMIN') AS EXPECTED_OWNER
FROM GN_DW.INFORMATION_SCHEMA.TABLES
WHERE TABLE_SCHEMA = 'GOLD'
  AND TABLE_OWNER IS DISTINCT FROM IFF(TABLE_TYPE = 'VIEW', 'GN_DW_DBT', 'GN_DW_ADMIN')
ORDER BY 1, 2;

-- [S0-2] 진단 — GN_DW_DBT 의 TABLE DML 권한 누락 (0행이 정상 · 기대 5종)
SELECT t.TABLE_NAME, COUNT(p.PRIVILEGE_TYPE) AS DBT_PRIV_CNT,
       LISTAGG(p.PRIVILEGE_TYPE, ',') WITHIN GROUP (ORDER BY p.PRIVILEGE_TYPE) AS DBT_PRIVS
FROM GN_DW.INFORMATION_SCHEMA.TABLES t
LEFT JOIN GN_DW.INFORMATION_SCHEMA.TABLE_PRIVILEGES p
       ON p.TABLE_SCHEMA = t.TABLE_SCHEMA AND p.TABLE_NAME = t.TABLE_NAME
      AND p.GRANTEE = 'GN_DW_DBT'
      AND p.PRIVILEGE_TYPE IN ('SELECT','INSERT','UPDATE','DELETE','TRUNCATE')
WHERE t.TABLE_SCHEMA = 'GOLD' AND t.TABLE_TYPE = 'BASE TABLE'
GROUP BY t.TABLE_NAME
HAVING COUNT(p.PRIVILEGE_TYPE) < 5
ORDER BY 1;

-- [S0-3] 참고 — 현재 FUTURE grant
SHOW FUTURE GRANTS IN SCHEMA GN_DW.GOLD;

-- [S1] 소유권 교정 — 타 role 소유 객체를 넘기려면 MANAGE GRANTS 필요 ⇒ ACCOUNTADMIN
--   🔴 [S0] 에 dbt 가 만들지 않은 VIEW(수동 생성)가 있으면 S1-2 전에 개별 판단한다.
USE ROLE ACCOUNTADMIN;
GRANT OWNERSHIP ON ALL TABLES IN SCHEMA GN_DW.GOLD TO ROLE GN_DW_ADMIN COPY CURRENT GRANTS;  -- S1-1
GRANT OWNERSHIP ON ALL VIEWS  IN SCHEMA GN_DW.GOLD TO ROLE GN_DW_DBT   COPY CURRENT GRANTS;  -- S1-2

-- [S2] 권한 재부여 — 07 설계 그대로 · 재실행 무해
USE ROLE GN_DW_ADMIN;
-- ADMIN
GRANT ALL PRIVILEGES ON SCHEMA GN_DW.GOLD TO ROLE GN_DW_ADMIN;
GRANT ALL PRIVILEGES ON ALL TABLES    IN SCHEMA GN_DW.GOLD TO ROLE GN_DW_ADMIN;
GRANT ALL PRIVILEGES ON ALL VIEWS     IN SCHEMA GN_DW.GOLD TO ROLE GN_DW_ADMIN;
GRANT ALL PRIVILEGES ON FUTURE TABLES IN SCHEMA GN_DW.GOLD TO ROLE GN_DW_ADMIN;
GRANT ALL PRIVILEGES ON FUTURE VIEWS  IN SCHEMA GN_DW.GOLD TO ROLE GN_DW_ADMIN;
-- ENGINEER
GRANT USAGE, CREATE VIEW ON SCHEMA GN_DW.GOLD TO ROLE GN_DW_ENGINEER;
GRANT SELECT, INSERT, UPDATE, DELETE, TRUNCATE ON ALL TABLES    IN SCHEMA GN_DW.GOLD TO ROLE GN_DW_ENGINEER;
GRANT SELECT, INSERT, UPDATE, DELETE, TRUNCATE ON FUTURE TABLES IN SCHEMA GN_DW.GOLD TO ROLE GN_DW_ENGINEER;
GRANT SELECT ON ALL VIEWS    IN SCHEMA GN_DW.GOLD TO ROLE GN_DW_ENGINEER;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA GN_DW.GOLD TO ROLE GN_DW_ENGINEER;
-- DBT
GRANT USAGE, CREATE VIEW ON SCHEMA GN_DW.GOLD TO ROLE GN_DW_DBT;
GRANT SELECT, INSERT, UPDATE, DELETE, TRUNCATE ON ALL TABLES    IN SCHEMA GN_DW.GOLD TO ROLE GN_DW_DBT;
GRANT SELECT, INSERT, UPDATE, DELETE, TRUNCATE ON FUTURE TABLES IN SCHEMA GN_DW.GOLD TO ROLE GN_DW_DBT;
GRANT SELECT ON ALL VIEWS    IN SCHEMA GN_DW.GOLD TO ROLE GN_DW_DBT;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA GN_DW.GOLD TO ROLE GN_DW_DBT;
-- 조회 role 3종
GRANT USAGE ON SCHEMA GN_DW.GOLD TO ROLE GN_DW_ANALYST;
GRANT USAGE ON SCHEMA GN_DW.GOLD TO ROLE GN_DW_VIEWER;
GRANT USAGE ON SCHEMA GN_DW.GOLD TO ROLE GN_DW_SERVICE;
GRANT SELECT ON ALL TABLES    IN SCHEMA GN_DW.GOLD TO ROLE GN_DW_ANALYST;
GRANT SELECT ON ALL VIEWS     IN SCHEMA GN_DW.GOLD TO ROLE GN_DW_ANALYST;
GRANT SELECT ON FUTURE TABLES IN SCHEMA GN_DW.GOLD TO ROLE GN_DW_ANALYST;
GRANT SELECT ON FUTURE VIEWS  IN SCHEMA GN_DW.GOLD TO ROLE GN_DW_ANALYST;
GRANT SELECT ON ALL TABLES    IN SCHEMA GN_DW.GOLD TO ROLE GN_DW_VIEWER;
GRANT SELECT ON ALL VIEWS     IN SCHEMA GN_DW.GOLD TO ROLE GN_DW_VIEWER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA GN_DW.GOLD TO ROLE GN_DW_VIEWER;
GRANT SELECT ON FUTURE VIEWS  IN SCHEMA GN_DW.GOLD TO ROLE GN_DW_VIEWER;
GRANT SELECT ON ALL TABLES    IN SCHEMA GN_DW.GOLD TO ROLE GN_DW_SERVICE;
GRANT SELECT ON ALL VIEWS     IN SCHEMA GN_DW.GOLD TO ROLE GN_DW_SERVICE;
GRANT SELECT ON FUTURE TABLES IN SCHEMA GN_DW.GOLD TO ROLE GN_DW_SERVICE;
GRANT SELECT ON FUTURE VIEWS  IN SCHEMA GN_DW.GOLD TO ROLE GN_DW_SERVICE;

