-- [1] 마스킹 정책 — 이메일 1종(범용 · 다른 이메일 컬럼에도 재사용)
--   · IS_ROLE_IN_SESSION 을 쓴다 — CURRENT_ROLE 비교는 상위 롤·secondary role 을 거부한다(모범 사례).
--   · 원문 노출 = GN_DW_ADMIN(수신자 관리 주체). 소유자 권한(owner's rights) 프로시저 안에서는 「프로시저 소유 롤만」 평가된다(Snowflake 문서)
--     ⇒ 알림 프로시저 소유 롤이 GN_DW_ADMIN 이면 메일 발송은 원문을 읽는다. 🔴 소유 롤이 다르면 메일이 가려진 주소로 나간다 — [5]③ 로 실측한다.
--   · 그 외 = 도메인만 남긴다('***@example.org') — 같은 회사 수신자인지 판단은 가능하게.
CREATE MASKING POLICY IF NOT EXISTS GN_DW.SECURITY.MP_PII_EMAIL AS (VAL STRING) RETURNS STRING ->
  CASE
    WHEN VAL IS NULL THEN NULL
    WHEN IS_ROLE_IN_SESSION('GN_DW_ADMIN') THEN VAL
    ELSE '***' || SUBSTR(VAL, POSITION('@' IN VAL))
  END
  COMMENT = 'N02 · PII 이메일(SEMANTIC_CATEGORY=EMAIL · IDENTIFIER) · 원문 = GN_DW_ADMIN · 그 외 도메인만 · 담당 TBD';

