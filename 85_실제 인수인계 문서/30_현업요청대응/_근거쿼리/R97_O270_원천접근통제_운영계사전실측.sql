-- Q09 [재현 전제] GOLD·SERVING 객체 소유자(테이블 = GN_DW_ADMIN · WIDE 뷰 = GN_DW_DBT 가 개발계 실측)
SELECT TABLE_SCHEMA, TABLE_TYPE, TABLE_OWNER, COUNT(*) AS N
FROM GN_DW.INFORMATION_SCHEMA.TABLES
WHERE TABLE_SCHEMA IN ('SILVER', 'GOLD', 'SERVING')
GROUP BY 1, 2, 3
ORDER BY 1, 2, 3;

