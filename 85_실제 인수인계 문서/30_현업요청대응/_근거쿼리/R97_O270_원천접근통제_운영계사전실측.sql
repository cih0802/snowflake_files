SHOW GRANTS OF ROLE GN_DW_SERVICE;

-- Q02 [C1] GN_DW 역할 보유 사용자의 기본·보조 역할 정책(DEFAULT_SECONDARY_ROLES = ALL 이면 분리 무력화)
SELECT u.NAME, u.LOGIN_NAME, u.TYPE, u.DISABLED, u.DEFAULT_ROLE, u.DEFAULT_SECONDARY_ROLE,
       LISTAGG(DISTINCT g.ROLE, ',') WITHIN GROUP (ORDER BY g.ROLE) AS GN_DW_ROLES,
       COUNT(DISTINCT g.ROLE) AS GN_DW_ROLE_CNT
FROM SNOWFLAKE.ACCOUNT_USAGE.USERS u
JOIN SNOWFLAKE.ACCOUNT_USAGE.GRANTS_TO_USERS g
  ON g.GRANTEE_NAME = u.NAME AND g.DELETED_ON IS NULL AND g.ROLE LIKE 'GN_DW%'
WHERE u.DELETED_ON IS NULL
GROUP BY 1, 2, 3, 4, 5, 6
ORDER BY GN_DW_ROLE_CNT DESC, 1;

-- Q03 [C5] Streamlit 목록 · 소유자 · 권한 방식(소유자 권한이면 팀장은 AGENCY 까지 본다)
SHOW STREAMLITS IN ACCOUNT;

-- Q04 [C4] 최근 30일 구 역할로 실행된 GN_DW 질의(서비스 의존 실측 · 사용자·창고·건수)
SELECT ROLE_NAME, USER_NAME, WAREHOUSE_NAME, COUNT(*) AS QUERY_CNT,
       MIN(START_TIME) AS FIRST_TS, MAX(START_TIME) AS LAST_TS
FROM SNOWFLAKE.ACCOUNT_USAGE.QUERY_HISTORY
WHERE START_TIME >= DATEADD(DAY, -30, CURRENT_TIMESTAMP())
  AND ROLE_NAME IN ('GN_DW_ANALYST', 'GN_DW_VIEWER', 'GN_DW_SERVICE')
GROUP BY 1, 2, 3
ORDER BY QUERY_CNT DESC;

-- Q05 [C4] 최근 30일 구 역할이 읽은 AGENCY·ERP 유래 객체(회수 시 깨지는 소비처)
SELECT q.ROLE_NAME, q.USER_NAME, f.value:"objectName"::STRING AS OBJ, COUNT(*) AS CNT
FROM SNOWFLAKE.ACCOUNT_USAGE.ACCESS_HISTORY a
JOIN SNOWFLAKE.ACCOUNT_USAGE.QUERY_HISTORY q ON q.QUERY_ID = a.QUERY_ID
, LATERAL FLATTEN(a.BASE_OBJECTS_ACCESSED) f
WHERE a.QUERY_START_TIME >= DATEADD(DAY, -30, CURRENT_TIMESTAMP())
  AND q.ROLE_NAME IN ('GN_DW_ANALYST', 'GN_DW_VIEWER', 'GN_DW_SERVICE')
  AND (f.value:"objectName"::STRING ILIKE 'GN_DW.BRONZE_AGENCY.%'
    OR f.value:"objectName"::STRING ILIKE 'GN_DW.BRONZE_ERP.%'
    OR f.value:"objectName"::STRING ILIKE 'GN_DW.SILVER.AGENCY_%'
    OR f.value:"objectName"::STRING ILIKE 'GN_DW.SILVER.ERP_%'
    OR f.value:"objectName"::STRING ILIKE 'GN_DW.GOLD.%AD_%'
    OR f.value:"objectName"::STRING ILIKE 'GN_DW.GOLD.%BUDGET%'
    OR f.value:"objectName"::STRING ILIKE 'GN_DW.GOLD.FACT_EXPENSE_RESOLUTION'
    OR f.value:"objectName"::STRING ILIKE 'GN_DW.GOLD.FACT_MKTG_CAMPAIGN_MONTHLY_COST')
GROUP BY 1, 2, 3
ORDER BY CNT DESC;

