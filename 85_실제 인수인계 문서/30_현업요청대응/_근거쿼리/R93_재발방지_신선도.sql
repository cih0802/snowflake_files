-- Q01 DR-25 CRM_HOLIDAY 권한(10-22 첫 오류 42501) · 객체 소유 롤과 dbt 실행 롤 권한
SELECT TABLE_SCHEMA, TABLE_NAME, TABLE_OWNER, TABLE_TYPE, CREATED, LAST_ALTERED, ROW_COUNT
FROM GN_DW.INFORMATION_SCHEMA.TABLES
WHERE TABLE_NAME IN ('CRM_HOLIDAY', 'DIM_DATE')
ORDER BY 1, 2;
-- Q02 SILVER 스키마에 dbt 롤이 가진 권한(CRM_HOLIDAY 생성·교체에 필요한 CREATE TABLE · OWNERSHIP)
SELECT PRIVILEGE, GRANTED_ON, NAME, GRANTEE_NAME, GRANTED_BY
FROM SNOWFLAKE.ACCOUNT_USAGE.GRANTS_TO_ROLES
WHERE DELETED_ON IS NULL
  AND GRANTEE_NAME = 'GN_DW_DBT'
  AND (NAME = 'GN_DW.SILVER' OR NAME ILIKE 'GN_DW.SILVER.CRM_HOLIDAY')
ORDER BY GRANTED_ON, NAME, PRIVILEGE;
-- Q03 AGENCY_AD_ROW_* 원천 개명(O260·O262) 반영 · 모델 테이블 상태
SELECT TABLE_SCHEMA, TABLE_NAME, TABLE_OWNER, LAST_ALTERED, ROW_COUNT
FROM GN_DW.INFORMATION_SCHEMA.TABLES
WHERE TABLE_NAME ILIKE 'AGENCY_AD_ROW_%'
ORDER BY 1, 2;
-- Q04 10-22~26 실패 기간 하류 신선도 · AGENCY·광고 계열 테이블의 최종 갱신(10-26 18:43 수동 build 이후면 따라잡음)
SELECT TABLE_SCHEMA, TABLE_NAME, LAST_ALTERED,
       IFF(LAST_ALTERED >= '2026-10-26 18:43:00 +0900'::TIMESTAMP_TZ, 'CAUGHT_UP', 'STALE') AS JUDGE
FROM GN_DW.INFORMATION_SCHEMA.TABLES
WHERE TABLE_SCHEMA IN ('SILVER', 'GOLD')
  AND (TABLE_NAME ILIKE 'AGENCY_%' OR TABLE_NAME ILIKE 'FACT_AD_%' OR TABLE_NAME IN ('CRM_HOLIDAY', 'DIM_DATE'))
ORDER BY JUDGE DESC, 1, 2;
-- Q05 10-27 이후 정기 build 상태(재발 감시 · 매 측정 시 최근 7일)
SELECT NAME, STATE, SCHEDULED_TIME, COMPLETED_TIME, LEFT(ERROR_MESSAGE, 200) AS ERROR_HEAD
FROM TABLE(GN_DW.INFORMATION_SCHEMA.TASK_HISTORY(
       SCHEDULED_TIME_RANGE_START => DATEADD('day', -7, CURRENT_TIMESTAMP()),
       TASK_NAME => 'daily'))
ORDER BY SCHEDULED_TIME;
