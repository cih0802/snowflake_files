-- 🔴 NOTIFICATION_HISTORY 는 최근 14일 · 1회 최대 1,000행 · 창 336시간 미만만 받는다 ⇒ 2026-11-04 이후에는 10-22 분이 사라진다.
-- Q01 알림 발송 이력(최근 13일 · 이메일 통합 포함 전 통합)
SELECT CREATED, PROCESSED, MESSAGE_SOURCE, INTEGRATION_NAME, STATUS, ERROR_MESSAGE
FROM TABLE(GN_DW.INFORMATION_SCHEMA.NOTIFICATION_HISTORY(
       START_TIME => DATEADD('day', -13, CURRENT_TIMESTAMP()),
       RESULT_LIMIT => 1000))
ORDER BY CREATED;
-- Q02 알림 발송 이력 일별·상태별 집계(Q01 이 1,000행에서 잘렸는지 대조용)
SELECT CREATED::DATE AS DAY, INTEGRATION_NAME, STATUS, COUNT(*) AS N
FROM TABLE(GN_DW.INFORMATION_SCHEMA.NOTIFICATION_HISTORY(
       START_TIME => DATEADD('day', -13, CURRENT_TIMESTAMP()),
       RESULT_LIMIT => 1000))
GROUP BY 1, 2, 3
ORDER BY 1, 2, 3;
-- Q03 메일 발송 호출 흔적(10-21 ~ 10-27 · SYSTEM$SEND_EMAIL 을 부른 문장 · 수신자 원문은 받지 않는다)
SELECT START_TIME, ROLE_NAME, WAREHOUSE_NAME, EXECUTION_STATUS, ERROR_CODE,
       LEFT(REGEXP_REPLACE(QUERY_TEXT, '[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+', '<email>'), 200) AS QUERY_HEAD
FROM SNOWFLAKE.ACCOUNT_USAGE.QUERY_HISTORY
WHERE START_TIME >= '2026-10-21'::TIMESTAMP_LTZ
  AND START_TIME <  '2026-10-28'::TIMESTAMP_LTZ
  AND QUERY_TEXT ILIKE '%SEND_EMAIL%'
ORDER BY START_TIME;
-- Q04 장애 알림을 보내는 Task·Alert 의 실행 이력(같은 기간 · 이름에 ALERT·NOTIFY·FAIL 포함)
SELECT NAME, SCHEMA_NAME, STATE, SCHEDULED_TIME, COMPLETED_TIME, LEFT(ERROR_MESSAGE, 200) AS ERROR_HEAD
FROM SNOWFLAKE.ACCOUNT_USAGE.TASK_HISTORY
WHERE DATABASE_NAME = 'GN_DW'
  AND SCHEDULED_TIME >= '2026-10-21'::TIMESTAMP_LTZ
  AND SCHEDULED_TIME <  '2026-10-28'::TIMESTAMP_LTZ
  AND (NAME ILIKE '%ALERT%' OR NAME ILIKE '%NOTIF%' OR NAME ILIKE '%FAIL%' OR NAME = 'daily')
ORDER BY SCHEDULED_TIME;
