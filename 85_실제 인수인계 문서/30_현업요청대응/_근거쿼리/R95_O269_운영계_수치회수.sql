-- Q03 [T1] TASK_VIDEO 상태(재개 결정 후 started 기대)
SHOW TASKS LIKE 'TASK_VIDEO' IN SCHEMA GN_DW.BRONZE_AGENCY;
-- Q04 [T2·T3 · ERP] 2026-10-27 이후 Task 실행 결과(daily 오류 원문 포함)
SELECT database_name, schema_name, name, state, COUNT(*) runs, MAX(scheduled_time) last_run,
       LISTAGG(DISTINCT LEFT(error_message, 200), ' | ') errors
FROM TABLE(GN_DW.INFORMATION_SCHEMA.TASK_HISTORY(
       SCHEDULED_TIME_RANGE_START => '2026-10-27 00:00:00'::TIMESTAMP_LTZ,
       RESULT_LIMIT => 1000))
GROUP BY 1, 2, 3, 4
ORDER BY 1, 2, 3, 4;
-- Q05 [85 문서 갱신 · T7 기준] Agent 3종 버전(43~58 반영 후)
