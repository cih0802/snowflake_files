-- Q07 [ERP · YEAR 비숫자] 건수 분해(YEAR · 수입지출구분 · 예산절차)
SELECT YEAR, INCOME_EXPS_DIV_NM, BDGT_PRCD_NM, COUNT(*) n
FROM GN_DW.BRONZE_ERP.BDGT_ACMSLT_LEDGER
WHERE YEAR IS NULL OR TRY_TO_NUMBER(YEAR) IS NULL
GROUP BY 1, 2, 3
ORDER BY 4 DESC;
-- Q08 [ERP · 컬럼 밀림 판정] 비숫자 YEAR 행 원문 20행(전 컬럼 · 밀림이면 금액 컬럼에도 문자가 보인다)
SELECT *
FROM GN_DW.BRONZE_ERP.BDGT_ACMSLT_LEDGER
WHERE YEAR IS NULL OR TRY_TO_NUMBER(YEAR) IS NULL
LIMIT 20;
-- Q09 [ERP · 대조군] 정상 행 5행(같은 컬럼 순서로 비교)
SELECT *
FROM GN_DW.BRONZE_ERP.BDGT_ACMSLT_LEDGER
WHERE TRY_TO_NUMBER(YEAR) IS NOT NULL
LIMIT 5;
-- Q10 [ERP · 영향 규모] 비숫자 YEAR 행의 금액 합(필터로 빼면 사라지는 크기)
SELECT COUNT(*) n,
       SUM(TRY_TO_NUMBER(TO_VARCHAR(YEAR_BDGT_TOT_AMT))) year_bdgt,
       SUM(TRY_TO_NUMBER(TO_VARCHAR(EXEC_TOT_AMT))) exec_tot
FROM GN_DW.BRONZE_ERP.BDGT_ACMSLT_LEDGER
WHERE YEAR IS NULL OR TRY_TO_NUMBER(YEAR) IS NULL;
-- Q11 [ERP · 적재 시점] 원천 테이블 최근 변경 시각
SELECT TABLE_NAME, ROW_COUNT, LAST_ALTERED
FROM GN_DW.INFORMATION_SCHEMA.TABLES
WHERE TABLE_SCHEMA = 'BRONZE_ERP'
ORDER BY 1;
