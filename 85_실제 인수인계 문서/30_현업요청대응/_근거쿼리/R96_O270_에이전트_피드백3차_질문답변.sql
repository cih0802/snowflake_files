-- Q01 [R95 Q04 후속] daily 2026-10-29 06:01 FAILED 오류 원문 전체(R95 는 200자에서 잘렸다)
SELECT name, state, scheduled_time, completed_time, error_code, error_message
FROM TABLE(GN_DW.INFORMATION_SCHEMA.TASK_HISTORY(
       SCHEDULED_TIME_RANGE_START => '2026-10-28 00:00:00'::TIMESTAMP_LTZ,
       RESULT_LIMIT => 1000))
WHERE schema_name = 'OPS' AND name ILIKE 'daily'
ORDER BY scheduled_time DESC;

-- Q02 [Agent 질문·답변 원문] 최근 3일 · 데분_5(제작비) · 데분_6(광고비) · 데분_7(영상 실적·개발단가) · 출처(재방송)
SELECT e.TIMESTAMP,
       e.RECORD_ATTRIBUTES:"snow.ai.observability.user.name"::STRING          AS user_name,
       e.RECORD_ATTRIBUTES:"snow.ai.observability.agent.thread_id"::STRING    AS thread_id,
       e.RECORD_ATTRIBUTES:"snow.ai.observability.object.version.name"::STRING AS agent_version,
       e.VALUE:"snow.ai.observability.request_body"::STRING                   AS request_body,
       e.VALUE:"snow.ai.observability.response"::STRING                       AS response
FROM TABLE(SNOWFLAKE.LOCAL.GET_AI_OBSERVABILITY_EVENTS('GN_DW', 'SERVING', 'AGENT_MARKETING', 'CORTEX AGENT')) e
WHERE e.TIMESTAMP >= DATEADD(DAY, -3, CURRENT_TIMESTAMP())
  AND e.RECORD:name::STRING = 'CORTEX_AGENT_REQUEST'
  AND (e.VALUE::STRING ILIKE '%제작비%' OR e.VALUE::STRING ILIKE '%광고비%'
    OR e.VALUE::STRING ILIKE '%영상광고%' OR e.VALUE::STRING ILIKE '%개발단가%'
    OR e.VALUE::STRING ILIKE '%실적%' OR e.VALUE::STRING ILIKE '%재방송%')
ORDER BY e.TIMESTAMP;

-- Q03 [스레드 목록] 최근 3일(Observability 탭과 같은 내용)
SELECT THREAD_ID, FIRST_INPUT, MESSAGE_COUNT, USER_NAME, AGENT_VERSION, FIRST_TIMESTAMP, LAST_TIMESTAMP, USER_FEEDBACK
FROM TABLE(SNOWFLAKE.LOCAL.GET_AI_AGENT_MONITORING_DATA(
       'GN_DW', 'SERVING', 'AGENT_MARKETING',
       DATEADD(DAY, -3, CURRENT_TIMESTAMP())::TIMESTAMP_TZ, CURRENT_TIMESTAMP()::TIMESTAMP_TZ))
ORDER BY LAST_TIMESTAMP DESC;

-- Q04 [Agent 가 실행한 SQL] 최근 3일 · 제작비·광고비·개발 실적을 읽은 SV 쿼리(데분_5 「어제 vs 오늘」 쿼리 차이 확인)
SELECT QUERY_ID, START_TIME, USER_NAME, EXECUTION_STATUS, ERROR_MESSAGE, LEFT(QUERY_TEXT, 1500) AS query_text
FROM SNOWFLAKE.ACCOUNT_USAGE.QUERY_HISTORY
WHERE START_TIME >= DATEADD(DAY, -3, CURRENT_TIMESTAMP())
  AND (QUERY_TEXT ILIKE '%SV_MKTG_CAMPAIGN_COST%' OR QUERY_TEXT ILIKE '%SV_AD%'
    OR QUERY_TEXT ILIKE '%SV_MSTR_SPNSR_DVLP%')
  AND QUERY_TEXT NOT ILIKE '%QUERY_HISTORY%'
ORDER BY START_TIME;

-- Q05 [데분_5 · 원천] ERP 지출결의 작성월별 콘텐츠구분자 기재 건수·금액(RPA 갱신 전후 비교 축)
--   개발계 2026-10-29 실측 = 2026-06 기재 118 → 07 1 → 08~10 0
SELECT TO_CHAR(TRY_TO_DATE(TO_VARCHAR(WRITE_DATE)), 'YYYYMM') AS write_mt,
       COUNT(*) AS n,
       COUNT_IF(NULLIF(TRIM(CONTENTS_DELIMITER), '-') IS NOT NULL) AS delim_filled,
       SUM(IFF(NULLIF(TRIM(CONTENTS_DELIMITER), '-') IS NOT NULL, TRY_TO_NUMBER(TO_VARCHAR(SUM_AMT)), 0)) AS delim_amt
FROM GN_DW.BRONZE_ERP.EXPENSE_RESOLUTION
WHERE TRY_TO_DATE(TO_VARCHAR(WRITE_DATE)) >= '2025-01-01'
GROUP BY 1
ORDER BY 1;

-- Q06 [데분_5 · 적재] ERP·GOLD 제작비 테이블 변경 시각(R95 Q11 = EXPENSE_RESOLUTION 2026-10-27 18:59)
SELECT TABLE_SCHEMA, TABLE_NAME, ROW_COUNT, LAST_ALTERED
FROM GN_DW.INFORMATION_SCHEMA.TABLES
WHERE (TABLE_SCHEMA = 'BRONZE_ERP' AND TABLE_NAME = 'EXPENSE_RESOLUTION')
   OR (TABLE_SCHEMA = 'SILVER' AND TABLE_NAME = 'ERP_EXPENSE_RESOLUTION')
   OR (TABLE_SCHEMA = 'GOLD' AND TABLE_NAME IN ('FACT_EXPENSE_RESOLUTION', 'FACT_MKTG_CAMPAIGN_MONTHLY_COST'))
ORDER BY 1, 2;

-- Q07 [데분_5 · 현재값] 2026 마케팅캠페인별 제작비(Agent 「오늘 답변」과 대조)
SELECT m.MKTG_CAMPAIGN_NAME, SUM(f.PROD_COST) AS prod_cost_2026
FROM GN_DW.GOLD.FACT_MKTG_CAMPAIGN_MONTHLY_COST f
JOIN GN_DW.GOLD.DIM_MARKETING_CAMPAIGN m ON m.MKTG_CAMPAIGN_SK = f.MKTG_CAMPAIGN_SK
WHERE f.MONTH_KEY BETWEEN 202601 AND 202612
GROUP BY 1
HAVING SUM(f.PROD_COST) IS NOT NULL
ORDER BY 2 DESC;

-- Q08 [데분_7 · 원천] 영상광고 원천 월별 개발건 기재 패턴(개발계 = 06월부터 전 행 0)
SELECT YEAR, MONTH, COUNT(*) AS n,
       COUNT(DVLP_CNT) AS dvlp_filled,
       COUNT_IF(TRY_TO_NUMBER(TO_VARCHAR(DVLP_CNT)) > 0) AS dvlp_pos,
       SUM(TRY_TO_NUMBER(TO_VARCHAR(DVLP_CNT), 38, 2)) AS dvlp_sum,
       SUM(TRY_TO_NUMBER(TO_VARCHAR(SPNSER_CNT), 38, 2)) AS spnser_sum,
       SUM(TRY_TO_NUMBER(TO_VARCHAR(LAST_AD_COST))) AS last_ad_cost
FROM GN_DW.BRONZE_AGENCY.VIDEO_AD_CMPGN_DTLS
WHERE TRY_TO_NUMBER(TO_VARCHAR(YEAR)) = 2026
GROUP BY 1, 2
ORDER BY 1, TRY_TO_NUMBER(TO_VARCHAR(MONTH));

-- Q09 [데분_7 · 마감값 후보] MSTR 2026 월별 개발건(홍보매체 PR_MTH_CD 별) — 현업 「실제 마감값」 대조용
SELECT STRD_MT, PR_MTH_CD, SUM(SPNSR_AMT_CNT) AS dev_cnt
FROM GN_DW.MSTR.F_MM_SPNSR_DVLP_SUM
WHERE STRD_MT BETWEEN '202601' AND '202612'
  AND DVLP_DIV_CD IN ('1', '2', '4')
GROUP BY 1, 2
ORDER BY 1, 3 DESC;

-- Q10 [데분_6 · 원천별 광고비 컬럼] 2026 월별 · 디지털 LAST_STMT_AMT · 영상 LAST_AD_COST · 재송출/방송 TOT_COST vs 현행 AD_COST
SELECT p.AD_SOURCE_TYPE, b.RT_TYPE, FLOOR(p.PERF_DATE_SK / 100) AS month_key,
       SUM(p.AD_COST) AS ad_cost_now, SUM(p.LAST_STMT_AMT) AS last_stmt_amt, SUM(p.TOT_COST) AS tot_cost
FROM GN_DW.GOLD.FACT_AD_PERFORMANCE p
LEFT JOIN GN_DW.SILVER.AGENCY_AD_BROADCAST b ON b.AD_PERF_DK = p.AD_PERF_DK
WHERE p.PERF_DATE_SK >= 20260101
GROUP BY 1, 2, 3
ORDER BY 1, 2, 3;

-- Q11 [출처명] 재방송 원천 하위구분 값(재송출/방송) 분포 — 라벨 변경 시 충돌 확인
SELECT RT_TYPE, COUNT(*) AS n
FROM GN_DW.SILVER.AGENCY_AD_BROADCAST
WHERE DW_SOURCE_TABLE ILIKE '%REBRDC%'
GROUP BY 1
ORDER BY 2 DESC;
