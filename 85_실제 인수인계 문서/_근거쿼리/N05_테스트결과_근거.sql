-- Q01 dbt 프로젝트 실행 이력 (최근 7일 · 함수 한도)
SELECT QUERY_ID, QUERY_START_TIME, QUERY_END_TIME, COMMAND, SUBSTR(ARGS, 1, 120) AS ARGS, STATE, ERROR_MESSAGE
FROM TABLE(GN_DW.INFORMATION_SCHEMA.DBT_PROJECT_EXECUTION_HISTORY(DATABASE => 'GN_DW', SCHEMA => 'OPS', OBJECT_NAME => 'DW_PIPELINE'))
ORDER BY QUERY_START_TIME;

-- Q02 마지막 전체 build 의 dbt 집계 줄 · WARN 테스트 목록
--   🔴 SYSTEM$GET_DBT_LOG 인자는 상수만 받는다 ⇒ QUERY_ID 를 하드코딩한다.
--         운영계(ZL50263) = 01c7dd2d-0002-365d-0001-72de071db1be (2026-10-21 06:01 · ARGS='')
SELECT 'DONE' AS KIND, REGEXP_SUBSTR(SYSTEM$GET_DBT_LOG('01c7dd2d-0002-365d-0001-72de071db1be'),
       'Done\\. PASS=[0-9]+ WARN=[0-9]+ ERROR=[0-9]+ SKIP=[0-9]+[^\\n]*') AS LINE
UNION ALL
SELECT 'WARN', REGEXP_SUBSTR(VALUE, 'Warning in test [^ ]+')
FROM TABLE(SPLIT_TO_TABLE(SYSTEM$GET_DBT_LOG('01c7dd2d-0002-365d-0001-72de071db1be'), '\n'))
WHERE VALUE LIKE '%Warning in test%';

-- Q03 dbt 테스트 실패 저장 테이블 (store_failures · OPS 의 GN_DW_DBT 소유 · 0행이 기대값) — A6 Q03 와 같은 기준
SELECT TABLE_NAME, ROW_COUNT, LAST_ALTERED
FROM GN_DW.INFORMATION_SCHEMA.TABLES
WHERE TABLE_SCHEMA = 'OPS' AND TABLE_OWNER = 'GN_DW_DBT' AND TABLE_TYPE = 'BASE TABLE'
ORDER BY ROW_COUNT DESC, TABLE_NAME;

-- Q04 MSTR 고정 기준값 게이트 V02 (MSTR 측 · 202606 전체법인 · 스킬_MSTR_검증쿼리.sql :123~135 의 MSTR 절만)
WITH G (DVLP_DIV_CD, N, MBR, CNT, AMT) AS (
    SELECT * FROM VALUES ('1', 12832, 11969, 25713.8900, 257138900),
                         ('2',  2318,  2014,  4999.9501,  49999501),
                         ('4',  1605,  1465,  3350.7500,  33507500)),
     X AS (SELECT DVLP_DIV_CD, COUNT(*) AS N, COUNT(DISTINCT MBER_NO) AS MBR, SUM(SPNSR_AMT_CNT) AS CNT, SUM(SPNSR_AMT) AS AMT
           FROM GN_DW.MSTR.F_MM_SPNSR_DVLP_SUM
           WHERE STRD_MT = '202606' AND DVLP_DIV_CD IN ('1', '2', '4')
           GROUP BY 1)
SELECT G.DVLP_DIV_CD, G.N AS GATE_N, X.N, G.MBR AS GATE_MBR, X.MBR, G.CNT AS GATE_CNT, ROUND(X.CNT, 4) AS CNT, G.AMT AS GATE_AMT, X.AMT,
       IFF(X.N = G.N AND X.MBR = G.MBR AND ROUND(X.CNT, 4) = G.CNT AND X.AMT = G.AMT, 'PASS', 'FAIL') AS RESULT
FROM G LEFT JOIN X ON G.DVLP_DIV_CD = X.DVLP_DIV_CD
ORDER BY 1;

-- Q05 평가셋(05_SV-Agent_ai/07_평가셋_eval.md · 기대값 2026-08-10 O57 스냅샷) 단일값 문항 재실행
--   판정 = |실측 − 기대| ≤ 0.01(비율·1,000 미만) 또는 ≤ 0.5(건·원). 🔴 FAIL 은 「결함」이 아니라 「기대값과 다름」이다 — 원인 분류는 N05 §4.
WITH r AS (
    SELECT 'M1' AS ID, 895178309108::FLOAT AS EXP, (SELECT TOTAL_PAID_ALL FROM SEMANTIC_VIEW(GN_DW.SERVING.SV_MEMBER_MONTHLY METRICS TOTAL_PAID_ALL))::FLOAT AS ACT
    UNION ALL SELECT 'M2', 891959790888, (SELECT TOTAL_BILLED_AMT FROM SEMANTIC_VIEW(GN_DW.SERVING.SV_MEMBER_MONTHLY METRICS TOTAL_BILLED_AMT))
    UNION ALL SELECT 'M3', 85.767153, (SELECT PAYMENT_RATE_FEE FROM SEMANTIC_VIEW(GN_DW.SERVING.SV_MEMBER_MONTHLY DIMENSIONS month.CAL_YEAR METRICS PAYMENT_RATE_FEE) WHERE CAL_YEAR = 2024)
    UNION ALL SELECT 'M4-2023', 86.05, (SELECT ROUND(PAYMENT_RATE_FEE, 2) FROM SEMANTIC_VIEW(GN_DW.SERVING.SV_MEMBER_MONTHLY DIMENSIONS month.CAL_YEAR METRICS PAYMENT_RATE_FEE) WHERE CAL_YEAR = 2023)
    UNION ALL SELECT 'M4-2025', 85.65, (SELECT ROUND(PAYMENT_RATE_FEE, 2) FROM SEMANTIC_VIEW(GN_DW.SERVING.SV_MEMBER_MONTHLY DIMENSIONS month.CAL_YEAR METRICS PAYMENT_RATE_FEE) WHERE CAL_YEAR = 2025)
    UNION ALL SELECT 'M8-DEV', 176400, (SELECT TOTAL_DEV_CNT FROM SEMANTIC_VIEW(GN_DW.SERVING.SV_MEMBER_MONTHLY DIMENSIONS month.CAL_YEAR METRICS TOTAL_DEV_CNT) WHERE CAL_YEAR = 2024)
    UNION ALL SELECT 'M8-STOP', 123180, (SELECT TOTAL_STOP_CNT FROM SEMANTIC_VIEW(GN_DW.SERVING.SV_MEMBER_MONTHLY DIMENSIONS month.CAL_YEAR METRICS TOTAL_STOP_CNT) WHERE CAL_YEAR = 2024)
    UNION ALL SELECT 'M9-DEV', 2291878, (SELECT TOTAL_DEV_CNT FROM SEMANTIC_VIEW(GN_DW.SERVING.SV_MEMBER_MONTHLY METRICS TOTAL_DEV_CNT))
    UNION ALL SELECT 'M9-STOP', 1038262, (SELECT TOTAL_STOP_CNT FROM SEMANTIC_VIEW(GN_DW.SERVING.SV_MEMBER_MONTHLY METRICS TOTAL_STOP_CNT))
    UNION ALL SELECT 'E2', 1585923, (SELECT DEV_MEMBER_COUNT FROM SEMANTIC_VIEW(GN_DW.SERVING.SV_MEMBER_EVENT METRICS DEV_MEMBER_COUNT))
    UNION ALL SELECT 'E3', 903064, (SELECT STOP_MEMBER_COUNT FROM SEMANTIC_VIEW(GN_DW.SERVING.SV_MEMBER_EVENT METRICS STOP_MEMBER_COUNT))
    UNION ALL SELECT 'S1', 38470780, (SELECT TOTAL_SEND_MEMBERS FROM SEMANTIC_VIEW(GN_DW.SERVING.SV_SERVICE METRICS TOTAL_SEND_MEMBERS))
    UNION ALL SELECT 'S2', 1031971, (SELECT DISTINCT_SEND_MEMBERS FROM SEMANTIC_VIEW(GN_DW.SERVING.SV_SERVICE METRICS DISTINCT_SEND_MEMBERS))
    UNION ALL SELECT 'S4', 16563437, (SELECT TOTAL_SEND_MEMBERS FROM SEMANTIC_VIEW(GN_DW.SERVING.SV_SERVICE DIMENSIONS date.CAL_YEAR METRICS TOTAL_SEND_MEMBERS) WHERE CAL_YEAR = 2024)
    UNION ALL SELECT 'P1', 1134126, (SELECT TOTAL_PARTICIPANTS FROM SEMANTIC_VIEW(GN_DW.SERVING.SV_EVENT_PARTICIPATION METRICS TOTAL_PARTICIPANTS))
    UNION ALL SELECT 'P2', 407223, (SELECT DISTINCT_PARTICIPANTS FROM SEMANTIC_VIEW(GN_DW.SERVING.SV_EVENT_PARTICIPATION METRICS DISTINCT_PARTICIPANTS))
    UNION ALL SELECT 'P4', 246628, (SELECT TOTAL_PARTICIPANTS FROM SEMANTIC_VIEW(GN_DW.SERVING.SV_EVENT_PARTICIPATION DIMENSIONS date.CAL_YEAR METRICS TOTAL_PARTICIPANTS) WHERE CAL_YEAR = 2024)
    UNION ALL SELECT 'B1', 547614848306, (SELECT TOTAL_PLAN_BUDGET FROM SEMANTIC_VIEW(GN_DW.SERVING.SV_BUDGET METRICS TOTAL_PLAN_BUDGET))
    UNION ALL SELECT 'B2', 297045080903, (SELECT TOTAL_EXEC_BUDGET FROM SEMANTIC_VIEW(GN_DW.SERVING.SV_BUDGET METRICS TOTAL_EXEC_BUDGET))
    UNION ALL SELECT 'B3', 54.243431, (SELECT EXEC_RATE FROM SEMANTIC_VIEW(GN_DW.SERVING.SV_BUDGET METRICS EXEC_RATE))
)
SELECT ID, EXP, ACT, ACT - EXP AS DIFF,
       IFF(ABS(ACT - EXP) <= IFF(ABS(EXP) < 1000, 0.01, 0.5), 'PASS', 'FAIL') AS RESULT
FROM r
ORDER BY ID;

-- Q06 예산 이상 분해 (Q05 B3 집행율 > 100% 원인 · GOLD.FACT_BUDGET 연도 × 편성차수)
SELECT LEFT(MONTH_KEY, 4) AS YR, BUDGET_PROCEDURE, COUNT(*) AS N,
       SUM(PLAN_BUDGET_MONTH) AS PLAN, SUM(EXEC_BUDGET_ERP) AS EXEC_ERP,
       ROUND(100 * SUM(EXEC_BUDGET_ERP) / NULLIF(SUM(PLAN_BUDGET_MONTH), 0), 2) AS RATE
FROM GN_DW.GOLD.FACT_BUDGET
GROUP BY 1, 2
ORDER BY 1, 2;

-- Q07 Agent 평가 실행 흔적 (AI Evals Task · 최근 30일 · 점수 자체는 Snowsight Evaluations 탭 또는 GET_AI_EVALUATION_DATA(실행 이름 필요))
SELECT REGEXP_SUBSTR(NAME, 'AI_EVALS_[A-Z_]+?_([0-9A-F]{32})', 1, 1, 'e', 1) AS RUN_ID, COUNT(*) AS N_TASK,
       COUNT_IF(STATE = 'SUCCEEDED') AS N_OK, MIN(SCHEDULED_TIME) AS FIRST_T, MAX(COMPLETED_TIME) AS LAST_T
FROM SNOWFLAKE.ACCOUNT_USAGE.TASK_HISTORY
WHERE SCHEDULED_TIME >= DATEADD(day, -30, CURRENT_TIMESTAMP())
  AND DATABASE_NAME = 'GN_DW' AND NAME LIKE 'AI_EVALS_%'
GROUP BY 1
ORDER BY 4;
