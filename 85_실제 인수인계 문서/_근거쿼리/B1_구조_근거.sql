-- Q01 테이블·뷰 목록 (스키마 · 종류 · 행 수 · 바이트 · 소유 · COMMENT)
SELECT TABLE_SCHEMA, TABLE_NAME, TABLE_TYPE, ROW_COUNT, BYTES, TABLE_OWNER, COMMENT
FROM GN_DW.INFORMATION_SCHEMA.TABLES
WHERE TABLE_SCHEMA <> 'INFORMATION_SCHEMA'
ORDER BY 1, 2;

-- Q02 컬럼 정의 (순서 · 타입 · NULL 허용 · 기본값 · COMMENT)
SELECT TABLE_SCHEMA, TABLE_NAME, ORDINAL_POSITION, COLUMN_NAME, DATA_TYPE,
       CHARACTER_MAXIMUM_LENGTH, NUMERIC_PRECISION, NUMERIC_SCALE, IS_NULLABLE, COLUMN_DEFAULT, COMMENT
FROM GN_DW.INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_SCHEMA <> 'INFORMATION_SCHEMA'
ORDER BY 1, 2, 3;

-- Q03 PK · FK (컬럼 단위 · SHOW 는 계정 전체 대신 스키마별)
SHOW PRIMARY KEYS IN DATABASE GN_DW;
SHOW IMPORTED KEYS IN DATABASE GN_DW;

-- Q04 SV 요약 — SV 별 논리테이블·차원·메트릭·관계 수 + base 스키마
SELECT v.NAME AS SV_NAME,
       (SELECT COUNT(*) FROM GN_DW.INFORMATION_SCHEMA.SEMANTIC_TABLES t WHERE t.SEMANTIC_VIEW_NAME = v.NAME) AS N_TABLES,
       (SELECT COUNT(*) FROM GN_DW.INFORMATION_SCHEMA.SEMANTIC_DIMENSIONS d WHERE d.SEMANTIC_VIEW_NAME = v.NAME) AS N_DIMENSIONS,
       (SELECT COUNT(*) FROM GN_DW.INFORMATION_SCHEMA.SEMANTIC_FACTS f WHERE f.SEMANTIC_VIEW_NAME = v.NAME) AS N_FACTS,
       (SELECT COUNT(*) FROM GN_DW.INFORMATION_SCHEMA.SEMANTIC_METRICS m WHERE m.SEMANTIC_VIEW_NAME = v.NAME) AS N_METRICS,
       (SELECT COUNT(*) FROM GN_DW.INFORMATION_SCHEMA.SEMANTIC_RELATIONSHIPS r WHERE r.SEMANTIC_VIEW_NAME = v.NAME) AS N_RELATIONSHIPS,
       (SELECT LISTAGG(DISTINCT t.BASE_TABLE_SCHEMA, '+') FROM GN_DW.INFORMATION_SCHEMA.SEMANTIC_TABLES t
         WHERE t.SEMANTIC_VIEW_NAME = v.NAME) AS BASE_SCHEMAS,
       v.CREATED
FROM GN_DW.INFORMATION_SCHEMA.SEMANTIC_VIEWS v
ORDER BY 1;

-- Q05 SV 논리테이블 ↔ base 객체 (계보 SERVING → GOLD/SERVING)
SELECT SEMANTIC_VIEW_NAME, NAME AS LOGICAL_TABLE, BASE_TABLE_SCHEMA, BASE_TABLE_NAME, PRIMARY_KEYS
FROM GN_DW.INFORMATION_SCHEMA.SEMANTIC_TABLES
ORDER BY 1, 2;

-- Q06 SV 메트릭 (이름 · 식 · 동의어 · 가산성)
SELECT SEMANTIC_VIEW_NAME, TABLE_NAME, NAME AS METRIC_NAME, DATA_TYPE, EXPRESSION, SYNONYMS,
       NON_ADDITIVE_DIMENSIONS, COMMENT
FROM GN_DW.INFORMATION_SCHEMA.SEMANTIC_METRICS
ORDER BY 1, 2, 3;

-- Q07 SV 차원 (이름 · 식 · 동의어)
SELECT SEMANTIC_VIEW_NAME, TABLE_NAME, NAME AS DIMENSION_NAME, DATA_TYPE, EXPRESSION, SYNONYMS
FROM GN_DW.INFORMATION_SCHEMA.SEMANTIC_DIMENSIONS
ORDER BY 1, 2, 3;

-- Q08 SV 관계
SELECT SEMANTIC_VIEW_NAME, NAME AS RELATIONSHIP_NAME, TABLE_NAME, FOREIGN_KEYS, REF_TABLE_NAME, REF_KEYS
FROM GN_DW.INFORMATION_SCHEMA.SEMANTIC_RELATIONSHIPS
ORDER BY 1, 2;

-- Q09 객체 의존 (뷰·SV → 테이블 · GN_DW 내부)
SELECT REFERENCING_SCHEMA, REFERENCING_OBJECT_NAME, REFERENCING_OBJECT_DOMAIN,
       REFERENCED_SCHEMA, REFERENCED_OBJECT_NAME, REFERENCED_OBJECT_DOMAIN, DEPENDENCY_TYPE
FROM SNOWFLAKE.ACCOUNT_USAGE.OBJECT_DEPENDENCIES
WHERE REFERENCING_DATABASE = 'GN_DW'
  AND REFERENCED_DATABASE = 'GN_DW'
ORDER BY 1, 2, 4, 5;

-- Q10 프로시저 · 함수 (D07)
SELECT PROCEDURE_SCHEMA AS SCHEMA_NAME, PROCEDURE_NAME AS NAME, 'PROCEDURE' AS KIND, ARGUMENT_SIGNATURE,
       PROCEDURE_LANGUAGE AS LANGUAGE, PROCEDURE_OWNER AS OWNER, LEFT(COMMENT, 300) AS COMMENT
FROM GN_DW.INFORMATION_SCHEMA.PROCEDURES
UNION ALL
SELECT FUNCTION_SCHEMA, FUNCTION_NAME, 'FUNCTION', ARGUMENT_SIGNATURE, FUNCTION_LANGUAGE, FUNCTION_OWNER, LEFT(COMMENT, 300)
FROM GN_DW.INFORMATION_SCHEMA.FUNCTIONS
ORDER BY 1, 3, 2;

