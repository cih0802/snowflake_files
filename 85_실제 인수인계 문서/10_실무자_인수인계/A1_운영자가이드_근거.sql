-- Q01 사용자 현황 — 기본 롤·WH·비활성·유형 (이메일 제외)
SELECT NAME, LOGIN_NAME, DEFAULT_ROLE, DEFAULT_WAREHOUSE, DEFAULT_SECONDARY_ROLE,
       DISABLED, TYPE, HAS_PASSWORD, HAS_MFA, HAS_RSA_PUBLIC_KEY, LAST_SUCCESS_LOGIN, CREATED_ON
FROM SNOWFLAKE.ACCOUNT_USAGE.USERS
WHERE DELETED_ON IS NULL
ORDER BY NAME;

-- Q02 사용자 ↔ 롤 할당 (A2 Q06 과 같은 축 · 온보딩 점검)
SELECT GRANTEE_NAME AS USER_NAME, ROLE AS ROLE_NAME, GRANTED_BY, CREATED_ON
FROM SNOWFLAKE.ACCOUNT_USAGE.GRANTS_TO_USERS
WHERE DELETED_ON IS NULL
ORDER BY 1, 2;

-- Q03 알림 수신자 플래그 건수 (OPS.ALERT_RECIPIENT_CONFIG · 이메일 제외)
SELECT COUNT(*) AS N_USERS,
       COUNT_IF(IS_ACTIVE_YN = 'Y') AS N_ACTIVE,
       COUNT_IF(IS_PIPELINE_ADMIN_YN = 'Y') AS N_PIPELINE_ADMIN,
       COUNT_IF(IS_ANALYST_YN = 'Y') AS N_ANALYST,
       COUNT_IF(IS_BUSINESS_USER_YN = 'Y') AS N_BUSINESS_USER,
       COUNT_IF(IS_DBT_ALERT_YN = 'Y') AS N_DBT_ALERT
FROM GN_DW.OPS.ALERT_RECIPIENT_CONFIG;

-- Q04 비용 가드 — quota · 예산 · 리소스 모니터
SHOW SNOWFLAKE.CORE.QUOTA INSTANCES;
SHOW SNOWFLAKE.CORE.BUDGET INSTANCES;
SHOW RESOURCE MONITORS;

-- Q05 계정 파라미터 — CoCo 한도 · Personal DB
SHOW PARAMETERS LIKE 'CORTEX_CODE%' IN ACCOUNT;
SHOW PARAMETERS LIKE '%PERSONAL_DATABASE%' IN ACCOUNT;

-- Q06 노출 경로 객체 — CoWork object · Streamlit · 컴퓨트 풀
SHOW SNOWFLAKE INTELLIGENCES;
SHOW STREAMLITS IN ACCOUNT;
SHOW COMPUTE POOLS;

-- Q07 Alert · 알림 통합
SHOW ALERTS IN DATABASE GN_DW;
SHOW NOTIFICATION INTEGRATIONS;
