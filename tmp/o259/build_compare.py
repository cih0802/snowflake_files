"""렌더 SQL → 단일 호출용 다중 문장(TEMP 테이블 · 세션 소멸) + 신구 대조."""
import io
R = "/workspace/tmp/o259/"
rd = lambda f: io.open(R + f, encoding="utf-8").read()
clean = rd("render_clean.sql").replace("T_CLEAN", "GN_DW.SILVER.T_O259_CLEAN")
succ = rd("render_succ.sql").replace("T_CLEAN", "GN_DW.SILVER.T_O259_CLEAN")
dorg = rd("render_dim_org.sql").replace("T_CLEAN", "GN_DW.SILVER.T_O259_CLEAN")
dsucc = rd("render_dim_succ.sql").replace("T_SUCC", "GN_DW.SILVER.T_O259_SUCC")
OC = ("ORG_SK, ORG_DK, CORP, DIVISION, DEPARTMENT, TEAM, ACMSLT_UPPER_DEPT_ID, ACMSLT_DEPT_YN, USE_YN, "
      "IS_ACTIVE_ORG, ORG_PATH, ORG_LEVEL, ACMSLT_DIV_GROUP_ID, ACMSLT_DIV_GROUP_NM, ACMSLT_DIV_ID, ACMSLT_DIV_NM")
SC = ("OLD_ORG_SK, OLD_DEPT_ID, OLD_DEPARTMENT, OLD_IS_ACTIVE_ORG, CUR_ORG_SK, CUR_DEPT_ID, CUR_DEPARTMENT, "
      "CUR_ORG_PATH, CUR_ORG_LEVEL, MAP_METHOD, IS_REMAPPED, IS_CONFIRMED, FLOW_CAND_DEPT_ID, FLOW_EVIDENCE_CNT, "
      "FLOW_SHARE, FLOW_LIFT, CONFIRMED_BY, CONFIRMED_DT, NOTE")
sql = f"""CREATE OR REPLACE TEMPORARY TABLE GN_DW.SILVER.T_O259_CLEAN AS
{clean};
CREATE OR REPLACE TEMPORARY TABLE GN_DW.SILVER.T_O259_SUCC AS
{succ};
CREATE OR REPLACE TEMPORARY TABLE GN_DW.SILVER.T_O259_DORG AS
{dorg};
CREATE OR REPLACE TEMPORARY TABLE GN_DW.SILVER.T_O259_DSUCC AS
{dsucc};
SELECT 'DIM_ORG new-old' K, COUNT(*) N FROM (SELECT {OC} FROM GN_DW.SILVER.T_O259_DORG MINUS SELECT {OC} FROM GN_DW.GOLD.DIM_ORG)
UNION ALL SELECT 'DIM_ORG old-new', COUNT(*) FROM (SELECT {OC} FROM GN_DW.GOLD.DIM_ORG MINUS SELECT {OC} FROM GN_DW.SILVER.T_O259_DORG)
UNION ALL SELECT 'DIM_ORG rows new', COUNT(*) FROM GN_DW.SILVER.T_O259_DORG
UNION ALL SELECT 'DIM_ORG rows old', COUNT(*) FROM GN_DW.GOLD.DIM_ORG
UNION ALL SELECT 'SUCC new-old', COUNT(*) FROM (SELECT {SC} FROM GN_DW.SILVER.T_O259_DSUCC MINUS SELECT {SC} FROM GN_DW.GOLD.DIM_ORG_SUCCESSION)
UNION ALL SELECT 'SUCC old-new', COUNT(*) FROM (SELECT {SC} FROM GN_DW.GOLD.DIM_ORG_SUCCESSION MINUS SELECT {SC} FROM GN_DW.SILVER.T_O259_DSUCC)
UNION ALL SELECT 'SUCC rows new', COUNT(*) FROM GN_DW.SILVER.T_O259_DSUCC
UNION ALL SELECT 'CLEAN rows', COUNT(*) FROM GN_DW.SILVER.T_O259_CLEAN
UNION ALL SELECT 'CLEAN ACTIVE', COUNT_IF(ORG_STATUS='ACTIVE') FROM GN_DW.SILVER.T_O259_CLEAN
UNION ALL SELECT 'RR '||COALESCE(RETIRE_REASON,'(ACTIVE)'), COUNT(*) FROM GN_DW.SILVER.T_O259_CLEAN GROUP BY RETIRE_REASON
UNION ALL SELECT 'PICKER retired', COUNT(*) FROM GN_DW.SILVER.T_O259_CLEAN WHERE ORG_STATUS='ACTIVE' AND NOT IS_ACTIVE_ORG
UNION ALL SELECT 'UPPER_CUR filled', COUNT(OLD_UPPER_CUR_DEPT_ID) FROM GN_DW.SILVER.T_O259_SUCC
ORDER BY 1"""
io.open(R + "compare.sql", "w", encoding="utf-8").write(sql)
print(len(sql))
