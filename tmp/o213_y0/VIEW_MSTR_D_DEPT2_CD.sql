create or replace view D_DEPT2_CD(
	DEPT2_ID,
	DEPT2_NM,
	DEPT3_ID,
	DEPT4_ID,
	DEPT5_ID,
	SORT_ORDR,
	USE_YN,
	ACMSLT_DEPT_YN,
	FST_DE,
	LST_DE,
	WORK_DE
) COMMENT='팀/지부(2레벨)'
 as
SELECT
  D.DEPT_ID AS DEPT2_ID, D.DEPT_NM AS DEPT2_NM, C.DEPT_ID AS DEPT3_ID,
  B.DEPT_ID AS DEPT4_ID, A.DEPT_ID AS DEPT5_ID,
  D.SORT_ORDR, D.USE_YN, D.ACMSLT_DEPT_YN,
  IFNULL(TO_CHAR(D.FRST_REGIST_DT, 'YYYYMMDD'), '19000101') AS FST_DE,
  IFNULL(TO_CHAR(D.LAST_UPDT_DT,   'YYYYMMDD'), '99991231') AS LST_DE,
  TO_CHAR(CURRENT_DATE(), 'YYYYMMDD') AS WORK_DE
FROM GN_DW.MSTR.D_CM_DEPT_INFO A
JOIN GN_DW.MSTR.D_CM_DEPT_INFO B ON B.ACMSLT_UPPER_DEPT_ID = A.DEPT_ID
JOIN GN_DW.MSTR.D_CM_DEPT_INFO C ON C.ACMSLT_UPPER_DEPT_ID = B.DEPT_ID
JOIN GN_DW.MSTR.D_CM_DEPT_INFO D ON D.ACMSLT_UPPER_DEPT_ID = C.DEPT_ID
WHERE A.UPPER_DEPT_ID = 'ZV000000'
  AND A.USE_YN = 'Y'
  AND C.DEPT_ID != 'ZC000029'
UNION ALL
SELECT 'Z~', '없음', 'Z~', 'Z~', 'Z~', 999, 'Y', 'Y', '20191101', '99991231', TO_CHAR(CURRENT_DATE(), 'YYYYMMDD');