create or replace view D_UP_CMPGN_CD(
	UPPER_CMPGN_CD,
	UPPER_CMPGN_NM,
	SORT_ORDR,
	USE_YN
) COMMENT='상위캠페인(UPPER_CMPGN_YN=Y) + 없음'
 as
SELECT
  CMPGN_CD AS UPPER_CMPGN_CD,
  CMPGN_NM AS UPPER_CMPGN_NM,
  ROW_NUMBER() OVER (ORDER BY CMPGN_CD) AS SORT_ORDR,
  USE_YN
FROM GN_DW.MSTR.D_CMPGN_CD
WHERE UPPER_CMPGN_YN = 'Y'
UNION ALL
SELECT 'Z~', '없음', 99999, 'Y';