USE ROLE SECURITYADMIN;
CREATE ROLE IF NOT EXISTS GN_DW_DBT COMMENT = 'dbt 실행 전용(DW_PIPELINE) — 적재·WIDE 뷰·테스트 감사. 사람 작업은 GN_DW_ENGINEER';
GRANT ROLE GN_DW_DBT TO ROLE GN_DW_ADMIN;

USE ROLE SYSADMIN;
GRANT USAGE ON WAREHOUSE GN_DW_ETL_WH TO ROLE GN_DW_DBT;

USE ROLE GN_DW_ADMIN;
GRANT USAGE ON DATABASE GN_DW TO ROLE GN_DW_DBT;
-- [1-a] BRONZE 4종 읽기(source)
GRANT USAGE ON SCHEMA GN_DW.BRONZE_CRM      TO ROLE GN_DW_DBT;
GRANT USAGE ON SCHEMA GN_DW.BRONZE_ERP      TO ROLE GN_DW_DBT;
GRANT USAGE ON SCHEMA GN_DW.BRONZE_AGENCY   TO ROLE GN_DW_DBT;
GRANT USAGE ON SCHEMA GN_DW.BRONZE_BIGQUERY TO ROLE GN_DW_DBT;
GRANT SELECT ON ALL TABLES    IN SCHEMA GN_DW.BRONZE_CRM      TO ROLE GN_DW_DBT;
GRANT SELECT ON FUTURE TABLES IN SCHEMA GN_DW.BRONZE_CRM      TO ROLE GN_DW_DBT;
GRANT SELECT ON ALL TABLES    IN SCHEMA GN_DW.BRONZE_ERP      TO ROLE GN_DW_DBT;
GRANT SELECT ON FUTURE TABLES IN SCHEMA GN_DW.BRONZE_ERP      TO ROLE GN_DW_DBT;
GRANT SELECT ON ALL TABLES    IN SCHEMA GN_DW.BRONZE_AGENCY   TO ROLE GN_DW_DBT;
GRANT SELECT ON FUTURE TABLES IN SCHEMA GN_DW.BRONZE_AGENCY   TO ROLE GN_DW_DBT;
GRANT SELECT ON ALL TABLES    IN SCHEMA GN_DW.BRONZE_BIGQUERY TO ROLE GN_DW_DBT;
GRANT SELECT ON FUTURE TABLES IN SCHEMA GN_DW.BRONZE_BIGQUERY TO ROLE GN_DW_DBT;
-- [1-b] SILVER = append + silver_purge DELETE + pre-hook TRUNCATE (UPDATE 불요 · ㉢)
GRANT USAGE ON SCHEMA GN_DW.SILVER TO ROLE GN_DW_DBT;
GRANT SELECT, INSERT, DELETE, TRUNCATE ON ALL TABLES    IN SCHEMA GN_DW.SILVER TO ROLE GN_DW_DBT;
GRANT SELECT, INSERT, DELETE, TRUNCATE ON FUTURE TABLES IN SCHEMA GN_DW.SILVER TO ROLE GN_DW_DBT;
-- [1-c] GOLD = dim merge(UPDATE) + fact append/TRUNCATE + WIDE 뷰 생성
GRANT USAGE, CREATE VIEW ON SCHEMA GN_DW.GOLD TO ROLE GN_DW_DBT;
GRANT SELECT, INSERT, UPDATE, DELETE, TRUNCATE ON ALL TABLES    IN SCHEMA GN_DW.GOLD TO ROLE GN_DW_DBT;
GRANT SELECT, INSERT, UPDATE, DELETE, TRUNCATE ON FUTURE TABLES IN SCHEMA GN_DW.GOLD TO ROLE GN_DW_DBT;
GRANT SELECT ON ALL VIEWS    IN SCHEMA GN_DW.GOLD TO ROLE GN_DW_DBT;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA GN_DW.GOLD TO ROLE GN_DW_DBT;
-- [1-d] store_failures · 감사 스키마(D.6 과 같은 범위 — FUTURE 미사용)
GRANT USAGE, CREATE TABLE ON SCHEMA GN_DW.OPS             TO ROLE GN_DW_DBT;
GRANT USAGE, CREATE TABLE ON SCHEMA GN_DW.dbt_test__audit TO ROLE GN_DW_DBT;
-- [1-e] 배포 dbt 프로젝트 실행(EXECUTE DBT PROJECT)
GRANT USAGE, MONITOR ON DBT PROJECT GN_DW.OPS.DW_PIPELINE TO ROLE GN_DW_DBT;

