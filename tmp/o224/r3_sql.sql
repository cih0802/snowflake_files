WITH __cc AS (
  SELECT
    cmpgn_ctgr_nm,
    has_member_pred,
    mber_no,
    member_churn_grade,
    sponsor_churn_grade,
    stdr_mt,
    member_churn_prob
  FROM GN_DW.SERVING.ML_CHURN_BY_CMPGN_CTGR_V
), summary AS (
  SELECT
    __cc.stdr_mt AS "기준월",
    COUNT(DISTINCT __cc.mber_no) AS "활동회원수(명)",
    COUNT(DISTINCT CASE WHEN __cc.has_member_pred THEN __cc.mber_no END) AS "회원 단위 예측 대상 회원수(명)",
    COUNT(DISTINCT CASE WHEN __cc.member_churn_grade = '고위험' THEN __cc.mber_no END) AS "중단 고위험 회원수(명)"
  FROM __cc
  WHERE
    __cc.stdr_mt = '202609' AND __cc.cmpgn_ctgr_nm = '고려인캠페인'
  GROUP BY
    __cc.stdr_mt
), member_list AS (
  SELECT
    __cc.mber_no,
    ROUND(__cc.member_churn_prob * 100, 2) AS member_churn_prob_pct,
    __cc.member_churn_grade,
    __cc.sponsor_churn_grade,
    COUNT(__cc.cmpgn_ctgr_nm) AS active_sponsor_cnt
  FROM __cc
  WHERE
    __cc.stdr_mt = '202609'
    AND __cc.cmpgn_ctgr_nm = '고려인캠페인'
    AND __cc.member_churn_grade = '고위험'
  GROUP BY
    __cc.mber_no,
    __cc.member_churn_prob,
    __cc.member_churn_grade,
    __cc.sponsor_churn_grade
  ORDER BY
    member_churn_prob_pct DESC NULLS LAST
  LIMIT 10
)
SELECT
  s."기준월",
  s."활동회원수(명)",
  s."회원 단위 예측 대상 회원수(명)",
  s."중단 고위험 회원수(명)",
  m.mber_no AS "회원번호",
  m.member_churn_prob_pct AS "회원 중단확률(%)",
  m.member_churn_grade AS "회원 중단위험 등급",
  m.sponsor_churn_grade AS "후원건 이탈위험 등급",
  m.active_sponsor_cnt AS "활동 약정 수"
FROM summary AS s
CROSS JOIN member_list AS m
ORDER BY
  m.member_churn_prob_pct DESC NULLS LAST
