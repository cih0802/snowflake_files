WITH __cc AS (
  SELECT
    active_spnsr_cnt,
    cmpgn_ctgr_nm,
    has_member_pred,
    mber_no,
    member_churn_grade,
    sponsor_churn_grade,
    stdr_mt,
    member_churn_prob
  FROM GN_DW.SERVING.ML_CHURN_BY_CMPGN_CTGR_V
), summary AS (
  SELECT
    __cc.stdr_mt AS "기준월",
    COUNT(DISTINCT __cc.mber_no) AS "활동회원수(명)",
    COUNT(DISTINCT CASE WHEN __cc.has_member_pred THEN __cc.mber_no END) AS "회원 단위 예측 대상 회원수(명)",
    COUNT(DISTINCT CASE WHEN __cc.member_churn_grade = '고위험' THEN __cc.mber_no END) AS "중단 고위험 회원수(명)"
  FROM __cc
  WHERE
    __cc.stdr_mt = '202609'
    AND __cc.cmpgn_ctgr_nm = '고려인캠페인'
    AND __cc.member_churn_grade = '고위험'
  GROUP BY
    __cc.stdr_mt
), detail AS (
  SELECT
    __cc.mber_no AS "회원번호",
    ROUND(__cc.member_churn_prob * 100, 2) AS "회원 중단확률(%)",
    __cc.member_churn_grade AS "회원 중단위험 등급",
    __cc.sponsor_churn_grade AS "후원건 이탈위험 등급",
    __cc.active_spnsr_cnt AS "활동 약정 수(건)",
    ROW_NUMBER() OVER (PARTITION BY __cc.mber_no ORDER BY __cc.member_churn_prob DESC NULLS LAST) AS rn
  FROM __cc
  WHERE
    __cc.stdr_mt = '202609'
    AND __cc.cmpgn_ctgr_nm = '고려인캠페인'
    AND __cc.member_churn_grade = '고위험'
), dedup AS (
  SELECT
    "회원번호",
    "회원 중단확률(%)",
    "회원 중단위험 등급",
    "후원건 이탈위험 등급",
    "활동 약정 수(건)"
  FROM detail
  WHERE
    rn = 1
  ORDER BY
    "회원 중단확률(%)" DESC NULLS LAST
  LIMIT 10
)
SELECT
  s."기준월",
  s."활동회원수(명)",
  s."회원 단위 예측 대상 회원수(명)",
  s."중단 고위험 회원수(명)",
  d."회원번호",
  d."회원 중단확률(%)",
  d."회원 중단위험 등급",
  d."후원건 이탈위험 등급",
  d."활동 약정 수(건)"
FROM dedup AS d
CROSS JOIN summary AS s
ORDER BY
  d."회원 중단확률(%)" DESC NULLS LAST
