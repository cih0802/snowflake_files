-- 바꾼 것 3가지(그 밖의 CTE·컬럼·정렬은 원본 그대로):
--   ① 컴파일 오류 3건 시정 — `BROADCAST_DATE` 는 SILVER 에 없다(→ 광고비는 GOLD 에서 읽으므로 소멸)
--      · `C.DEVELOPMENT_INFLOW_PATH` 는 CRM_DEV_SUMMARY 에 없다 → CAMPAIGN_DIM 에 인입경로 나열을 추가해 그쪽에서 읽는다.
--      · `D.ACTIVITY_RATE`·`D.PAYMENT_RATE` 는 GN_DW 에 없다 → NULL(원천 확인 전 창작 금지 · R2-7).
--   ② 광고비 3종 = SILVER 원시 조인(1:1 맵만 · 나머지 폐기) → **GOLD.FACT_AD_PERFORMANCE**(O225 as-of UTM · O232 소재 매핑 반영).
--      · 마케팅캠페인에 연결되지 않은 광고비는 버리지 않고 `(마케팅캠페인 미연결)` 행으로 남긴다 ⇒ 매체별 총액 = GOLD 총액.
--   ③ 금액 정의 = GOLD AD_COST(광고비). 원본은 디지털 LAST_STMT_AMT(최종 청구액) · 재방송 TOT_COST(총비용)라 더 크다(진단 §3).
WITH CRM_CAMPAIGN_BASE AS (
    SELECT
        NULLIF(TRIM(CMPGN_CD), '') AS CMPGN_CD,
        NULLIF(TRIM(MK_CMPGN_NM), '') AS MKTG_CAMPAIGN_NM,
        NULLIF(TRIM(MBER_INFLOW_PATH_NM), '') AS INFLOW_PATH_NM,
        COALESCE(NULLIF(TRIM(CMPGN_TYPE1_NM), ''), '미분류') AS CAMPAIGN_TYPE1,
        COALESCE(NULLIF(TRIM(MKTG_CHANNEL_NM), ''), '미분류') AS CHANNEL_NAME
    FROM GN_DW.SILVER.CRM_CAMPAIGN
    WHERE NULLIF(TRIM(CMPGN_CD), '') IS NOT NULL
      AND NULLIF(TRIM(MK_CMPGN_NM), '') IS NOT NULL
),
CAMPAIGN_DIM AS (
    SELECT
        MKTG_CAMPAIGN_NM,
        LISTAGG(DISTINCT CAMPAIGN_TYPE1, ', ') WITHIN GROUP (ORDER BY CAMPAIGN_TYPE1) AS CAMPAIGN_TYPE1,
        LISTAGG(DISTINCT CHANNEL_NAME, ', ') WITHIN GROUP (ORDER BY CHANNEL_NAME) AS CHANNEL_NAME,
        -- ① 원본이 참조하던 개발인입경로(표시용 나열 · 그루핑·합산 금지)
        LISTAGG(DISTINCT INFLOW_PATH_NM, ', ') WITHIN GROUP (ORDER BY INFLOW_PATH_NM) AS DEVELOPMENT_INFLOW_PATH
    FROM CRM_CAMPAIGN_BASE
    GROUP BY 1
),
CRM_DEV_SUMMARY AS (
    SELECT
        TO_DATE(D.OCCRRNC_DE, 'YYYYMMDD') AS PERFORMANCE_DATE,
        C.MKTG_CAMPAIGN_NM,
        COUNT(DISTINCT CONCAT_WS('|',
            COALESCE(D.SPNSR_NO, ''),
            COALESCE(TO_VARCHAR(D.SPNSR_BSNS_NO), ''),
            COALESCE(D.OCCRRNC_DE, ''),
            COALESCE(TO_VARCHAR(D.SER_NO), '')
        )) AS DEVELOPMENT_COUNT,
        -- 🔴 원본의 D.ACTIVITY_RATE · D.PAYMENT_RATE 는 GN_DW 어디에도 없다(INFORMATION_SCHEMA 0건 · jw08094 2026-10-15)
        --    ⇒ 값을 만들지 않고 NULL 로 둔다. 스트림릿 실제 원천(다른 계정·뷰)을 확인한 뒤 연결한다.
        CAST(NULL AS DOUBLE) AS ACTIVITY_RATE,
        CAST(NULL AS DOUBLE) AS PAYMENT_RATE
    FROM GN_DW.SILVER.CRM_MEMBER_DEV D
    JOIN CRM_CAMPAIGN_BASE C
      ON UPPER(TRIM(D.CMPGN_CD)) = UPPER(C.CMPGN_CD)
    WHERE REGEXP_LIKE(D.OCCRRNC_DE, '^[0-9]{8}$')
    GROUP BY 1, 2
),
-- 제작비 (ERP) — 원본 그대로
ERP_COST AS (
    SELECT
        COALESCE(TRY_TO_DATE(TO_VARCHAR(WRITE_DATE), 'YYYYMMDD'), TRY_TO_DATE(TO_VARCHAR(WRITE_DATE))) AS PERFORMANCE_DATE,
        C.MKTG_CAMPAIGN_NM,
        SUM(COALESCE(SUM_AMT, 0)) AS PRODUCTION_COST
    FROM GN_DW.BRONZE_ERP.EXPENSE_RESOLUTION E
    JOIN CRM_CAMPAIGN_BASE C
      ON UPPER(TRIM(E.CONTENTS_DELIMITER)) = UPPER(C.CMPGN_CD)
    WHERE E.CONTENTS_DELIMITER IS NOT NULL
      AND TRIM(E.CONTENTS_DELIMITER) NOT IN ('', '-')
    GROUP BY 1, 2
),
-- ② 광고비 3종 = GOLD 1곳에서 (매체 구분 = AD_SOURCE_TYPE)
AD_COST_GOLD AS (
    SELECT
        TO_DATE(TO_CHAR(F.PERF_DATE_SK), 'YYYYMMDD') AS PERFORMANCE_DATE,
        COALESCE(MK.MKTG_CAMPAIGN_NAME, '(마케팅캠페인 미연결)') AS MKTG_CAMPAIGN_NM,
        SUM(IFF(F.AD_SOURCE_TYPE = 'DIGITAL', F.AD_COST, 0)) AS DIGITAL_AD_COST,
        SUM(IFF(F.AD_SOURCE_TYPE = 'VIDEO', F.AD_COST, 0)) AS VIDEO_AD_COST,
        SUM(IFF(F.AD_SOURCE_TYPE = 'REBROADCAST', F.AD_COST, 0)) AS REBROADCAST_AD_COST
    FROM GN_DW.GOLD.FACT_AD_PERFORMANCE F
    LEFT JOIN GN_DW.GOLD.DIM_MARKETING_CAMPAIGN MK
      ON MK.MKTG_CAMPAIGN_SK = F.MKTG_CAMPAIGN_SK
     AND F.MKTG_CAMPAIGN_SK > 0
    WHERE F.PERF_DATE_SK <> 0
    GROUP BY 1, 2
),
ACTIVE_KEYS AS (
    SELECT PERFORMANCE_DATE, MKTG_CAMPAIGN_NM FROM CRM_DEV_SUMMARY
    UNION SELECT PERFORMANCE_DATE, MKTG_CAMPAIGN_NM FROM ERP_COST
    UNION SELECT PERFORMANCE_DATE, MKTG_CAMPAIGN_NM FROM AD_COST_GOLD
),
FINAL_DATA AS (
    SELECT
        K.PERFORMANCE_DATE,
        K.MKTG_CAMPAIGN_NM AS MARKETING_CAMPAIGN_NAME,
        COALESCE(X.CAMPAIGN_TYPE1, '미분류') AS CAMPAIGN_TYPE1,
        COALESCE(X.CHANNEL_NAME, '미분류') AS CHANNEL_NAME,
        COALESCE(X.DEVELOPMENT_INFLOW_PATH, '미분류') AS DEVELOPMENT_INFLOW_PATH,
        COALESCE(E.PRODUCTION_COST, 0) AS PRODUCTION_COST,           -- 제작비
        COALESCE(A.DIGITAL_AD_COST, 0) AS DIGITAL_AD_COST,           -- 디지털 광고비
        COALESCE(A.VIDEO_AD_COST, 0) AS VIDEO_AD_COST,               -- 영상 광고비
        COALESCE(A.REBROADCAST_AD_COST, 0) AS REBROADCAST_AD_COST,   -- 재방송 광고비
        COALESCE(A.DIGITAL_AD_COST, 0) + COALESCE(A.VIDEO_AD_COST, 0) + COALESCE(A.REBROADCAST_AD_COST, 0) AS AD_COST,
        COALESCE(E.PRODUCTION_COST, 0)
          + COALESCE(A.DIGITAL_AD_COST, 0) + COALESCE(A.VIDEO_AD_COST, 0) + COALESCE(A.REBROADCAST_AD_COST, 0) AS TOTAL_COST,
        COALESCE(C.DEVELOPMENT_COUNT, 0) AS DEVELOPMENT_COUNT,       -- 개발건수
        C.ACTIVITY_RATE,                                             -- 활동률
        C.PAYMENT_RATE                                               -- 납입률
    FROM ACTIVE_KEYS K
    LEFT JOIN CAMPAIGN_DIM X
      ON K.MKTG_CAMPAIGN_NM = X.MKTG_CAMPAIGN_NM
    LEFT JOIN CRM_DEV_SUMMARY C
      ON K.PERFORMANCE_DATE = C.PERFORMANCE_DATE AND K.MKTG_CAMPAIGN_NM = C.MKTG_CAMPAIGN_NM
    LEFT JOIN ERP_COST E
      ON K.PERFORMANCE_DATE = E.PERFORMANCE_DATE AND K.MKTG_CAMPAIGN_NM = E.MKTG_CAMPAIGN_NM
    LEFT JOIN AD_COST_GOLD A
      ON K.PERFORMANCE_DATE = A.PERFORMANCE_DATE AND K.MKTG_CAMPAIGN_NM = A.MKTG_CAMPAIGN_NM
)
SELECT
    *,
    DIV0(TOTAL_COST, DEVELOPMENT_COUNT) AS DEVELOPMENT_UNIT_COST     -- 건당 개발비용(미연결 행은 개발건수 0 ⇒ 0)
FROM FINAL_DATA
WHERE PERFORMANCE_DATE IS NOT NULL
  AND (DEVELOPMENT_COUNT > 0 OR TOTAL_COST <> 0)
ORDER BY PERFORMANCE_DATE DESC, TOTAL_COST DESC;
