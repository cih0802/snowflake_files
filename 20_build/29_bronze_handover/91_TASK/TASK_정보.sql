-- 최초 생성 이후 
ALTER TASK IF EXISTS GN_DW.BRONZE_AGENCY.AGENCY_TASK_MASTER RESUME;
ALTER TASK IF EXISTS GN_DW.BRONZE_AGENCY.TASK_DGT RESUME;
ALTER TASK IF EXISTS GN_DW.BRONZE_AGENCY.TASK_REBRDC RESUME;
ALTER TASK IF EXISTS GN_DW.BRONZE_AGENCY.TASK_VIDEO RESUME;
ALTER TASK IF EXISTS GN_DW.BRONZE_GA4.TASK_GA_USER_DEMOGRAPHIC RESUME; --SUSPEND   
ALTER TASK IF EXISTS GN_DW.BRONZE_GSC.TASK_GOOGLE_SEARCH RESUME; --SUSPEND   
ALTER TASK IF EXISTS GN_DW.BRONZE_BIGQUERY.TASK_LOAD_BIGQUERY RESUME; --SUSPEND   


ALTER TASK IF EXISTS GN_DW.BRONZE_AGENCY.AGENCY_TASK_MASTER SUSPEND;
ALTER TASK IF EXISTS GN_DW.BRONZE_AGENCY.TASK_DGT SUSPEND;
ALTER TASK IF EXISTS GN_DW.BRONZE_AGENCY.TASK_REBRDC SUSPEND;
ALTER TASK IF EXISTS GN_DW.BRONZE_AGENCY.TASK_VIDEO SUSPEND;



-- 디지털 대행사 TASK
CREATE OR REPLACE TASK GN_DW.BRONZE_AGENCY.TASK_DGT
    WAREHOUSE = GN_DW_ETL_WH
    AFTER GN_DW.BRONZE_AGENCY.AGENCY_TASK_MASTER
AS
BEGIN
    --매월 10일과 11일은 전월데이터까지 재인입
    IF (DAY(CURRENT_DATE()) IN (10, 11)) THEN
        -- 전월 데이터 처리
        CALL GN_DW.BRONZE_AGENCY.SP_LOAD_DGT_AD_FROM_GSHEET(
            TO_CHAR(
                DATEADD(MONTH, -1, CURRENT_DATE()),
                'YYYYMM'
            )
        );
        CALL GN_DW.BRONZE_AGENCY.SP_LOAD_DGT_AD_FROM_GSHEET(TO_CHAR(CURRENT_DATE(), 'YYYYMM'));

    ELSE
        CALL GN_DW.BRONZE_AGENCY.SP_LOAD_DGT_AD_FROM_GSHEET(TO_CHAR(CURRENT_DATE(), 'YYYYMM'));
    END IF;
END;

