------------------------ 빅쿼리 -------------------------------------------------
-- 실행시점 기준 이틀전. 전일의 데이터가 익일 오전 11시경에 생성됨. 따라서 01시 기준 실행시에는 이틀전 데이터 타겟으로 해야함. 
CREATE OR REPLACE TASK GN_DW.BRONZE_BIGQUERY.TASK_LOAD_BIGQUERY
    WAREHOUSE = GN_DW_ETL_WH
    SCHEDULE = 'USING CRON 40 1 * * * Asia/Seoul'
AS
BEGIN
    CALL GN_DW.BRONZE_BIGQUERY.SP_LOAD_BIGQUERY(
        TO_CHAR(
            DATEADD(DAY, -2, CURRENT_DATE()),
            'YYYYMMDD'
        )
    );
    CALL GN_DW.BRONZE_BIGQUERY.SP_LOAD_BIGQUERY_REFINED_DATA(
        TO_CHAR(
            DATEADD(DAY, -2, CURRENT_DATE()),
            'YYYYMMDD'
        )
    );
END;


-- TASK 내역 조회
SELECT
    QUERY_ID,
    NAME,
    STATE,
    ERROR_CODE,
    ERROR_MESSAGE,
    QUERY_TEXT,
    QUERY_START_TIME
FROM TABLE(
    GN_DW.INFORMATION_SCHEMA.TASK_HISTORY(
        RESULT_LIMIT => 200
    )
)
WHERE NAME like 'TASK%'
ORDER BY QUERY_START_TIME DESC;