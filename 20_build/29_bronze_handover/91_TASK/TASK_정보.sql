CREATE OR REPLACE TASK GN_DW.BRONZE_AGENCY.AGENCY_TASK_MASTER
    WAREHOUSE = GN_DW_ETL_WH
    SCHEDULE = 'USING CRON 10 1 * * * Asia/Seoul'
AS
