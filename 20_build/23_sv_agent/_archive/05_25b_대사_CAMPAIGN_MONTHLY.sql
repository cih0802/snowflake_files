-- [1] 월별 합 = FMM 합(기대 = 모든 DIFF 0 · 전 월)
WITH f AS (
    SELECT BASE_MONTH_KEY AS MK,
           SUM(ACTIVE_CNT) AS A, SUM(PREV_MONTH_END_ACTIVE_CNT) AS P, SUM(STOP_CNT) AS ST,
           SUM(DEV_CNT) AS D, SUM(DECREASE_CNT) AS DC, SUM(CHURN_CNT) AS CH,
           SUM(PAID_FEE_BILLABLE) AS PF, SUM(UNPAID_BILLED_AMT) AS UP
    FROM GN_DW.GOLD.FACT_CAMPAIGN_MONTHLY
    GROUP BY 1
), m AS (
    SELECT MONTH_KEY AS MK,
           SUM(ACTIVE_CNT) AS A, SUM(PREV_MONTH_END_ACTIVE_CNT) AS P, SUM(STOP_AMT_CNT) AS ST,
           SUM(DEV_CNT) AS D, SUM(DECREASE_CNT) AS DC, SUM(CHURN_CNT) AS CH,
           SUM(PAID_FEE_BILLABLE) AS PF, SUM(UNPAID_BILLED_AMT) AS UP
    FROM GN_DW.GOLD.FACT_MEMBER_MONTHLY
    WHERE MONTH_KEY > 0
    GROUP BY 1
)
SELECT COUNT(*) AS MONTHS,
       COUNT_IF(ABS(COALESCE(f.A, 0) - COALESCE(m.A, 0)) > 0.001) AS BAD_ACTIVE,
       COUNT_IF(ABS(COALESCE(f.P, 0) - COALESCE(m.P, 0)) > 0.001) AS BAD_PREV,
       COUNT_IF(ABS(COALESCE(f.ST, 0) - COALESCE(m.ST, 0)) > 0.001) AS BAD_STOP,
       COUNT_IF(ABS(COALESCE(f.D, 0) - COALESCE(m.D, 0)) > 0.001) AS BAD_DEV,
       COUNT_IF(ABS(COALESCE(f.DC, 0) - COALESCE(m.DC, 0)) > 0.001) AS BAD_DEC,
       COUNT_IF(ABS(COALESCE(f.CH, 0) - COALESCE(m.CH, 0)) > 0.001) AS BAD_CHURN,
       COUNT_IF(ABS(COALESCE(f.PF, 0) - COALESCE(m.PF, 0)) > 0.5) AS BAD_PAID,
       COUNT_IF(ABS(COALESCE(f.UP, 0) - COALESCE(m.UP, 0)) > 0.5) AS BAD_UNPAID
FROM m FULL OUTER JOIN f ON f.MK = m.MK;

-- [2] 누계·연도초 = FACT_CAMPAIGN_CUM_STOP(기대 DIFF 0 · 기준월 202609)
SELECT (SELECT SUM(CUM_STOP_CNT) FROM GN_DW.GOLD.FACT_CAMPAIGN_MONTHLY WHERE BASE_MONTH_KEY = 202609)
     - (SELECT SUM(CUM_STOP_CNT) FROM GN_DW.GOLD.FACT_CAMPAIGN_CUM_STOP WHERE BASE_MONTH_KEY = 202609) AS DIFF_CUM_STOP,
       (SELECT SUM(CUM_DEV_CNT) FROM GN_DW.GOLD.FACT_CAMPAIGN_MONTHLY WHERE BASE_MONTH_KEY = 202609)
     - (SELECT SUM(CUM_DEV_CNT) FROM GN_DW.GOLD.FACT_CAMPAIGN_CUM_STOP WHERE BASE_MONTH_KEY = 202609) AS DIFF_CUM_DEV,
       (SELECT SUM(YEAR_START_ACTIVE_CNT) FROM GN_DW.GOLD.FACT_CAMPAIGN_MONTHLY WHERE BASE_MONTH_KEY = 202609)
     - (SELECT SUM(YEAR_START_ACTIVE_CNT) FROM GN_DW.GOLD.FACT_CAMPAIGN_CUM_STOP WHERE BASE_MONTH_KEY = 202609) AS DIFF_YS;

-- [3] 미매핑 비중(참고 · 기준월 202609) — 캠페인 SK=0 · 납입방식 SK=0
SELECT SUM(IFF(CAMPAIGN_SK = 0, ACTIVE_CNT, 0)) / NULLIF(SUM(ACTIVE_CNT), 0) * 100 AS ACTIVE_CAMPAIGN_UNMAPPED_PCT,
       SUM(IFF(CAMPAIGN_SK = 0, STOP_CNT, 0)) / NULLIF(SUM(STOP_CNT), 0) * 100     AS STOP_CAMPAIGN_UNMAPPED_PCT,
       SUM(IFF(CAMPAIGN_SK = 0, PAID_FEE_BILLABLE, 0)) / NULLIF(SUM(PAID_FEE_BILLABLE), 0) * 100 AS PAID_CAMPAIGN_UNMAPPED_PCT,
       SUM(IFF(PAYMENT_SK = 0, ACTIVE_CNT, 0)) / NULLIF(SUM(ACTIVE_CNT), 0) * 100  AS ACTIVE_PAYMENT_UNMAPPED_PCT
FROM GN_DW.GOLD.FACT_CAMPAIGN_MONTHLY
WHERE BASE_MONTH_KEY = 202609;

-- [4] 음성 — 여러 기준월 SUM 은 누계가 겹친다(기대 = SUM_1_9 > ONLY_09 · 기준월 고정 규칙의 근거)
SELECT (SELECT SUM(CUM_STOP_CNT) FROM GN_DW.GOLD.FACT_CAMPAIGN_MONTHLY WHERE BASE_MONTH_KEY = 202609) AS ONLY_09,
       (SELECT SUM(CUM_STOP_CNT) FROM GN_DW.GOLD.FACT_CAMPAIGN_MONTHLY WHERE BASE_MONTH_KEY BETWEEN 202601 AND 202609) AS SUM_1_9;
