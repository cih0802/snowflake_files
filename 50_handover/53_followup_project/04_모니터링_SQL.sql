-- 자리표시자 <DB> · <PIPELINE> 치환 · ⚠️ ACCOUNT_USAGE 는 수 시간 지연 — 당일은 제외한다

-- [비용 1] 서비스별 크레딧 — 최근 30일 (청구 대조용 · metering)
SELECT SERVICE_TYPE,
       ROUND(SUM(CREDITS_USED), 2) AS CREDITS,
       ROUND(SUM(CREDITS_USED) / NULLIF(SUM(SUM(CREDITS_USED)) OVER (), 0) * 100, 1) AS PCT
FROM SNOWFLAKE.ACCOUNT_USAGE.METERING_HISTORY
WHERE START_TIME >= DATEADD(DAY, -30, CURRENT_DATE())
  AND START_TIME < CURRENT_DATE()
GROUP BY 1
ORDER BY CREDITS DESC;

-- [비용 2] 웨어하우스별 크레딧 — 최근 30일
SELECT WAREHOUSE_NAME,
       ROUND(SUM(CREDITS_USED), 2) AS CREDITS,
       ROUND(SUM(CREDITS_USED_CLOUD_SERVICES), 2) AS CREDITS_CLOUD
FROM SNOWFLAKE.ACCOUNT_USAGE.WAREHOUSE_METERING_HISTORY
WHERE START_TIME >= DATEADD(DAY, -30, CURRENT_DATE())
  AND START_TIME < CURRENT_DATE()
GROUP BY 1
ORDER BY CREDITS DESC;

-- [비용 3] AI 도메인별 — 각 도메인의 정본 뷰만(인터페이스별 CoCo 뷰와 합산하면 2배)
SELECT 'CORTEX CODE' AS DOMAIN, ROUND(SUM(TOKEN_CREDITS), 4) AS CREDITS
FROM SNOWFLAKE.ACCOUNT_USAGE.SNOWFLAKE_COCO_USAGE_HISTORY
WHERE USAGE_TIME >= DATEADD(DAY, -30, CURRENT_DATE()) AND USAGE_TIME < CURRENT_DATE()
UNION ALL
SELECT 'CORTEX AGENT', ROUND(SUM(TOKEN_CREDITS), 4)
FROM SNOWFLAKE.ACCOUNT_USAGE.CORTEX_AGENT_USAGE_HISTORY
WHERE START_TIME >= DATEADD(DAY, -30, CURRENT_DATE()) AND START_TIME < CURRENT_DATE()
UNION ALL
SELECT 'SNOWFLAKE INTELLIGENCE', ROUND(SUM(TOKEN_CREDITS), 4)
FROM SNOWFLAKE.ACCOUNT_USAGE.SNOWFLAKE_INTELLIGENCE_USAGE_HISTORY
WHERE START_TIME >= DATEADD(DAY, -30, CURRENT_DATE()) AND START_TIME < CURRENT_DATE()
UNION ALL
SELECT 'AI FUNCTION', ROUND(SUM(TOKEN_CREDITS), 4)
FROM SNOWFLAKE.ACCOUNT_USAGE.CORTEX_AISQL_USAGE_HISTORY
WHERE USAGE_TIME >= DATEADD(DAY, -30, CURRENT_DATE()) AND USAGE_TIME < CURRENT_DATE();

-- [비용 4] 통제 객체 — 리소스 모니터 · 예산(클래스 인스턴스 · SHOW BUDGETS 는 실패한다)
SHOW RESOURCE MONITORS;
SHOW SNOWFLAKE.CORE.BUDGET INSTANCES IN ACCOUNT;

-- [배치 1] dbt 실행 — 최근 7일 (롤 · 상태 · 소요)
SELECT START_TIME, ROLE_NAME, EXECUTION_STATUS,
       ROUND(TOTAL_ELAPSED_TIME / 1000) AS SEC,
       SUBSTR(QUERY_TEXT, 1, 200) AS QUERY_PREVIEW,
       ERROR_MESSAGE
FROM SNOWFLAKE.ACCOUNT_USAGE.QUERY_HISTORY
WHERE START_TIME >= DATEADD(DAY, -7, CURRENT_TIMESTAMP())
  AND QUERY_TEXT ILIKE 'EXECUTE DBT PROJECT%'
ORDER BY START_TIME DESC;

-- [배치 2] Task · Alert 상태
SHOW TASKS IN DATABASE <DB>;
SHOW ALERTS IN DATABASE <DB>;

-- [배치 3] dbt 테스트 실패 저장 테이블 — dbt 롤 소유 테이블 전부(이름 목록을 고정하지 않는다)
SELECT TABLE_SCHEMA, TABLE_NAME, ROW_COUNT, LAST_ALTERED
FROM <DB>.INFORMATION_SCHEMA.TABLES
WHERE TABLE_SCHEMA = 'OPS'
  AND TABLE_OWNER = '<PRJ>_DBT'
  AND ROW_COUNT > 0
ORDER BY ROW_COUNT DESC;

-- [보안 1] 최근 7일 로그인 실패
SELECT USER_NAME, CLIENT_IP, ERROR_MESSAGE, EVENT_TIMESTAMP
FROM SNOWFLAKE.ACCOUNT_USAGE.LOGIN_HISTORY
WHERE EVENT_TIMESTAMP >= DATEADD(DAY, -7, CURRENT_TIMESTAMP())
  AND IS_SUCCESS = 'NO'
ORDER BY EVENT_TIMESTAMP DESC;

-- [보안 2] 최근 7일 권한 변경 건수 (평상시 수준을 먼저 재 두고 급증을 본다)
SELECT START_TIME::DATE AS DAY, QUERY_TYPE, COUNT(*) AS N
FROM SNOWFLAKE.ACCOUNT_USAGE.QUERY_HISTORY
WHERE START_TIME >= DATEADD(DAY, -7, CURRENT_TIMESTAMP())
  AND QUERY_TYPE IN ('GRANT', 'REVOKE')
GROUP BY 1, 2
ORDER BY 1, 2;

-- [보안 3] 마스킹 정책 부착 현황
SELECT POLICY_NAME, REF_DATABASE_NAME, REF_SCHEMA_NAME, REF_ENTITY_NAME, REF_COLUMN_NAME
FROM SNOWFLAKE.ACCOUNT_USAGE.POLICY_REFERENCES
WHERE POLICY_KIND = 'MASKING_POLICY'
ORDER BY 1, 2, 3, 4, 5;
