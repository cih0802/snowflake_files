-- Q01 dbt 실행 이력 — 최근 7일 (롤 · 상태 · 오류)
SELECT START_TIME, ROLE_NAME, USER_NAME, EXECUTION_STATUS, ERROR_CODE,
       LEFT(ERROR_MESSAGE, 300) AS ERROR_MESSAGE,
       ROUND(TOTAL_ELAPSED_TIME / 1000, 1) AS ELAPSED_SEC,
       LEFT(QUERY_TEXT, 200) AS QUERY_TEXT
FROM SNOWFLAKE.ACCOUNT_USAGE.QUERY_HISTORY
WHERE QUERY_TEXT ILIKE 'EXECUTE DBT PROJECT%'
  AND START_TIME > DATEADD(day, -7, CURRENT_TIMESTAMP())
ORDER BY START_TIME DESC
LIMIT 50;

-- Q02 dbt 프로젝트 배포 상태
SHOW DBT PROJECTS IN SCHEMA GN_DW.OPS;
SHOW VERSIONS IN DBT PROJECT GN_DW.OPS.DW_PIPELINE;

-- Q03 dbt 테스트 실패 저장 테이블 (store_failures · OPS 의 GN_DW_DBT 소유 전부 · 기대 = 전건 0행)
--   🔴 [2026-10-20] 이름을 하드코딩하지 않는다 — 종전 6종 목록이 ACCEPTED_VALUES_*·NOT_NULL_* 4종(실패 행 존재)을 놓쳤다
SELECT TABLE_NAME AS MONITOR, ROW_COUNT AS ROWS_, LAST_ALTERED
FROM GN_DW.INFORMATION_SCHEMA.TABLES
WHERE TABLE_SCHEMA = 'OPS'
  AND TABLE_OWNER = 'GN_DW_DBT'
  AND TABLE_TYPE = 'BASE TABLE'
ORDER BY ROW_COUNT DESC, TABLE_NAME;

-- Q04 BIGQUERY 체인 일자 수 대조 (02_dbt_parse_compile_build.sql [3-3-a] · 기대 = 4행의 DAYS_ 가 같다)
SELECT 'SRC  BIGQUERY_REFINED_DATA' AS LAYER,
       COUNT(DISTINCT TRY_TO_DATE(EVENT_DATE, 'YYYYMMDD')) AS DAYS_, COUNT(*) AS ROWS_
FROM GN_DW.SILVER.BIGQUERY_REFINED_DATA
WHERE EVENT_DATE IS NOT NULL
UNION ALL SELECT 'SILVER BIGQUERY_BASIC', COUNT(DISTINCT EVENT_DT), COUNT(*) FROM GN_DW.SILVER.BIGQUERY_BASIC
UNION ALL SELECT 'SILVER BIGQUERY_EVENT', COUNT(DISTINCT EVENT_DT), COUNT(*) FROM GN_DW.SILVER.BIGQUERY_EVENT
UNION ALL SELECT 'GOLD  FACT_BIGQUERY_BEHAVIOR', COUNT(DISTINCT DATE_SK), COUNT(*) FROM GN_DW.GOLD.FACT_BIGQUERY_BEHAVIOR
ORDER BY 1;

-- Q05 Task · Alert 상태와 최근 이력
SHOW TASKS IN DATABASE GN_DW;
SELECT NAME, STATE, SCHEDULED_TIME, COMPLETED_TIME, LEFT(ERROR_MESSAGE, 300) AS ERROR_MESSAGE
FROM TABLE(GN_DW.INFORMATION_SCHEMA.TASK_HISTORY(
       SCHEDULED_TIME_RANGE_START => DATEADD('day', -6, CURRENT_TIMESTAMP()), RESULT_LIMIT => 100))
ORDER BY SCHEDULED_TIME DESC;
SHOW ALERTS IN DATABASE GN_DW;
SELECT NAME, STATE, SCHEDULED_TIME, COMPLETED_TIME, LEFT(SQL_ERROR_MESSAGE, 300) AS SQL_ERROR_MESSAGE
FROM TABLE(GN_DW.INFORMATION_SCHEMA.ALERT_HISTORY(
       SCHEDULED_TIME_RANGE_START => DATEADD('day', -6, CURRENT_TIMESTAMP())))
ORDER BY SCHEDULED_TIME DESC;

-- Q06 MSTR 적재 상태 (프로시저 적재 · dbt 와 별개)
