-- Q08 객체 소유 혼입 점검 (dbt 를 다른 롤로 돌렸을 때 · 기대 = GOLD 뷰·OPS 감사 테이블 = GN_DW_DBT)
SELECT TABLE_SCHEMA, TABLE_TYPE, TABLE_OWNER, COUNT(*) AS N
FROM GN_DW.INFORMATION_SCHEMA.TABLES
WHERE TABLE_SCHEMA IN ('SILVER', 'GOLD', 'OPS', 'SERVING')
GROUP BY 1, 2, 3
ORDER BY 1, 2, 3;

-- Q09 BRONZE 원천 신선도 (06_RUNBOOK §1.3 · 대표 = 정기회원 마스터 · 기대 = HOURS_STALE ≤ 24 · N = N_KEY)
SELECT 'BRONZE_CRM.TM_MM_FDRM_MBER_INFO' AS TABLE_NM, MAX(_LOAD_DT) AS LAST_LOADED,
       DATEDIFF(HOUR, MAX(_LOAD_DT), CURRENT_TIMESTAMP()) AS HOURS_STALE,
       COUNT(*) AS N, COUNT(DISTINCT MBER_NO) AS N_KEY
FROM GN_DW.BRONZE_CRM.TM_MM_FDRM_MBER_INFO;

