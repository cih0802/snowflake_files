-- Q02 GN_DW 스키마별 객체 수
SELECT s.SCHEMA_NAME,
       COUNT_IF(t.TABLE_TYPE = 'BASE TABLE' AND t.IS_DYNAMIC = 'NO') AS BASE_TABLES,
       COUNT_IF(t.IS_DYNAMIC = 'YES') AS DYNAMIC_TABLES,
       COUNT_IF(t.TABLE_TYPE = 'VIEW') AS VIEWS,
       COUNT_IF(t.TABLE_TYPE = 'MATERIALIZED VIEW') AS MVIEWS,
       COUNT(t.TABLE_NAME) AS TOTAL
FROM GN_DW.INFORMATION_SCHEMA.SCHEMATA s
LEFT JOIN GN_DW.INFORMATION_SCHEMA.TABLES t
  ON t.TABLE_SCHEMA = s.SCHEMA_NAME
WHERE s.SCHEMA_NAME <> 'INFORMATION_SCHEMA'
GROUP BY 1
ORDER BY 1;

-- Q03 프로시저·함수·스테이지 수
SELECT 'PROCEDURE' AS T, PROCEDURE_SCHEMA AS S, COUNT(*) AS N
FROM GN_DW.INFORMATION_SCHEMA.PROCEDURES GROUP BY 1, 2
UNION ALL
SELECT 'FUNCTION', FUNCTION_SCHEMA, COUNT(*)
FROM GN_DW.INFORMATION_SCHEMA.FUNCTIONS GROUP BY 1, 2
UNION ALL
SELECT 'STAGE', STAGE_SCHEMA, COUNT(*)
FROM GN_DW.INFORMATION_SCHEMA.STAGES GROUP BY 1, 2
ORDER BY 1, 2;

