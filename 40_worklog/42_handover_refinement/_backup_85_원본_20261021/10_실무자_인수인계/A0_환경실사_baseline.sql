SELECT POLICY_KIND, POLICY_NAME, REF_SCHEMA_NAME, COUNT(*) AS N
FROM SNOWFLAKE.ACCOUNT_USAGE.POLICY_REFERENCES
WHERE REF_DATABASE_NAME = 'GN_DW'
