FROM SNOWFLAKE.ACCOUNT_USAGE.TAG_REFERENCES
WHERE OBJECT_DATABASE = 'GN_DW'
  AND OBJECT_DELETED IS NULL
GROUP BY 1, 2, 3, 4;
SELECT REF_ENTITY_DOMAIN, REF_SCHEMA_NAME, COUNT(*) AS N, COUNT(DISTINCT REF_ENTITY_NAME) AS TABLES
FROM SNOWFLAKE.ACCOUNT_USAGE.DATA_METRIC_FUNCTION_REFERENCES
WHERE REF_DATABASE_NAME = 'GN_DW'
GROUP BY 1, 2;

-- Q09 [ENV] 데이터 차이 축 — SILVER.BIGQUERY_REFINED_DATA 적재 범위(외부 Python 적재 · 운영계와 범위가 다르다)
SELECT COUNT(*) AS N_ROWS, MIN(EVENT_DATE) AS MIN_D, MAX(EVENT_DATE) AS MAX_D, COUNT(DISTINCT EVENT_DATE) AS N_DAYS
FROM GN_DW.SILVER.BIGQUERY_REFINED_DATA;

-- Q10 [ENV] 실행 이력 — Task(존재 이력 포함) · dbt 실행(최근 30일 · 롤별)
SELECT SCHEMA_NAME, REGEXP_REPLACE(NAME, '_[0-9A-F]{32}.*$', '_*') AS NAME_PATTERN, STATE,
       COUNT(*) AS N, MIN(SCHEDULED_TIME) AS FIRST_RUN, MAX(SCHEDULED_TIME) AS LAST_RUN
FROM SNOWFLAKE.ACCOUNT_USAGE.TASK_HISTORY
WHERE DATABASE_NAME = 'GN_DW'
GROUP BY 1, 2, 3
ORDER BY 1, 2;
SELECT ROLE_NAME, EXECUTION_STATUS, COUNT(*) AS N, MIN(START_TIME) AS FIRST_T, MAX(START_TIME) AS LAST_T
FROM SNOWFLAKE.ACCOUNT_USAGE.QUERY_HISTORY
WHERE QUERY_TEXT ILIKE 'EXECUTE DBT PROJECT%'
  AND START_TIME > DATEADD(day, -30, CURRENT_TIMESTAMP())
GROUP BY 1, 2
ORDER BY 1, 2;
