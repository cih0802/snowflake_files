-- Q01 [일] 서비스별 크레딧 — 최근 7일 일별 (ACCOUNT_USAGE 지연 최대 수 시간)
SELECT USAGE_DATE, SERVICE_TYPE, ROUND(SUM(CREDITS_BILLED), 4) AS CREDITS_BILLED
FROM SNOWFLAKE.ACCOUNT_USAGE.METERING_DAILY_HISTORY
WHERE USAGE_DATE >= DATEADD(day, -7, CURRENT_DATE())
GROUP BY 1, 2
ORDER BY 1 DESC, 3 DESC;

-- Q02 [주] 웨어하우스별 크레딧 — 최근 7일
SELECT WAREHOUSE_NAME, ROUND(SUM(CREDITS_USED), 4) AS CREDITS_USED
FROM SNOWFLAKE.ACCOUNT_USAGE.WAREHOUSE_METERING_HISTORY
WHERE START_TIME >= DATEADD(day, -7, CURRENT_TIMESTAMP())
GROUP BY 1
ORDER BY 2 DESC;

-- Q03 [주] AI 사용 — Agent · Snowflake Intelligence · CoCo 사용자별 최근 7일
SELECT 'AGENT' AS SURFACE, AGENT_NAME AS OBJ, USER_NAME, COUNT(*) AS N_REQUEST, ROUND(SUM(TOKEN_CREDITS), 4) AS CREDITS
FROM SNOWFLAKE.ACCOUNT_USAGE.CORTEX_AGENT_USAGE_HISTORY
WHERE START_TIME >= DATEADD(day, -7, CURRENT_TIMESTAMP())
GROUP BY 1, 2, 3
UNION ALL
SELECT 'SNOWFLAKE_INTELLIGENCE', AGENT_NAME, USER_NAME, COUNT(*), ROUND(SUM(TOKEN_CREDITS), 4)
FROM SNOWFLAKE.ACCOUNT_USAGE.SNOWFLAKE_INTELLIGENCE_USAGE_HISTORY
WHERE START_TIME >= DATEADD(day, -7, CURRENT_TIMESTAMP())
GROUP BY 1, 2, 3
UNION ALL
SELECT 'COCO', NULL, u.NAME, COUNT(*), ROUND(SUM(h.TOKEN_CREDITS), 4)
FROM SNOWFLAKE.ACCOUNT_USAGE.SNOWFLAKE_COCO_USAGE_HISTORY h
LEFT JOIN SNOWFLAKE.ACCOUNT_USAGE.USERS u ON u.USER_ID = h.USER_ID
WHERE h.USAGE_TIME >= DATEADD(day, -7, CURRENT_TIMESTAMP())
GROUP BY 1, 2, 3
ORDER BY 1, 5 DESC;

-- Q04 [주] 권한 변경 — 최근 7일 GN_DW 롤 대상 부여·회수
SELECT CREATED_ON, MODIFIED_ON, DELETED_ON, GRANTEE_NAME, PRIVILEGE, GRANTED_ON, NAME, GRANTED_BY
FROM SNOWFLAKE.ACCOUNT_USAGE.GRANTS_TO_ROLES
WHERE (CREATED_ON >= DATEADD(day, -7, CURRENT_TIMESTAMP()) OR DELETED_ON >= DATEADD(day, -7, CURRENT_TIMESTAMP()))
  AND GRANTEE_NAME LIKE 'GN_DW%'
ORDER BY COALESCE(DELETED_ON, CREATED_ON) DESC
LIMIT 200;
SELECT CREATED_ON, DELETED_ON, GRANTEE_NAME AS USER_NAME, ROLE AS ROLE_NAME, GRANTED_BY
FROM SNOWFLAKE.ACCOUNT_USAGE.GRANTS_TO_USERS
WHERE CREATED_ON >= DATEADD(day, -7, CURRENT_TIMESTAMP()) OR DELETED_ON >= DATEADD(day, -7, CURRENT_TIMESTAMP())
ORDER BY COALESCE(DELETED_ON, CREATED_ON) DESC;

-- Q05 [주] 실패 쿼리 — 최근 7일 GN_DW 롤별 오류 상위
SELECT ROLE_NAME, ERROR_CODE, LEFT(ERROR_MESSAGE, 200) AS ERROR_MESSAGE, COUNT(*) AS N, MAX(START_TIME) AS LAST_T
FROM SNOWFLAKE.ACCOUNT_USAGE.QUERY_HISTORY
WHERE START_TIME >= DATEADD(day, -7, CURRENT_TIMESTAMP())
  AND EXECUTION_STATUS = 'FAIL'
  AND ROLE_NAME LIKE 'GN_DW%'
GROUP BY 1, 2, 3
ORDER BY 4 DESC
LIMIT 50;

-- Q06 [월] 사용자 · 롤 보유 현황 (온보딩/오프보딩 누락 · 장기 미접속)
SELECT u.NAME AS USER_NAME, u.DISABLED, u.DEFAULT_ROLE, u.LAST_SUCCESS_LOGIN,
       LISTAGG(g.ROLE, ',') WITHIN GROUP (ORDER BY g.ROLE) AS ROLES
FROM SNOWFLAKE.ACCOUNT_USAGE.USERS u
LEFT JOIN SNOWFLAKE.ACCOUNT_USAGE.GRANTS_TO_USERS g
  ON g.GRANTEE_NAME = u.NAME AND g.DELETED_ON IS NULL
WHERE u.DELETED_ON IS NULL
GROUP BY 1, 2, 3, 4
ORDER BY 4 NULLS FIRST;

-- Q07 [월] 객체 수 기준선 — A0 Q02 와 같은 축(달라지면 원인 확인)
SELECT TABLE_SCHEMA, TABLE_TYPE, COUNT(*) AS N
FROM GN_DW.INFORMATION_SCHEMA.TABLES
WHERE TABLE_SCHEMA <> 'INFORMATION_SCHEMA'
GROUP BY 1, 2
ORDER BY 1, 2;
