-- Q01 #1 개발(명) — 플래그 합 vs 고유 회원 (사건 팩트 · 월 팩트)
SELECT 'FACT_MEMBER_EVENT' AS SRC,
       SUM(DEV_MEMBERS) AS SUM_FLAG,
       COUNT(DISTINCT IFF(DEV_CNT > 0, MEMBER_DK, NULL)) AS DISTINCT_DEV_MEMBERS,
       SUM(DEV_CNT) AS DEV_CNT_SUM
FROM GN_DW.GOLD.FACT_MEMBER_EVENT
UNION ALL
SELECT 'FACT_MEMBER_MONTHLY',
       SUM(DEV_MEMBERS),
       COUNT(DISTINCT IFF(DEV_CNT > 0, MEMBER_DK, NULL)),
       SUM(DEV_CNT)
FROM GN_DW.GOLD.FACT_MEMBER_MONTHLY;

-- Q02 #2 발송 건수 vs 고유 회원수
SELECT COUNT(*) AS SEND_ROWS,
       COUNT(DISTINCT MEMBER_DK) AS DISTINCT_SEND_MEMBERS
FROM GN_DW.GOLD.FACT_MESSAGE_DISPATCH;

-- Q03 #3·#4 회비 납부율 · 미납 청구액 (월 팩트)
SELECT SUM(BILLED_AMT) AS BILLED_AMT,
       SUM(PAID_FEE_BILLABLE) AS PAID_FEE_BILLABLE,
       ROUND(SUM(PAID_FEE_BILLABLE) / NULLIF(SUM(BILLED_AMT), 0) * 100, 2) AS PAYMENT_RATE_FEE_PCT,
       SUM(UNPAID_BILLED_AMT) AS UNPAID_BILLED_AMT
FROM GN_DW.GOLD.FACT_MEMBER_MONTHLY;

-- Q04 #6 형제 팩트 — 청구 총계 일치(따로 집계하면 같아야 한다 · 조인하면 부푼다)
SELECT 'FACT_MEMBER_MONTHLY' AS SRC, SUM(BILLED_AMT) AS BILLED_AMT, COUNT(*) AS N_ROWS
FROM GN_DW.GOLD.FACT_MEMBER_MONTHLY
UNION ALL
SELECT 'FACT_MEMBER_FEE', SUM(BILLED_AMT), COUNT(*)
FROM GN_DW.GOLD.FACT_MEMBER_FEE;

-- Q05 소비 객체 — SV · Agent · Streamlit 수
SELECT 'SEMANTIC_VIEW' AS K, COUNT(*) AS N FROM GN_DW.INFORMATION_SCHEMA.SEMANTIC_VIEWS
UNION ALL
SELECT 'STREAMLIT', COUNT(*) FROM GN_DW.INFORMATION_SCHEMA.STREAMLITS;
SHOW AGENTS IN SCHEMA GN_DW.SERVING;
