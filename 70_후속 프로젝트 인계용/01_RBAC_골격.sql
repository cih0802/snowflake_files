-- N07 · RBAC 골격 — 🔴 미실행 템플릿 (자리표시자 <PRJ> · <DB> · <WH_*> 를 치환한 뒤 검토 후 실행)
-- 원본 = GN_DW 07_ENVIRONMENT_RBAC_setup.sql · A2_롤별_접근권한_설계.csv (2026-10-20) · 설명 = 00_README_N07.md
-- 원칙: 소유 = <PRJ>_ADMIN · 변환 실행 = <PRJ>_DBT · 소비 롤은 소비 계층만 · FUTURE GRANT 로 신규 객체 자동 반영

-- [0] 롤 (SECURITYADMIN) -------------------------------------------------
USE ROLE SECURITYADMIN;
CREATE ROLE IF NOT EXISTS <PRJ>_ADMIN    COMMENT = '객체 소유 · DDL · SV/Agent 배포 · 정책';
CREATE ROLE IF NOT EXISTS <PRJ>_ENGINEER COMMENT = '개발 · 조회 · SILVER 작업';
CREATE ROLE IF NOT EXISTS <PRJ>_DBT      COMMENT = 'dbt 실행 전용(SILVER/GOLD 적재 · 뷰 생성)';
CREATE ROLE IF NOT EXISTS <PRJ>_LOADER   COMMENT = '원천(BRONZE) 적재 전용 — 외부 적재팀';
CREATE ROLE IF NOT EXISTS <PRJ>_ANALYST  COMMENT = '분석가 — GOLD·SILVER·SERVING 조회';
CREATE ROLE IF NOT EXISTS <PRJ>_VIEWER   COMMENT = '현업 — GOLD·SERVING 조회 · Agent 사용';
CREATE ROLE IF NOT EXISTS <PRJ>_SERVICE  COMMENT = '앱·서비스 계정 — VIEWER 와 같은 범위';
GRANT ROLE <PRJ>_ADMIN TO ROLE SYSADMIN;   -- 「ADMIN 이상」 = SYSADMIN · ACCOUNTADMIN 이 상속

-- [1] 웨어하우스 (SYSADMIN) — 용도별 분리 ------------------------------------
USE ROLE SYSADMIN;
CREATE WAREHOUSE IF NOT EXISTS <WH_DEV>       WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60  AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;
CREATE WAREHOUSE IF NOT EXISTS <WH_ETL>       WAREHOUSE_SIZE = 'SMALL'  AUTO_SUSPEND = 60  AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;
CREATE WAREHOUSE IF NOT EXISTS <WH_ANALYTICS> WAREHOUSE_SIZE = 'MEDIUM' AUTO_SUSPEND = 300 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;
GRANT USAGE ON WAREHOUSE <WH_DEV>       TO ROLE <PRJ>_ADMIN;
GRANT USAGE ON WAREHOUSE <WH_DEV>       TO ROLE <PRJ>_ENGINEER;
GRANT USAGE ON WAREHOUSE <WH_ETL>       TO ROLE <PRJ>_DBT;
GRANT USAGE ON WAREHOUSE <WH_ETL>       TO ROLE <PRJ>_LOADER;
GRANT USAGE ON WAREHOUSE <WH_ANALYTICS> TO ROLE <PRJ>_ANALYST;
GRANT USAGE ON WAREHOUSE <WH_ANALYTICS> TO ROLE <PRJ>_VIEWER;
GRANT USAGE ON WAREHOUSE <WH_ANALYTICS> TO ROLE <PRJ>_SERVICE;

-- [2] DB · 스키마 (소유 = ADMIN) -------------------------------------------
CREATE DATABASE IF NOT EXISTS <DB>;
GRANT OWNERSHIP ON DATABASE <DB> TO ROLE <PRJ>_ADMIN COPY CURRENT GRANTS;
USE ROLE <PRJ>_ADMIN;
CREATE SCHEMA IF NOT EXISTS <DB>.BRONZE_<SRC>;   -- 원천별 1개
CREATE SCHEMA IF NOT EXISTS <DB>.SILVER;
CREATE SCHEMA IF NOT EXISTS <DB>.GOLD;
CREATE SCHEMA IF NOT EXISTS <DB>.SERVING;        -- SV · Agent · 소비 뷰
CREATE SCHEMA IF NOT EXISTS <DB>.OPS;            -- dbt 프로젝트 · 감사 · 알림 · 비용 (소비 롤 비공개)
CREATE SCHEMA IF NOT EXISTS <DB>.SECURITY;       -- 마스킹 · 행 접근 정책 · 태그

-- [3] DB USAGE -------------------------------------------------------------
GRANT USAGE ON DATABASE <DB> TO ROLE <PRJ>_ENGINEER;
GRANT USAGE ON DATABASE <DB> TO ROLE <PRJ>_DBT;
GRANT USAGE ON DATABASE <DB> TO ROLE <PRJ>_LOADER;
GRANT USAGE ON DATABASE <DB> TO ROLE <PRJ>_ANALYST;
GRANT USAGE ON DATABASE <DB> TO ROLE <PRJ>_VIEWER;
GRANT USAGE ON DATABASE <DB> TO ROLE <PRJ>_SERVICE;

-- [4] BRONZE — LOADER 쓰기 · DBT/ENGINEER 읽기 · ANALYST 는 요건이 있을 때만 -------
GRANT USAGE ON SCHEMA <DB>.BRONZE_<SRC> TO ROLE <PRJ>_LOADER;
GRANT INSERT, UPDATE ON FUTURE TABLES IN SCHEMA <DB>.BRONZE_<SRC> TO ROLE <PRJ>_LOADER;
GRANT USAGE ON SCHEMA <DB>.BRONZE_<SRC> TO ROLE <PRJ>_DBT;
GRANT SELECT ON FUTURE TABLES IN SCHEMA <DB>.BRONZE_<SRC> TO ROLE <PRJ>_DBT;
GRANT USAGE ON SCHEMA <DB>.BRONZE_<SRC> TO ROLE <PRJ>_ENGINEER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA <DB>.BRONZE_<SRC> TO ROLE <PRJ>_ENGINEER;
-- 🔴 원천에 개인정보가 있으면 BRONZE 를 소비 롤에 열기 전에 마스킹 정책부터(N07 05 규약 §4)

-- [5] SILVER · GOLD — DBT 적재 · 소비 롤 조회 ---------------------------------
GRANT USAGE ON SCHEMA <DB>.SILVER TO ROLE <PRJ>_DBT;
GRANT USAGE ON SCHEMA <DB>.GOLD   TO ROLE <PRJ>_DBT;
GRANT INSERT, UPDATE, DELETE, TRUNCATE, SELECT ON FUTURE TABLES IN SCHEMA <DB>.SILVER TO ROLE <PRJ>_DBT;
GRANT INSERT, UPDATE, DELETE, TRUNCATE, SELECT ON FUTURE TABLES IN SCHEMA <DB>.GOLD   TO ROLE <PRJ>_DBT;
GRANT CREATE VIEW ON SCHEMA <DB>.GOLD TO ROLE <PRJ>_DBT;          -- dbt 뷰 모델
GRANT USAGE ON SCHEMA <DB>.GOLD TO ROLE <PRJ>_ANALYST;
GRANT USAGE ON SCHEMA <DB>.GOLD TO ROLE <PRJ>_VIEWER;
GRANT USAGE ON SCHEMA <DB>.GOLD TO ROLE <PRJ>_SERVICE;
GRANT SELECT ON FUTURE TABLES IN SCHEMA <DB>.GOLD TO ROLE <PRJ>_ANALYST;
GRANT SELECT ON FUTURE VIEWS  IN SCHEMA <DB>.GOLD TO ROLE <PRJ>_ANALYST;
GRANT SELECT ON FUTURE TABLES IN SCHEMA <DB>.GOLD TO ROLE <PRJ>_VIEWER;
GRANT SELECT ON FUTURE VIEWS  IN SCHEMA <DB>.GOLD TO ROLE <PRJ>_VIEWER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA <DB>.GOLD TO ROLE <PRJ>_SERVICE;
GRANT SELECT ON FUTURE VIEWS  IN SCHEMA <DB>.GOLD TO ROLE <PRJ>_SERVICE;
GRANT USAGE ON SCHEMA <DB>.SILVER TO ROLE <PRJ>_ANALYST;
GRANT SELECT ON FUTURE TABLES IN SCHEMA <DB>.SILVER TO ROLE <PRJ>_ANALYST;

-- [6] SERVING — SV 는 FUTURE GRANT 가 없다 ⇒ 각 SV DDL 파일 끝에서 개별 GRANT -------
GRANT USAGE ON SCHEMA <DB>.SERVING TO ROLE <PRJ>_ANALYST;
GRANT USAGE ON SCHEMA <DB>.SERVING TO ROLE <PRJ>_VIEWER;
GRANT USAGE ON SCHEMA <DB>.SERVING TO ROLE <PRJ>_SERVICE;
-- (SV 파일 끝) GRANT SELECT, REFERENCES ON SEMANTIC VIEW <DB>.SERVING.<SV> TO ROLE <PRJ>_VIEWER;
-- (Agent 파일 끝) GRANT USAGE ON AGENT <DB>.SERVING.<AGENT> TO ROLE <PRJ>_VIEWER;

-- [7] OPS — 소비 롤 비공개 · DBT 는 dbt 프로젝트·테스트 저장용 ---------------------
GRANT USAGE, CREATE TABLE ON SCHEMA <DB>.OPS TO ROLE <PRJ>_DBT;
GRANT USAGE ON SCHEMA <DB>.OPS TO ROLE <PRJ>_ENGINEER;
-- 🔴 ANALYST · VIEWER · SERVICE 에는 OPS 를 주지 않는다(알림 수신자 이메일이 있다 · GN_DW DR-09)

-- [8] 계정 권한 (ACCOUNTADMIN · 필요한 것만) ------------------------------------
USE ROLE ACCOUNTADMIN;
GRANT EXECUTE TASK, EXECUTE MANAGED TASK ON ACCOUNT TO ROLE <PRJ>_DBT;
GRANT APPLY MASKING POLICY ON ACCOUNT TO ROLE <PRJ>_ADMIN;

