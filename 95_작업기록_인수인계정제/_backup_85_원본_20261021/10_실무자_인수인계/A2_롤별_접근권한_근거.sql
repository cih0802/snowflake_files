-- Q03 매트릭스 원본 — 롤 × 객체종류 × 스키마 × 권한 (직접 부여 · 상속 제외 · OWNERSHIP 포함)
SELECT GRANTEE_NAME AS ROLE_NAME,
       GRANTED_ON,
       COALESCE(TABLE_SCHEMA, CASE WHEN GRANTED_ON = 'SCHEMA' THEN NAME END) AS SCHEMA_NAME,
       PRIVILEGE,
       COUNT(*) AS N_OBJECTS
FROM SNOWFLAKE.ACCOUNT_USAGE.GRANTS_TO_ROLES
WHERE DELETED_ON IS NULL
  AND GRANTEE_NAME LIKE 'GN_DW%'
  AND GRANTED_TO = 'ROLE'
GROUP BY 1, 2, 3, 4
ORDER BY 1, 2, 3, 4;

-- Q04 GN_DW 객체 수(분모) — 스키마별 테이블·뷰 · SV · Agent (매트릭스 「전건 부여」 판정용)
SELECT TABLE_SCHEMA AS SCHEMA_NAME,
       COUNT_IF(TABLE_TYPE = 'BASE TABLE') AS N_TABLE,
       COUNT_IF(TABLE_TYPE = 'VIEW') AS N_VIEW
FROM GN_DW.INFORMATION_SCHEMA.TABLES
WHERE TABLE_SCHEMA <> 'INFORMATION_SCHEMA'
GROUP BY 1
ORDER BY 1;

