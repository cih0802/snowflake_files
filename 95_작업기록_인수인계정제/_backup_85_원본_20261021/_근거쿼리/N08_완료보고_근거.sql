-- Q01 계층별 테이블 · 뷰 · 행 수
SELECT CASE WHEN TABLE_SCHEMA LIKE 'BRONZE%' THEN 'BRONZE' ELSE TABLE_SCHEMA END AS LAYER,
       COUNT_IF(TABLE_TYPE = 'BASE TABLE') AS N_TABLES,
       COUNT_IF(TABLE_TYPE = 'VIEW') AS N_VIEWS,
       SUM(IFF(TABLE_TYPE = 'BASE TABLE', ROW_COUNT, 0)) AS N_ROWS
FROM GN_DW.INFORMATION_SCHEMA.TABLES
WHERE TABLE_SCHEMA IN ('BRONZE_CRM', 'BRONZE_AGENCY', 'BRONZE_ERP', 'BRONZE_BIGQUERY', 'BRONZE_GA4', 'BRONZE_GSC',
                       'SILVER', 'GOLD', 'ML', 'MSTR', 'SERVING')
GROUP BY 1
ORDER BY 1;

-- Q02 소비 객체 수 (SV · Streamlit)
SELECT 'SEMANTIC_VIEW' AS K, COUNT(*) AS N FROM GN_DW.INFORMATION_SCHEMA.SEMANTIC_VIEWS
UNION ALL
SELECT 'STREAMLIT', COUNT(*) FROM GN_DW.INFORMATION_SCHEMA.STREAMLITS;

