-- 실행 롤 = ACCOUNTADMIN(ACCOUNT_USAGE) · 작성 2026-10-20
-- ⚠️ ACCOUNT_USAGE 는 최대 45분~3시간 지연된다 — 방금 돌린 실행은 안 보일 수 있다.

-- Q01 Task 목록 (스케줄 · 상태 · 소유 · 선행)
SHOW TASKS IN DATABASE GN_DW;

-- Q02 Alert 목록 (스케줄 · 상태)
SHOW ALERTS IN DATABASE GN_DW;

-- Q03 dbt 실행 집계 — 최근 30일 (롤 · 명령 · 상태별 건수 · 평균/최대 초)
SELECT ROLE_NAME,
       REGEXP_SUBSTR(QUERY_TEXT, 'ARGS\\s*=\\s*''([a-z]+)', 1, 1, 'ie', 1) AS CMD,
       EXECUTION_STATUS, COUNT(*) AS N,
       ROUND(AVG(TOTAL_ELAPSED_TIME) / 1000) AS AVG_S, ROUND(MAX(TOTAL_ELAPSED_TIME) / 1000) AS MAX_S,
       MIN(START_TIME) AS FIRST_RUN, MAX(START_TIME) AS LAST_RUN
FROM SNOWFLAKE.ACCOUNT_USAGE.QUERY_HISTORY
WHERE START_TIME >= DATEADD(day, -30, CURRENT_TIMESTAMP())
  AND QUERY_TEXT ILIKE 'EXECUTE DBT PROJECT%'
GROUP BY 1, 2, 3
ORDER BY 1, 2, 3;

-- Q04 dbt build 실행별 (인자 · 소요 · WH 크기) — 전체 build 와 부분 build 를 가른다
SELECT START_TIME, ROLE_NAME, EXECUTION_STATUS, ROUND(TOTAL_ELAPSED_TIME / 1000) AS SEC, WAREHOUSE_NAME, WAREHOUSE_SIZE,
       SUBSTR(REGEXP_SUBSTR(QUERY_TEXT, 'ARGS\\s*=\\s*''[^'']*''', 1, 1, 'i'), 1, 200) AS ARGS
FROM SNOWFLAKE.ACCOUNT_USAGE.QUERY_HISTORY
WHERE START_TIME >= DATEADD(day, -30, CURRENT_TIMESTAMP())
  AND QUERY_TEXT ILIKE 'EXECUTE DBT PROJECT%'
  AND QUERY_TEXT ILIKE '%build%'
ORDER BY START_TIME;

-- Q05 Task 실행 이력 집계 — 최근 30일 (Task 별 건수 · 상태 · 평균/최대 초)
SELECT DATABASE_NAME, SCHEMA_NAME, NAME, STATE, COUNT(*) AS N,
       ROUND(AVG(DATEDIFF(second, QUERY_START_TIME, COMPLETED_TIME))) AS AVG_S,
       MAX(DATEDIFF(second, QUERY_START_TIME, COMPLETED_TIME)) AS MAX_S,
       MAX(SCHEDULED_TIME) AS LAST_SCHEDULED
FROM SNOWFLAKE.ACCOUNT_USAGE.TASK_HISTORY
WHERE SCHEDULED_TIME >= DATEADD(day, -30, CURRENT_TIMESTAMP())
  AND DATABASE_NAME = 'GN_DW'
GROUP BY 1, 2, 3, 4
ORDER BY 1, 2, 3, 4;

-- Q06 Alert 실행 이력 — 최근 6일 (상태 · 소요 · 🔴 함수 한도 「7일 이전 불가」라 -7 은 경계에서 실패 → -6)
SELECT NAME, STATE, SCHEDULED_TIME, COMPLETED_TIME,
       DATEDIFF(second, SCHEDULED_TIME, COMPLETED_TIME) AS SEC, SQL_ERROR_MESSAGE
FROM TABLE(GN_DW.INFORMATION_SCHEMA.ALERT_HISTORY(SCHEDULED_TIME_RANGE_START => DATEADD(day, -6, CURRENT_TIMESTAMP())::TIMESTAMP_LTZ))
ORDER BY SCHEDULED_TIME DESC;

-- Q07 MSTR 적재 월 1회분 소요 (🔴 BCHLOG.RUNKEY 가 전부 NULL 이라 실행 단위로 묶을 수 없다 ⇒
--     월마다 1행 남기는 USP_D_STRD_CAL_CD 의 연속 간격 = 월 1회분 소요(초)로 본다 · 마지막 달은 다음 행이 없어 제외)
WITH c AS (
    SELECT LOGTIME, LEAD(LOGTIME) OVER (ORDER BY LOGTIME) AS NEXT_T
    FROM GN_DW.MSTR.BCHLOG
    WHERE LOGPROC = 'USP_D_STRD_CAL_CD'
)
SELECT COUNT(*) AS N_MONTH_CYCLES, ROUND(AVG(DATEDIFF(second, LOGTIME, NEXT_T))) AS AVG_S,
       MAX(DATEDIFF(second, LOGTIME, NEXT_T)) AS MAX_S, MIN(LOGTIME) AS FIRST_T,
       (SELECT MAX(LOGTIME) FROM GN_DW.MSTR.BCHLOG) AS LAST_T,
       (SELECT COUNT(*) FROM GN_DW.MSTR.BCHLOG) AS N_LOG,
       (SELECT COUNT_IF(ERRNUM IS NOT NULL AND ERRNUM <> 0) FROM GN_DW.MSTR.BCHLOG) AS N_ERR,
       (SELECT COUNT_IF(RUNKEY IS NULL) FROM GN_DW.MSTR.BCHLOG) AS N_RUNKEY_NULL
FROM c
WHERE NEXT_T IS NOT NULL;

-- Q08 원천 객체 최종 변경 시각 (BRONZE 스키마별 · LAST_ALTERED = DDL·DML 포함 ⇒ 🔴 재구축·GRANT 로도 갱신되므로
--     「적재 시각」 근거로 쓰지 않는다 · 적재 신선도는 A6 Q09(_LOAD_DT) 가 정본)
SELECT TABLE_SCHEMA, COUNT(*) AS N_TABLES, MIN(LAST_ALTERED) AS OLDEST, MAX(LAST_ALTERED) AS NEWEST
FROM GN_DW.INFORMATION_SCHEMA.TABLES
WHERE TABLE_TYPE = 'BASE TABLE'
  AND (TABLE_SCHEMA LIKE 'BRONZE%' OR (TABLE_SCHEMA = 'SILVER' AND TABLE_NAME = 'BIGQUERY_REFINED_DATA'))
GROUP BY 1
ORDER BY 1;
