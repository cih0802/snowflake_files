-- §0 사전점검(읽기 전용) --------------------------------------------------------
-- 0-1 Agent 기본 버전(롤백 기준) — is_default = true 인 행의 name 을 런북 표에 적는다
SHOW VERSIONS IN AGENT GN_DW.SERVING.AGENT_MARKETING;
SHOW VERSIONS IN AGENT GN_DW.SERVING.AGENT_MEMBER;
SHOW VERSIONS IN AGENT GN_DW.SERVING.AGENT_EXECUTIVE;

-- 0-2 의존 객체 실재(4행 모두 1 이어야 진행)
SELECT 'ML_MEMBER_RISK_V' AS OBJ, COUNT(*) AS N FROM GN_DW.INFORMATION_SCHEMA.VIEWS
 WHERE TABLE_SCHEMA = 'SERVING' AND TABLE_NAME = 'ML_MEMBER_RISK_V'
UNION ALL
SELECT 'MSTR_SPNSR_DVLP_V', COUNT(*) FROM GN_DW.INFORMATION_SCHEMA.VIEWS
 WHERE TABLE_SCHEMA = 'SERVING' AND TABLE_NAME = 'MSTR_SPNSR_DVLP_V'
UNION ALL
SELECT 'SV_SPNSR_CLS_AGGR', COUNT(*) FROM GN_DW.INFORMATION_SCHEMA.SEMANTIC_VIEWS
 WHERE "SCHEMA" = 'SERVING' AND NAME = 'SV_SPNSR_CLS_AGGR'
UNION ALL
SELECT 'SV_MBRFEE_PRDT_ACTL', COUNT(*) FROM GN_DW.INFORMATION_SCHEMA.SEMANTIC_VIEWS
 WHERE "SCHEMA" = 'SERVING' AND NAME = 'SV_MBRFEE_PRDT_ACTL';

-- 0-3 SV_AD 에 GA 개발(건) 지표가 이미 있는가(1 = 재배포 불필요 · 0 = 05_07_SV_DDL_AD.sql 배포)
SELECT COUNT_IF(CONTAINS(GET_DDL('SEMANTIC_VIEW', 'GN_DW.SERVING.SV_AD'), 'GA_DEV_CNT')) AS HAS_GA_DEV_CNT;

-- 0-4 신규 객체 부재 확인(이미 있으면 재실행 = 덮어쓰기임을 인지)
SHOW CORTEX SEARCH SERVICES LIKE 'SEARCH_BIZ_DEFINITION' IN SCHEMA GN_DW.SERVING;
SHOW SEMANTIC VIEWS LIKE 'SV_ML_INC_CAMPAIGN' IN SCHEMA GN_DW.SERVING;

-- §1 사후검증 -------------------------------------------------------------------
-- 1-1 코퍼스 행수(개발계 ua91864 2026-10-13 = 2,145 · 라우팅 16 · 지표 236 · 용어 517 · 조직 222 · 원천참고 1,154)
SELECT DOC_TYPE, COUNT(*) AS N FROM GN_DW.SERVING.BIZ_DEFINITION_CORPUS GROUP BY DOC_TYPE ORDER BY DOC_TYPE;

-- 1-2 Search 1순위(기대 = RT-19 · RT-14)
SELECT 'Q_INC' AS Q, PARSE_JSON(SNOWFLAKE.CORTEX.SEARCH_PREVIEW('GN_DW.SERVING.SEARCH_BIZ_DEFINITION',
  '{"query":"10월 증액개발이 높을 것으로 보이는 마케팅캠페인 예측","columns":["DOC_ID"],"limit":1}')):results[0]:DOC_ID::STRING AS TOP1
UNION ALL
SELECT 'Q_LTV', PARSE_JSON(SNOWFLAKE.CORTEX.SEARCH_PREVIEW('GN_DW.SERVING.SEARCH_BIZ_DEFINITION',
  '{"query":"캠페인별 LTV 계산식","columns":["DOC_ID"],"limit":1}')):results[0]:DOC_ID::STRING;

-- 1-3 증액 예측 뷰 원천 대조(PRED = SRC_PRED · N_ROWS = PRED 이어야 한다)
SELECT v.STDR_MT, COUNT(*) AS N_ROWS, COUNT(DISTINCT v.MBER_NO) AS PRED, COUNT_IF(v.IS_LINKED) AS LINKED,
       (SELECT COUNT(DISTINCT r.MBER_NO) FROM GN_DW.SERVING.ML_MEMBER_RISK_V r
         WHERE r.HAS_INC_PRED AND r.STDR_MT = v.STDR_MT) AS SRC_PRED
FROM GN_DW.SERVING.ML_INC_BY_MKTG_CMPGN_V v
GROUP BY v.STDR_MT ORDER BY v.STDR_MT;

-- 1-4 SV 조회(개발계 기준월 202609 1위 = 가두캠페인 · 기대 증액 225.5명)
SELECT * FROM SEMANTIC_VIEW(GN_DW.SERVING.SV_ML_INC_CAMPAIGN
  DIMENSIONS ic.MK_CMPGN_NM
  METRICS ic.PREDICTED_MEMBERS, ic.EXPECTED_INC_MEMBERS, ic.AVG_INC_PROB
  WHERE ic.STDR_MT = (SELECT MAX(STDR_MT) FROM GN_DW.SERVING.ML_INC_BY_MKTG_CMPGN_V) AND ic.MK_CMPGN_NM IS NOT NULL)
ORDER BY EXPECTED_INC_MEMBERS DESC LIMIT 10;

-- 1-5 Agent 도구 수(기대 = MARKETING 24 · MEMBER 23 · EXECUTIVE 13 — 운영계 기존 도구 수 + 4 / +1 / +1)
SHOW VERSIONS IN AGENT GN_DW.SERVING.AGENT_MARKETING;

