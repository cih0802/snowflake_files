-- [2] 달력 파생 뷰 2종
CREATE OR REPLACE VIEW GN_DW.MSTR.D_STRD_DE_CD COMMENT = '기준일자. 9999-12-31 은 STRD_NM=N/A' AS
SELECT
  YMD                                            AS STRD_DE,
  CASE WHEN YMD = '99991231' THEN 'N/A'
       ELSE TO_CHAR(SYMD, 'YYYY-MM-DD') END      AS STRD_NM,
  TO_CHAR(DATEADD(DAY,   -1, SYMD), 'YYYYMMDD')  AS STRD_PRE_DE,
  TO_CHAR(DATEADD(MONTH, -1, SYMD), 'YYYYMMDD')  AS STRD_PRE_MT_DE,
  TO_CHAR(DATEADD(YEAR,  -1, SYMD), 'YYYYMMDD')  AS STRD_PRE_YMT_DE,
  LEFT(YMD, 6)                                   AS STRD_MT,
  QQ                                             AS STRD_QT,
  YY                                             AS STRD_YY,
  MM                                             AS MT_ID,
  TO_CHAR(CURRENT_DATE(), 'YYYYMMDD')            AS WORK_DE
FROM GN_DW.MSTR.D_STRD_CAL_CD;

CREATE OR REPLACE VIEW GN_DW.MSTR.D_STRD_MT_CD COMMENT = '기준년월' AS
SELECT DISTINCT
  LEFT(YMD, 6)                                          AS STRD_MT,
  TO_CHAR(SYMD, 'YYYY-MM')                              AS STRD_NM,
  TO_CHAR(DATEADD(MONTH, -1, SYMD), 'YYYYMM')           AS PRE_STRD_MT,
  TO_CHAR(DATEADD(YEAR,  -1, SYMD), 'YYYYMM')           AS PRE_YY_STRD_MT,
  YY                                                    AS STRD_YY,
  QQ                                                    AS STRD_QT,
  MM                                                    AS STRD_MM,
  TO_CHAR(DATEADD(YEAR, -1, SYMD), 'YYYY') || '12'      AS PRE_YY_12_MT,
  TO_CHAR(DATEADD(YEAR, -2, SYMD), 'YYYY') || '12'      AS PPRE_YY_12_MT
FROM GN_DW.MSTR.D_STRD_CAL_CD;

-- [3] 부서 계층 뷰 4종 (ACMSLT_UPPER_DEPT_ID 체인 · 루트 UPPER_DEPT_ID = ZV000000)
CREATE OR REPLACE VIEW GN_DW.MSTR.D_DEPT4_CD COMMENT = '본부/지부(4레벨)' AS
SELECT
  B.DEPT_ID AS DEPT4_ID, B.DEPT_NM AS DEPT4_NM, A.DEPT_ID AS DEPT5_ID,
  B.SORT_ORDR, B.USE_YN, B.ACMSLT_DEPT_YN,
  IFNULL(TO_CHAR(B.FRST_REGIST_DT, 'YYYYMMDD'), '19000101') AS FST_DE,
  IFNULL(TO_CHAR(B.LAST_UPDT_DT,   'YYYYMMDD'), '99991231') AS LST_DE,
  TO_CHAR(CURRENT_DATE(), 'YYYYMMDD') AS WORK_DE
FROM GN_DW.MSTR.D_CM_DEPT_INFO A
JOIN GN_DW.MSTR.D_CM_DEPT_INFO B ON B.ACMSLT_UPPER_DEPT_ID = A.DEPT_ID
WHERE A.UPPER_DEPT_ID = 'ZV000000'
  AND A.USE_YN = 'Y'
UNION ALL
SELECT 'Z~', '없음', 'Z~', 999, 'Y', 'Y', '20191101', '99991231', TO_CHAR(CURRENT_DATE(), 'YYYYMMDD');

