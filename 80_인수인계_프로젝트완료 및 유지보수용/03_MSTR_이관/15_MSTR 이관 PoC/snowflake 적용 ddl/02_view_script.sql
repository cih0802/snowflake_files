-- [4] 상위캠페인
CREATE OR REPLACE VIEW GN_DW.MSTR.D_UP_CMPGN_CD COMMENT = '상위캠페인(UPPER_CMPGN_YN=Y) + 없음' AS
SELECT
  CMPGN_CD AS UPPER_CMPGN_CD,
  CMPGN_NM AS UPPER_CMPGN_NM,
  ROW_NUMBER() OVER (ORDER BY CMPGN_CD) AS SORT_ORDR,
  USE_YN
FROM GN_DW.MSTR.D_CMPGN_CD
WHERE UPPER_CMPGN_YN = 'Y'
UNION ALL
SELECT 'Z~', '없음', 99999, 'Y';

-- [5] 후원사업 원장 뷰 (BRONZE 직접 참조 · 함수 2종이 사용)
CREATE OR REPLACE VIEW GN_DW.MSTR.D_SPNSR_BSNS_V COMMENT = '후원·후원사업 결합. DSC_DE 미중단 = 99991231' AS
SELECT
  TO_CHAR(A.FRST_REGIST_DT, 'YYYYMM')   AS STRD_MT,
  A.SPNSR_NO,
  B.SPNSR_BSNS_NO,
  B.SPNSR_BSNS_ID,
  A.MBER_NO,
  A.CMPGN_CD,
  A.ACMSLT_DEPT_CD,
  A.JOIN_PATH_CD,
  A.FRST_RGSTR_ID,
  TO_CHAR(A.FRST_REGIST_DT, 'YYYYMMDD') AS FST_DE,
  B.SPNSR_AMT,
  IFNULL(B.SPNSR_DSCNTC_DE, '99991231') AS DSC_DE,
  B.SPNSR_DSCNTC_YN,
  B.SPNSR_DSCNTC_RSN_CD
FROM GN_DW.BRONZE_CRM.TM_MM_FDRM_MBER_SPNSR A
JOIN GN_DW.BRONZE_CRM.TM_MM_FDRM_MBER_SPNSR_BSNS B
  ON A.SPNSR_NO = B.SPNSR_NO;
