CREATE FUNCTION [dbo].[FN_MM_ACT_DATE]
(
	@STRD_MT 		AS CHAR(6)
)
RETURNS TABLE
AS 
RETURN 
(
SELECT t1.MBER_NO, t1.STDR_DE, t1.FRST_REGIST_DT, SPNSR_DSCNTC_DE, t2.RE_SPNSR_DE, actualdt FROM
			MSTR_ODS.DBO.TM_MM_FDRM_MBER_INFO t1
			INNER JOIN (SELECT DISTINCT MBER_NO FROM MART.D_SPNSR_BSNS_V WHERE FST_DE <= @STRD_MT + '31' AND ( DSC_DE IS NULL OR DSC_DE > @STRD_MT + '31')) t3 ON t1.MBER_NO = t3.MBER_NO
			LEFT OUTER JOIN
			(
				SELECT t1.MBER_NO, t1.SPNSR_DSCNTC_DE, t2.RE_SPNSR_DE,
					CASE WHEN RE_SPNSR_DE IS NULL THEN DateAdd(d, -1, SPNSR_DSCNTC_DE)
						ELSE
							CASE
								WHEN SPNSR_DSCNTC_DE > RE_SPNSR_DE THEN DateAdd(d, -1, SPNSR_DSCNTC_DE) ELSE
								
								CASE WHEN RE_SPNSR_DE < DATEADD( DD, -1, DATEADD(MM, 1,CONVERT( DATE,@STRD_MT + '01'))) THEN DATEADD( DD, -1, DATEADD(MM, 1,CONVERT( DATE,@STRD_MT + '01'))) ELSE RE_SPNSR_DE END
							END
					END AS actualdt
				FROM
				(
					SELECT MBER_NO, SPNSR_DSCNTC_DE
					FROM
					(
					SELECT *, ROW_NUMBER() OVER(PARTITION BY MBER_NO ORDER BY SPNSR_DSCNTC_DE DESC) AS rnum FROM MSTR_ODS.DBO.TM_MM_FDRM_MBER_SPNSR_DSCNTC WHERE SPNSR_DSCNTC_DE <= @STRD_MT + '31'
					) t1
					WHERE t1.rnum = 1
				) t1
				LEFT OUTER JOIN 
				(
					SELECT MBER_NO, RE_SPNSR_DE
					FROM
					(
					SELECT *, ROW_NUMBER() OVER(PARTITION BY MBER_NO ORDER BY RE_SPNSR_DE DESC) AS rnum FROM MSTR_ODS.DBO.TM_MM_FDRM_MBER_RE_SPNSR WHERE RE_SPNSR_DE <= @STRD_MT + '31'
					) t1
					WHERE t1.rnum = 1
				) t2
				ON t1.MBER_NO = t2.MBER_NO
			) t2 ON t1.MBER_NO = t2.MBER_NO
		WHERE DATEADD( DD, -1, DATEADD(MM, 1,CONVERT( DATE,@STRD_MT + '01'))) BETWEEN CONVERT(DATE,FRST_REGIST_DT) AND CONVERT(DATE, ISNULL(actualdt,'9999-12-31'))
 )
GO

