-- 월마감 이후 실행 프로시져
CREATE OR REPLACE PROCEDURE GN_DW.BRONZE_CRM.SP_EXEC_MONTH_END(P_STDR_MT VARCHAR)
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS CALLER
AS  
BEGIN
    -- 변수 선언
    LET V_STDR_MT VARCHAR := COALESCE(P_STDR_MT, TO_CHAR(DATEADD(MONTH, -1, CURRENT_DATE()), 'YYYYMM'));
    LET V_START_TIME TIMESTAMP_NTZ := CURRENT_TIMESTAMP();
    LET V_PROC_NAME VARCHAR := 'SP_EXEC_MONTH_END';
    -- 인입쿼리 시작
    -- 머신러닝 데이터셋 구성
    CALL GN_DW.ML.SP_INSERT_ML_DATASET_MONTHLY_DEV_AMT(:V_STDR_MT);
    CALL GN_DW.ML.SP_INSERT_ML_DATASET_CMPGN_MBER_SNAPSHOT(:V_STDR_MT);
    CALL GN_DW.ML.SP_INSERT_ML_DATASET_MBER_SERVICE_INFO(:V_STDR_MT);
    CALL GN_DW.ML.SP_INSERT_ML_DATASET_MBRFEE_PAY_DTLS(:V_STDR_MT);
    CALL GN_DW.ML.SP_INSERT_ML_DATASET_MBER_MONTHLY_INFO(:V_STDR_MT);
    CALL GN_DW.ML.SP_INSERT_ML_DATASET_MBER_MONTHLY_SETLE_INFO(:V_STDR_MT);
    CALL GN_DW.ML.SP_INSERT_ML_DATASET_SNPSR_BSNS_NO_DSCNT_ML_DATA(:V_STDR_MT);
    CALL GN_DW.ML.SP_INSERT_ML_DATASET_CMPGN_MONTHLY_SNAPSHOT(:V_STDR_MT);
    CALL GN_DW.ML.SP_INSERT_ML_DATASET_MBER_MONTHLY_SNAPSHOT(:V_STDR_MT);
    -- 머신러닝 학습
    -- 회원실 5개
    CALL GN_DW.ML.SP_SPNSR_CHURN_12M_PREDICT(:V_STDR_MT);
    CALL GN_DW.ML.SP_MBER_CHURN_6M_PREDICT(:V_STDR_MT);
    CALL GN_DW.ML.SP_CMPGN_CTGR_AMT_FORECAST(:V_STDR_MT);
    CALL GN_DW.ML.SP_MBER_INC_12M_PREDICT(:V_STDR_MT);
    CALL GN_DW.ML.SP_LOYAL_MBER_PREDICT(:V_STDR_MT);
    -- 나마본 7개
    CALL GN_DW.ML.SP_MONTHLY_DVLP_AMT_FORECAST(:V_STDR_MT); 
    CALL GN_DW.ML.SP_MONTHLY_CMPGN_DVLP_AMT_FORECAST(:V_STDR_MT);
    CALL GN_DW.ML.SP_DVLP_INC_CONTRIBUTION(:V_STDR_MT);
    CALL GN_DW.ML.SP_ONCE_TO_FDRM_CONVERSION_6M(:V_STDR_MT);
    CALL GN_DW.ML.SP_MKTG_CHANNEL_MBER_AVG_LTV_FORECAST(:V_STDR_MT);
    CALL GN_DW.ML.SP_CMPGN_SPNSR_AMT_LTV_FORECAST(:V_STDR_MT);
    CALL GN_DW.ML.SP_CHANNEL_NEW_DVLP_CONTRIBUTION(:V_STDR_MT); 
    
    -- 기존 예측 프로세스 치 자동화
    -- 기획실
    CALL GN_DW.SILVER.SP_ANNUAL_DVLP_GOAL_ACMSLT_AGGR_DATA1(:V_STDR_MT); 
    CALL GN_DW.SILVER.SP_ANNUAL_DVLP_GOAL_ACMSLT_AGGR_DATA2(:V_STDR_MT);
    -- 회원실
    CALL GN_DW.SILVER.SP_INSERT_MM_SPNSR_CLS_AGGR_DATA1(:V_STDR_MT);
    CALL GN_DW.SILVER.SP_INSERT_MM_SPNSR_CLS_AGGR_DATA2(:V_STDR_MT);
    CALL GN_DW.SILVER.SP_INSERT_MM_SPNSR_CLS_AGGR_DATA3(:V_STDR_MT);
    CALL GN_DW.SILVER.SP_INSERT_MM_SPNSR_CLS_AGGR_DATA4(:V_STDR_MT);
    CALL GN_DW.SILVER.SP_INSERT_MM_SPNSR_CLS_AGGR_DATA5(:V_STDR_MT);
    CALL GN_DW.SILVER.SP_RECALC_ANNUAL_MBRFEE_PRDT_ACTL_DATA(:V_STDR_MT);
    -- 성공 로그 기록
    INSERT INTO GN_DW.ML.ML_PROCEDURE_LOG (PROC_NAME, STDR_MT, START_TIME, END_TIME, DURATION_SEC, STATUS, ERROR_MSG)
    SELECT 
        :V_PROC_NAME,
        :V_STDR_MT,
        :V_START_TIME,
        CURRENT_TIMESTAMP(),
        DATEDIFF('SECOND', :V_START_TIME, CURRENT_TIMESTAMP()),
        'SUCCESS',
        NULL;
    RETURN 'SUCCESS: STDR_MT=' || :V_STDR_MT;
EXCEPTION
    WHEN OTHER THEN
        LET V_ERR_MSG VARCHAR := SQLERRM;
        -- 실패 로그 기록
        INSERT INTO GN_DW.ML.ML_PROCEDURE_LOG (PROC_NAME, STDR_MT, START_TIME, END_TIME, DURATION_SEC, STATUS, ERROR_MSG)
        SELECT 
            :V_PROC_NAME,
            :V_STDR_MT,
            :V_START_TIME,
            CURRENT_TIMESTAMP(),
            DATEDIFF('SECOND', :V_START_TIME, CURRENT_TIMESTAMP()),
            'FAILED',
            :V_ERR_MSG;

        RETURN 'FAILED: ' || :V_ERR_MSG;
END;
